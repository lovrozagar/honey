/**
 * The Python SDK (bit 14): a package emitted from the IR alone (H2), in the src layout: `pyproject.toml`,
 * `src/<pkg>/types.py` (every component, then every hoisted declaration, in name order, then the `ErrorKey`
 * StrEnum when the API declares error keys), `client.py` (the
 * resource classes and the `SDK` and `AsyncSDK` clients), `__init__.py` (the package root's exports), an empty
 * `py.typed`, and the vendored runtime under `_honey/`. Every `.py` file and the manifest carry the marker.
 */
import { type OpenApiDocument, toIR } from "../../ir/build.ts"
import type { IR, IRSchema } from "../../ir/model.ts"
import { sdkModel } from "../../ir/sdk-model.ts"
import { pyDocLines } from "../shared/escape.ts"
import { compareCodeUnits, NameScope } from "../shared/lang.ts"
import { pythonErrorKeys } from "./errors.ts"
import { type ClientEnv, clientDecls, clientTitle } from "./sdk-client.ts"
import { allOrder, importBlock, importLine } from "./sdk-imports.ts"
import type { PythonCallPlan } from "./sdk-plan.ts"
import { pyproject, validatePackageName, validateVersion } from "./sdk-pyproject.ts"
import { needsWebSocket, runtimeExports, runtimeFiles } from "./transport.ts"
import { type PyTypeContext, pyTopLevel, pyTypeContext } from "./types.ts"

export type PythonSdkOptions = {
	/** the import name; `honey_sdk` by default, its distribution name with `-` for `_` */
	readonly packageName?: string
	/** the package version; `0.1.0` by default */
	readonly version?: string
	/** false: each non-stream method returns an `SDKResult` instead of raising an error status; true by default */
	readonly throwOnError?: boolean
}

export type GeneratedPythonSdk = { readonly files: Readonly<Record<string, string>> }

/* the marker ruff, mypy and linguist read */
const MARKER = "# @generated by honey. DO NOT EDIT."

/* where client.py imports each runtime name from, under `._honey.` */
const RUNTIME: Readonly<Record<string, string>> = {
	AsyncRealtimeTransport: "realtime",
	AsyncTransport: "send_async",
	AsyncWsTransport: "ws",
	ClientConfig: "config",
	Defaults: "config",
	EventStream: "events",
	Operation: "operation",
	RequestOptions: "config",
	ResumableConnection: "realtime",
	SDKResult: "result",
	SyncTransport: "send_sync",
	TypedWebSocket: "ws",
}

/** A docstring of `lines` at column 0: one line, or the first on the quotes and the closing quotes alone. */
const docstring = (lines: readonly string[]) =>
	lines.length === 1 ? [`"""${lines[0]}"""`] : [`"""${lines[0]}`, ...lines.slice(1), '"""']

/** The blank lines before a module's `i`th declaration: one after the imports unless it is a class, else two. */
const gap = (decl: string, i: number) => (i === 0 && !decl.startsWith("class ") ? [""] : ["", ""])

/** A module: the marker, its docstring, its imports (every module has one), then its declarations two blank lines
 * apart, one after the imports when the first is no class (isort's spacing). */
function pyFile(doc: readonly string[], imports: readonly (readonly string[])[], decls: readonly string[]): string {
	const head = [MARKER, ...docstring(doc), "", ...importBlock(imports)]
	return [...head, ...decls.flatMap((decl, i) => [...gap(decl, i), decl]), ""].join("\n")
}

/** Each component's declaration in code-unit order, its description as its docstring: [name, text]. */
function componentDecls(ir: IR, at: PyTypeContext): [string, string][] {
	return Object.keys(ir.schemas)
		.sort(compareCodeUnits)
		.map((name) => {
			const claimed = at.names.ref(name)
			return [claimed, pyTopLevel(claimed, ir.schemas[name] as IRSchema, at, ir.schemaDescriptions[name])]
		})
}

/** The identifiers `text` spells outside its strings. */
const spelled = (text: string) =>
	new Set(
		Array.from(
			text.replace(/"""[\s\S]*?"""|"(?:[^"\\\n]|\\.)*"/g, '""').matchAll(/[A-Za-z_]\w*/g),
			(match) => match[0],
		),
	)

/** client.py: the marker, the API's doc, its imports, then its declarations. */
function clientFile(
	ir: IR,
	env: ClientEnv,
	body: { readonly lines: readonly string[]; readonly types: readonly string[] },
) {
	const doc = pyDocLines([clientTitle(ir), ir.info.description].filter((part) => part !== undefined).join("\n\n"))
	const used = spelled(body.lines.join("\n"))
	const honey = new Map<string, string[]>()
	for (const name of ["ClientConfig", "Defaults", "SyncTransport", env.transport, ...env.imports].filter(
		(n) => n in RUNTIME,
	))
		honey.set(RUNTIME[name] as string, [...(honey.get(RUNTIME[name] as string) ?? []), name])
	const sections = [
		["from __future__ import annotations"],
		[
			...(env.imports.has("builtins") ? ["import builtins"] : []),
			...importLine(
				"collections.abc",
				[...env.imports].filter((name) => !(name in RUNTIME) && name !== "builtins"),
			),
			...importLine("typing", [...env.at.typing, "Self"]),
		],
		[
			...[...honey.keys()]
				.sort(compareCodeUnits)
				.flatMap((module) => importLine(`._honey.${module}`, honey.get(module) as string[])),
			...importLine(
				".types",
				body.types.filter((name) => used.has(name)),
			),
		],
	]
	return pyFile(doc, sections, [body.lines.join("\n")])
}

/** __init__.py: each runtime module's exports, the clients, every type; all of them in `__all__`. */
function initFile(ir: IR, runtime: Readonly<Record<string, string>>, types: readonly string[]) {
	const modules = Object.entries(runtime).map(
		([file, source]) => [file.replace(/\.py$/, ""), runtimeExports(source)] as const,
	)
	const lines = [
		...modules.flatMap(([module, names]) => importLine(`._honey.${module}`, names)),
		...importLine(".client", ["SDK", "AsyncSDK"]),
		...importLine(".types", types),
	]
	const all = allOrder([...modules.flatMap(([, names]) => names), "SDK", "AsyncSDK", ...types])
	return pyFile([clientTitle(ir)], [lines], [`__all__ = [${all.map((name) => `"${name}"`).join(", ")}]`])
}

/** The package's files for `document`, and the call plan of every method in them. */
function emitPython(document: Record<string, unknown>, options: PythonSdkOptions) {
	const pkg = {
		name: validatePackageName(options.packageName ?? "honey_sdk"),
		version: validateVersion(options.version ?? "0.1.0"),
	}
	const ir = toIR(document as OpenApiDocument, { deriveOperationIds: true })
	const model = sdkModel(ir)
	const at = pyTypeContext(ir)
	/* components first: the client's hoisted types then land beside them */
	const components = componentDecls(ir, at)
	/* before the client: its `_DEFAULTS` names ErrorKey, and each `<Key>Data` lands among the hoisted declarations */
	const errorKey = pythonErrorKeys(model, at)
	const features = {
		realtime: model.ops.some((op) => op.stream === "realtime"),
		ws: model.ops.some((op) => op.stream === "ws"),
	}
	const transport = features.realtime ? "AsyncRealtimeTransport" : features.ws ? "AsyncWsTransport" : "AsyncTransport"
	const env: ClientEnv = {
		at: { ...at, declTyping: at.typing, typing: new Set() },
		constants: new NameScope(),
		imports: new Set(),
		keyed: errorKey !== null,
		ops: model.opsById,
		throwOnError: options.throwOnError ?? true,
		transport,
		typesImports: new Set(),
	}
	const client = clientDecls(ir, env)
	const hoisted = [...at.decls].sort(([a], [b]) => compareCodeUnits(a, b))
	const decls = [...components, ...hoisted, ...(errorKey === null ? [] : [["ErrorKey", errorKey] as [string, string]])]
	const types = decls.map(([name]) => name)
	const runtime = runtimeFiles(features)
	const typesDoc = pyDocLines(ir.info.title === undefined ? "The API's types." : `The ${ir.info.title} API's types.`)
	const root = `src/${pkg.name}`
	const files: Record<string, string> = {
		"pyproject.toml": pyproject(pkg, needsWebSocket(features)),
		[`${root}/__init__.py`]: initFile(ir, runtime, types),
		[`${root}/client.py`]: clientFile(ir, env, { lines: client.lines, types }),
		[`${root}/py.typed`]: "",
		[`${root}/types.py`]: pyFile(
			[typesDoc[0] as string],
			[
				["from __future__ import annotations"],
				[...(errorKey === null ? [] : ["from enum import StrEnum"]), ...importLine("typing", at.typing)],
				importLine("._honey.body", env.typesImports),
			],
			decls.map(([, text]) => text),
		),
		...Object.fromEntries(Object.entries(runtime).map(([name, source]) => [`${root}/_honey/${name}`, source])),
	}
	const sorted = Object.fromEntries(Object.entries(files).sort(([a], [b]) => compareCodeUnits(a, b)))
	return { files: sorted, plans: client.plans }
}

/** The package's files for `document`, by path. */
export function generatePythonSdk(
	document: Record<string, unknown>,
	options: PythonSdkOptions = {},
): GeneratedPythonSdk {
	return { files: emitPython(document, options).files }
}

/**
 * Each operation's call plan by id, from the very emit `generatePythonSdk` runs with these options: the names
 * the fixed reflection driver walks (G17), never re-derived outside the emitter.
 */
export function pythonCallPlans(
	document: Record<string, unknown>,
	options: PythonSdkOptions = {},
): Readonly<Record<string, PythonCallPlan>> {
	return Object.fromEntries(emitPython(document, options).plans.map((plan) => [plan.operation, plan]))
}
