/** The vendored runtime's files by class name, read from disk on every call, in `packageName`; every file by default. */
export function runtimeFiles(
	packageName: string,
	features: JavaRuntimeFeatures = {
		json: true,
		opt: true,
		operations: true,
		realtime: true,
		transport: true,
		ws: true,
	},
): Record<string, string> {
	const names = [
		...(features.json ? ["Json"] : []),
		...(features.opt ? ["Opt"] : []),
		...(features.transport ? ["Transport"] : []),
		...(features.operations ? [...OPERATION_FILES, ...STALE_FILES, ...SSE_FILES] : []),
		...(features.ws ? WS_FILES : []),
		...(features.realtime ? REALTIME_FILES : []),
	]
	return Object.fromEntries(
		names.map((name) => [
			name,
			readFileSync(new URL(`../../runtime/java/${name}.java`, import.meta.url), "utf8").replace(
				RUNTIME_PACKAGE,
				() => `package ${packageName};`,
			),
		]),
	)
}

/** The exchange's stale tracking, shipped with every exchange: the tracker, its config and the read's view. */
const STALE_FILES = ["InvalidationConfig", "StaleMeta", "StaleTracker"]

/** The package's files for `document`, by path, in code-unit order. */
export function generateJavaSdk(document: Record<string, unknown>, options: JavaSdkOptions = {}): GeneratedJavaSdk {
	const { files, notices } = emitJava(document, options)
	return { files, notices }
}

/**
 * Each operation's call plan by id, from the very emit `generateJavaSdk` runs with these options: the names the fixed
 * reflection driver walks, never re-derived outside the emitter.
 */
export function javaCallPlans(
	document: Record<string, unknown>,
	options: JavaSdkOptions = {},
): Readonly<Record<string, JavaCallPlan>> {
	return Object.fromEntries(emitJava(document, options).plans.map((plan) => [plan.operation, plan]))
}

/** The runtime files an SDK of `ops` and the component declarations `decls` ships. */
function featuresOf(ops: readonly SdkOp[], decls: ReadonlyMap<string, string>): JavaRuntimeFeatures {
	const operations = ops.length > 0
	return {
		json: decls.size > 0 || operations,
		operations,
		opt: [...decls.values()].some((decl) => /\bOpt</.test(decl)) || operations,
		realtime: ops.some((op) => op.stream === "realtime"),
		transport: !operations,
		ws: ops.some((op) => op.stream === "ws" || op.stream === "realtime"),
	}
}

/** The package's files and the call plans, from one emit. */
function emitJava(document: Record<string, unknown>, options: JavaSdkOptions) {
	const pkg = packageOf(options)
	const dir = `src/main/java/${pkg.packageName.replaceAll(".", "/")}`
	/* an operation without an operationId is named by the IR's derivation, as every sibling emitter asks */
	const ir = toIR(document as OpenApiDocument, { deriveOperationIds: true })
	const model = sdkModel(ir)
	const ctx = javaTypeContext(ir, [pkg.clientName])
	const isArray = (schema: Parameters<typeof model.resolve>[0]) => model.resolve(schema).kind === "array"
	const operations = model.ops.length > 0
	const env: SurfaceEnv = {
		client: pkg.clientName,
		ctx,
		isArray,
		marker: MARKER,
		notices: [],
		ops: model.opsById,
		packageName: pkg.packageName,
	}
	const surface = operations ? surfaceOf(ir, env) : { files: {}, plans: [] as JavaCallPlan[] }
	const errors = operations
		? {
				...errorClassFiles(dir, pkg.packageName, MARKER),
				...errorKeyFiles(model, ctx, { dir, marker: MARKER, packageName: pkg.packageName }),
			}
		: {}
	const decls = componentDecls(ir, ctx)
	/* the mirror's names are claimed last, after every normal one (the components' own hoists included) */
	const mirror = operations ? mirrorOf(ir, env) : {}
	const runtime = Object.entries(runtimeFiles(pkg.packageName, featuresOf(model.ops, decls))).map(
		([name, text]): [string, string] => [`${dir}/${name}.java`, text],
	)
	const client = operations ? mirror[`${pkg.clientName}.java`] : `${MARKER}\n${clientJava(pkg)}`
	const entries: [string, string][] = [
		["build.gradle", `${MARKER}\n${buildGradle(pkg, { description: ir.info.description, name: ir.info.title })}`],
		["settings.gradle", `${MARKER}\n${settingsGradle(pkg)}`],
		[`${dir}/${pkg.clientName}.java`, client as string],
		...runtime,
		...Object.entries(modelFiles(decls, { dir, marker: MARKER, packageName: pkg.packageName })),
		...Object.entries(errors),
		...Object.entries({ ...surface.files, ...mirror })
			.filter(([name]) => name !== `${pkg.clientName}.java`)
			.map(([name, text]): [string, string] => [`${dir}/${name}`, text]),
	]
	/* one declaration per file: a second claim of a path throws, never overwrites */
	const files: Record<string, string> = {}
	for (const [path, text] of entries) putFile(files, path, text)
	const renamed = ctx.names.renamed.map((rename) => renameNotice("java", rename))
	return {
		files: Object.fromEntries(Object.entries(files).sort(([a], [b]) => compareCodeUnits(a, b))),
		notices: [...new Set([...env.notices, ...renamed])],
		plans: surface.plans,
	}
}
