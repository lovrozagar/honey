/**
 * The package manifest (Fb2, Fb3): `pyproject.toml` with the generated marker, hatchling over the src
 * layout, `requires-python` and the one httpx2 dependency. No spec text reaches it; the run's metadata block does
 * (plan 39 8.4), each value already held to its grammar (no control character), and lands as a TOML basic string,
 * whose escapes JSON's are. The package name and version are validated before anything is emitted.
 */
import { issuesUrl, type Metadata, personOf } from "../shared/metadata.ts"

/** The `requires-python` every emitted package declares: the floor CI installs (PY_FLOOR). */
export const PYTHON_REQUIRES = ">=3.11"

/**
 * The trove classifiers every package carries: the Python versions from that floor to the one `.python-version` pins,
 * which sdk-pyproject.test holds them to, and typed (PEP 561); no `License ::` (PEP 639).
 */
export const PYTHON_CLASSIFIERS: readonly string[] = [
	"Programming Language :: Python :: 3",
	"Programming Language :: Python :: 3 :: Only",
	"Programming Language :: Python :: 3.11",
	"Programming Language :: Python :: 3.12",
	"Programming Language :: Python :: 3.13",
	"Programming Language :: Python :: 3.14",
	"Typing :: Typed",
]

/* honey's own record of what it wrote (gen/write.ts MANIFEST), which no sdist ships */
const MANIFEST = ".honey-generated.json"

/** The lowest httpx2 every emitted package accepts. */
export const HTTPX2_FLOOR = "2.12.0"

/** The dependency string every emitted package declares (`httpx2[ws]` when it needs WebSockets). */
export const HTTPX2 = `httpx2>=${HTTPX2_FLOOR},<3`

/* the hard keywords and the soft ones, none an import name */
const KEYWORDS =
	" False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield match case type _ "

/** `name` when it is an import name a package may take: lower snake case, no keyword, not the runtime's. */
export function validatePackageName(name: string): string {
	if (!/^[a-z][a-z0-9_]*$/.test(name) || KEYWORDS.includes(` ${name} `) || name === "_honey") {
		throw new Error(`Invalid package name: "${name}"`)
	}
	return name
}

/** `version` when it is in PEP 440's release, pre, post and dev subset. */
export function validateVersion(version: string): string {
	if (!/^\d+(\.\d+)*((a|b|rc)\d+)?(\.post\d+)?(\.dev\d+)?$/.test(version)) {
		throw new Error(`Invalid version: "${version}"`)
	}
	return version
}

/** A TOML basic string of `text`. */
const toml = (text: string) => JSON.stringify(text)

/** One author as PEP 621's inline table: its name, and its email when given. */
function authorTable(author: string): string {
	if (!author.endsWith(">")) return `{ name = ${toml(author)} }`
	const { email, name } = personOf(author)
	return `{ name = ${toml(name)}, email = ${toml(email)} }`
}

/** The `[project]` lines the metadata block fills, each only when given, in PEP 621's order. */
function described(metadata: Metadata): string[] {
	const { authors, description, keywords, license } = metadata
	return [
		...(description === undefined ? [] : [`description = ${toml(description)}`]),
		`requires-python = "${PYTHON_REQUIRES}"`,
		...(license === undefined ? [] : [`license = ${toml(license)}`]),
		...(authors === undefined ? [] : [`authors = [${authors.map(authorTable).join(", ")}]`]),
		...(keywords === undefined ? [] : [`keywords = [${keywords.map(toml).join(", ")}]`]),
	]
}

/** `[project.urls]` under the well-known labels PyPI shows, or nothing when the block gives no URL. */
function urls(metadata: Metadata): string[] {
	const { changelog, documentation, homepage, repository } = metadata
	const labeled = [
		["Homepage", homepage],
		["Source", repository],
		["Issues", repository === undefined ? undefined : issuesUrl(repository)],
		["Documentation", documentation],
		["Changelog", changelog],
	].filter((entry): entry is [string, string] => entry[1] !== undefined)
	return labeled.length === 0 ? [] : ["[project.urls]", ...labeled.map(([label, url]) => `${label} = ${toml(url)}`), ""]
}

/** The manifest of package `pkg` (its import name; the distribution name has `-` for `_`). */
export function pyproject(
	pkg: { readonly name: string; readonly version: string },
	ws: boolean,
	metadata: Metadata = {},
): string {
	const dependency = ws ? HTTPX2.replace("httpx2", "httpx2[ws]") : HTTPX2
	return [
		"# @generated by honey. DO NOT EDIT.",
		"[build-system]",
		'requires = ["hatchling>=1.27"]',
		'build-backend = "hatchling.build"',
		"",
		"[project]",
		`name = "${pkg.name.replaceAll("_", "-")}"`,
		`version = "${pkg.version}"`,
		...described(metadata),
		`classifiers = [${PYTHON_CLASSIFIERS.map(toml).join(", ")}]`,
		`dependencies = ["${dependency}"]`,
		"",
		...urls(metadata),
		"[tool.hatch.build.targets.sdist]",
		`exclude = ["${MANIFEST}"]`,
		"",
		"[tool.hatch.build.targets.wheel]",
		`packages = ["src/${pkg.name}"]`,
		"",
	].join("\n")
}
