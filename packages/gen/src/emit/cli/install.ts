/**
 * The CLI's install scripts (bit 17 phase g): `install.sh` (Linux and macOS, POSIX sh) and `install.ps1` (Windows).
 * Each picks the archive for this OS and architecture (`<PREFIX>_INSTALL_ARCH` over it), downloads it and
 * `checksums.txt` from the release (the repository's GitHub Releases, a tag by `<PREFIX>_VERSION`, else the latest;
 * `<PREFIX>_INSTALL_BASE` over it, required with no repository), verifies the archive's sha256 against
 * `checksums.txt` before anything installs, and installs the binary to `<PREFIX>_INSTALL_DIR` or its default. Each is
 * hardened for a `curl | sh`:
 * - the whole body is one function called on the last line, so a truncated download runs nothing;
 * - the base is https://, or http:// on loopback (127.0.0.0/8, ::1, localhost) alone, refused before any fetch;
 * - curl runs with `--proto` and `--tlsv1.2`, wget with `--https-only`, and neither is a refusal;
 * - `set -eu`, a trap that removes the temp dir, no `eval`;
 * - a refusal is one line on stderr and a nonzero exit.
 * Every value they hold is a validated option (the binary, the repository, the variables' prefix), each a
 * single-quoted literal; no spec text reaches them.
 */
/* the marker a generated script carries on its first lines */
const MARKER = "Code generated by honey. DO NOT EDIT."

/** The options a script is written from: the binary, its repository (none when unset), the variables' prefix. */
export type InstallApp = { readonly bin: string; readonly repo: string | undefined; readonly prefix: string }

/** install.sh's head: the shebang, the marker, what it does and reads, `set -eu`, and `fail`. */
const shHead = ({ bin, prefix }: InstallApp) => {
	const v = (name: string) => `${prefix}_${name}`
	return `#!/bin/sh
# ${MARKER}
# Installs ${bin} on Linux or macOS: the archive for this OS and architecture, its sha256 checked against
# checksums.txt before anything installs. The script is one function called on its last line, so a truncated
# download runs nothing.
#   ${v("VERSION")}       a release tag (default: the latest)
#   ${v("INSTALL_BASE")}  where the release's files are: https://, or http:// on loopback
#   ${v("INSTALL_DIR")}   where ${bin} goes (default: ~/.local/bin)
#   ${v("INSTALL_ARCH")}  amd64 or arm64, over this machine's
set -eu

fail() {
	echo "${bin} install: $1" >&2
	exit 1
}

`
}

/** install.sh's download and digest helpers. */
const SH_TOOLS = `# fetch <url> <file>: curl or wget, held to https (or http on a loopback base)
fetch() {
	if command -v curl >/dev/null 2>&1; then
		curl --proto "$proto" --tlsv1.2 -fsSL -o "$2" "$1" || fail "could not download $1"
	elif command -v wget >/dev/null 2>&1; then
		if [ "$proto" = "=https" ]; then
			wget --https-only -q -O "$2" "$1" || fail "could not download $1"
		else
			wget -q -O "$2" "$1" || fail "could not download $1"
		fi
	else
		fail "neither curl nor wget is installed"
	fi
}

# sha256 <file>: its digest, by sha256sum or shasum
sha256() {
	if command -v sha256sum >/dev/null 2>&1; then
		sha256sum "$1" | awk '{ print $1 }'
	elif command -v shasum >/dev/null 2>&1; then
		shasum -a 256 "$1" | awk '{ print $1 }'
	else
		fail "neither sha256sum nor shasum is installed to verify the download"
	fi
}

`

/** install.sh's base: the release's location, its protocol checked before any fetch. */
const shBase = ({ prefix }: InstallApp) => {
	const v = (name: string) => `${prefix}_${name}`
	return `# resolve_base: where the release's files are, its protocol checked before any fetch
resolve_base() {
	if [ -n "\${${v("INSTALL_BASE")}:-}" ]; then
		base=\${${v("INSTALL_BASE")}}
	elif [ -z "$repo" ]; then
		fail "set ${v("INSTALL_BASE")}: no repository to download from"
	elif [ -n "\${${v("VERSION")}:-}" ]; then
		case \${${v("VERSION")}} in
		*[!A-Za-z0-9._-]* | .* | "") fail "${v("VERSION")} \${${v("VERSION")}}: not a release tag" ;;
		esac
		base="https://github.com/$repo/releases/download/\${${v("VERSION")}}"
	else
		base="https://github.com/$repo/releases/latest/download"
	fi
	case $base in
	https://*)
		proto="=https"
		return
		;;
	http://*) ;;
	*) fail "$base: want https://" ;;
	esac
	rest=\${base#http://}
	case $rest in
	\\[::1\\] | \\[::1\\][:/]*) host="[::1]" ;;
	*)
		host=\${rest%%/*}
		host=\${host%%:*}
		;;
	esac
	case $host in
	localhost | "[::1]") ;;
	127.*)
		case $host in
		*[!0-9.]*) fail "$base: want https://" ;;
		esac
		;;
	*) fail "$base: want https://, or http:// on loopback" ;;
	esac
	proto="=http"
}

`
}

/** install.sh's platform: the archive's os and arch. */
const shPlatform = ({ prefix }: InstallApp) => {
	const v = (name: string) => `${prefix}_${name}`
	return `# platform: the archive's os and arch
platform() {
	case $(uname -s) in
	Linux) os=linux ;;
	Darwin) os=darwin ;;
	*) fail "$(uname -s): this script installs on Linux and macOS; on Windows, run install.ps1" ;;
	esac
	arch=\${${v("INSTALL_ARCH")}:-}
	if [ -z "$arch" ]; then
		case $(uname -m) in
		x86_64 | amd64) arch=amd64 ;;
		aarch64 | arm64) arch=arm64 ;;
		*) fail "$(uname -m): no build for this architecture (set ${v("INSTALL_ARCH")} to amd64 or arm64)" ;;
		esac
	fi
	case $arch in
	amd64 | arm64) ;;
	*) fail "${v("INSTALL_ARCH")} $arch: want amd64 or arm64" ;;
	esac
}

`
}

/** install.sh's main: fetch, verify, install; called on the script's last line. */
const shMain = ({ bin, prefix, repo }: InstallApp) => {
	const v = (name: string) => `${prefix}_${name}`
	return `main() {
	bin='${bin}'
	repo='${repo ?? ""}'
	resolve_base
	platform
	archive="\${bin}_\${os}_\${arch}.tar.gz"
	dir=\${${v("INSTALL_DIR")}:-$HOME/.local/bin}
	tmp=$(mktemp -d)
	trap 'rm -rf "$tmp"' EXIT
	fetch "$base/$archive" "$tmp/$archive"
	fetch "$base/checksums.txt" "$tmp/checksums.txt"
	want=$(awk -v name="$archive" '$2 == name { print $1 }' "$tmp/checksums.txt")
	[ -n "$want" ] || fail "checksums.txt lists no $archive"
	got=$(sha256 "$tmp/$archive")
	[ "$got" = "$want" ] || fail "$archive: its sha256 is $got, checksums.txt says $want"
	mkdir "$tmp/x"
	tar -xzf "$tmp/$archive" -C "$tmp/x" "$bin" || fail "$archive holds no $bin"
	mkdir -p "$dir"
	cp "$tmp/x/$bin" "$dir/.$bin.new"
	chmod 755 "$dir/.$bin.new"
	mv -f "$dir/.$bin.new" "$dir/$bin"
	echo "installed $dir/$bin"
}

main "$@"
`
}

/** install.sh for `app`. */
export const installSh = (app: InstallApp): string =>
	[shHead(app), SH_TOOLS, shBase(app), shPlatform(app), shMain(app)].join("")

/** install.ps1's head and the first half of its function: the base it downloads from. */
const ps1Head = ({ bin, prefix, repo }: InstallApp) => {
	const v = (name: string) => `$env:${prefix}_${name}`
	return `# ${MARKER}
# Installs ${bin} on Windows: the archive for this architecture, its sha256 checked against checksums.txt before
# anything installs. The script is one function called on its last line, so a truncated download runs nothing.
#   ${v("VERSION")}       a release tag (default: the latest)
#   ${v("INSTALL_BASE")}  where the release's files are: https://, or http:// on loopback
#   ${v("INSTALL_DIR")}   where ${bin}.exe goes (default: $env:LOCALAPPDATA\\Programs\\${bin})
#   ${v("INSTALL_ARCH")}  amd64 or arm64, over this machine's
$ErrorActionPreference = 'Stop'

function Install-Release {
	$bin = '${bin}'
	$repo = '${repo ?? ""}'
	function Fail([string] $reason) {
		[Console]::Error.WriteLine("$bin install: $reason")
		exit 1
	}
	$base = ${v("INSTALL_BASE")}
	if (-not $base) {
		if (-not $repo) { Fail "set ${prefix}_INSTALL_BASE: no repository to download from" }
		$version = ${v("VERSION")}
		if ($version) {
			if ($version -notmatch '^[A-Za-z0-9_-][A-Za-z0-9._-]*$') { Fail "${prefix}_VERSION $($version): not a release tag" }
			$base = "https://github.com/$repo/releases/download/$version"
		} else {
			$base = "https://github.com/$repo/releases/latest/download"
		}
	}
`
}

/** install.ps1's second half: the base checked, the platform, fetch, verify, install; the call on the last line. */
const ps1Rest = ({ bin, prefix }: InstallApp) => {
	const v = (name: string) => `$env:${prefix}_${name}`
	return `	$uri = $null
	if (-not [Uri]::TryCreate($base, [UriKind]::Absolute, [ref] $uri)) { Fail "$($base): not a URL" }
	if ($uri.Scheme -ne 'https' -and -not ($uri.Scheme -eq 'http' -and $uri.IsLoopback)) {
		Fail "$($base): want https://, or http:// on loopback"
	}
	$arch = ${v("INSTALL_ARCH")}
	if (-not $arch) {
		$arch = switch ([System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString()) {
			'X64' { 'amd64' }
			'Arm64' { 'arm64' }
			default { Fail "$($_): no build for this architecture (set ${prefix}_INSTALL_ARCH to amd64 or arm64)" }
		}
	}
	if ($arch -notin @('amd64', 'arm64')) { Fail "${prefix}_INSTALL_ARCH $($arch): want amd64 or arm64" }
	$archive = "${bin}_windows_$arch.zip"
	$dir = ${v("INSTALL_DIR")}
	if (-not $dir) { $dir = Join-Path $env:LOCALAPPDATA (Join-Path 'Programs' $bin) }
	$tmp = Join-Path ([IO.Path]::GetTempPath()) ([IO.Path]::GetRandomFileName())
	New-Item -ItemType Directory -Path $tmp | Out-Null
	try {
		$file = Join-Path $tmp $archive
		$sums = Join-Path $tmp 'checksums.txt'
		foreach ($pair in @(@("$base/$archive", $file), @("$base/checksums.txt", $sums))) {
			try {
				Invoke-WebRequest -Uri $pair[0] -OutFile $pair[1] -UseBasicParsing
			} catch {
				Fail "could not download $($pair[0])"
			}
		}
		$want = Get-Content $sums | ForEach-Object { $fields = $_ -split '\\s+'; if ($fields[1] -eq $archive) { $fields[0] } } | Select-Object -First 1
		if (-not $want) { Fail "checksums.txt lists no $archive" }
		$got = (Get-FileHash -Algorithm SHA256 -Path $file).Hash.ToLowerInvariant()
		if ($got -ne $want) { Fail "$($archive): its sha256 is $got, checksums.txt says $want" }
		$out = Join-Path $tmp 'x'
		Expand-Archive -Path $file -DestinationPath $out
		$exe = Join-Path $out "$bin.exe"
		if (-not (Test-Path $exe)) { Fail "$archive holds no $bin.exe" }
		New-Item -ItemType Directory -Force -Path $dir | Out-Null
		Move-Item -Force -Path $exe -Destination (Join-Path $dir "$bin.exe")
		Write-Output "installed $(Join-Path $dir "$bin.exe")"
	} finally {
		Remove-Item -Recurse -Force -Path $tmp
	}
}

Install-Release
`
}

/** install.ps1 for `app`: the Windows archive, verified by Get-FileHash, installed under LOCALAPPDATA by default. */
export const installPs1 = (app: InstallApp): string => `${ps1Head(app)}${ps1Rest(app)}`
