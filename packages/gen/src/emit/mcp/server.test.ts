/**
 * The generated MCP server's package (bit 18 phase a): its files byte for byte; the vendored runtime as one module in
 * order; `dist/` the types-erased CommonJS of every `src/` file, the same whichever runtime generates; the options
 * refused unless they match their grammar (F2); the TypeScript strict and erasable-only; the compiled server under
 * node and the source under bun answering alike, and both official clients connecting to it.
 */
import { readFileSync } from "node:fs"
import { join } from "node:path"
import { createJiti } from "jiti"
import { describe, expect, it } from "vitest"
import { clientCheck, withClients } from "./__fixtures__/clients.ts"
import { exchange, initialize, request, typeErrors, written } from "./__fixtures__/written.ts"
import { erased, MCP_RUNTIME, generateMcpServer, mcpRuntimeSource } from "./server.ts"

const CLIENTS = withClients()
const SLOW = { timeout: 120_000 }
const OK = { 200: { content: { "application/json": { schema: { type: "object" } } }, description: "ok" } }

/** A document of one gated operation, titled `title`, versioned `version`. */
const document = (title = "Shop", version = "1.2.0") => ({
	info: { title, version },
	openapi: "3.1.0",
	paths: { "/items": { get: { operationId: "items.list", responses: OK, "x-mcp": true } } },
})

const MARKER = "// Code generated by honey. DO NOT EDIT."

describe("the package's files (phase a)", () => {
	// v0: bccd07ce25
	it("writes package.json, the source under src/ (the embedded TS SDK under src/sdk/) and its compiled twin under dist/", () => {
		const files = generateMcpServer(document()).files
		const sdk = ["client", "index", "map", "runtime", "types"].map((part) => `sdk/api.${part}.gen`)
		const modules = ["mcp.runtime", "server", "tools.gen", ...sdk]
		expect(Object.keys(files).sort()).toEqual(
			["package.json", "dist/package.json", ...modules.flatMap((name) => [`src/${name}.ts`, `dist/${name}.js`])].sort(),
		)
	})

	it("declares the package by the server's name, its bin the compiled entry, no dependency", () => {
		expect(JSON.parse(generateMcpServer(document()).files["package.json"] as string)).toEqual({
			bin: { "shop-mcp": "dist/server.js" },
			description: "The shop API as MCP tools",
			engines: { node: ">=22" },
			files: ["dist", "src"],
			name: "shop-mcp",
			type: "module",
			version: "1.2.0",
		})
	})

	it("writes the entry: the SDK client by the environment, the key as the API's scheme says, the tools served over stdio", () => {
		const files = generateMcpServer(document()).files
		expect([files["src/server.ts"], files["dist/package.json"]]).toEqual([
			`${MARKER}

// The shop MCP server: its tools over stdio, for the MCP client that starts it. The API key is
// $SHOP_API_KEY, sent as the API's scheme says; the API is at $SHOP_BASE_URL, else its first server.
import { bindTools, createSession, serveStdio } from "./mcp.runtime"
import { Api } from "./sdk/api.index.gen"
import { toolSpecs } from "./tools.gen"

const key = process.env["SHOP_API_KEY"] ?? ""
const client = new Api({
	baseURL: process.env["SHOP_BASE_URL"] || "",
	headers: key === "" ? {} : { "Authorization": "Bearer " + key },
	throwOnError: true,
})

void serveStdio(createSession({ name: "shop", version: "1.2.0" }, bindTools(toolSpecs, client)))
`,
			'{\n\t"type": "commonjs"\n}\n',
		])
	})
})

describe("the tools file (phase b)", () => {
	it("writes each tool's spec into tools.gen.ts as data the runtime binds", () => {
		expect(generateMcpServer(document()).files["src/tools.gen.ts"]).toBe(`${MARKER}

import type { ToolSpec } from "./mcp.runtime"

export const toolSpecs: readonly ToolSpec[] = [
	{
		name: "items_list",
		inputSchema: {
			type: "object",
			properties: {},
		},
		member: [
			"items",
			"list",
		],
		args: [],
	},
]
`)
	})
})

/** A runtime/mcp module's source. */
const runtimeModule = (name: string) => readFileSync(new URL(`../../runtime/mcp/${name}.ts`, import.meta.url), "utf8")

describe("the vendored runtime (phase a)", () => {
	// v0: 9b4a7eba93
	it("joins the vendored runtime into one module, each runtime/mcp file after the ones it imports, their imports of each other dropped", () => {
		const text = mcpRuntimeSource()
		/* each module's own imports of its siblings, by name, read from its source */
		const misplaced = MCP_RUNTIME.flatMap((name, at) =>
			[...runtimeModule(name).matchAll(/from "\.\/([\w-]+)\.ts"/g)]
				.map((match) => match[1] as string)
				.filter((sibling) => !MCP_RUNTIME.slice(0, at).includes(sibling))
				.map((sibling) => `${name} before ${sibling}`),
		)
		const firsts = MCP_RUNTIME.map(
			(name) =>
				runtimeModule(name)
					.split("\n")
					.find((line) => line.startsWith("export ")) as string,
		)
		expect([
			text.startsWith(`${MARKER}\n\n`),
			misplaced,
			firsts
				.map((line) => text.indexOf(line))
				.every((at, i, all) => at > 0 && (i === 0 || at > (all[i - 1] as number))),
			/from "\.\/[\w-]+\.ts"/.test(text),
		]).toEqual([true, [], true, false])
	})
})

describe("the compiled twin (phase a)", () => {
	it("is each source file with its types erased by jiti, the entry a bin with its shebang, the same generated twice", () => {
		const files = generateMcpServer(document()).files
		const jiti = createJiti(import.meta.url, { fsCache: false, moduleCache: false })
		const drift = Object.entries(files)
			.filter(([path]) => path.startsWith("src/"))
			.filter(([path, source]) => {
				const code = jiti.transform({ filename: path, source, ts: true }).trimEnd()
				const shebang = path === "src/server.ts" ? "#!/usr/bin/env node\n" : ""
				return files[path.replace(/^src\//, "dist/").replace(/\.ts$/, ".js")] !== `${shebang}${code}\n`
			})
		expect([drift, generateMcpServer(document()).files]).toEqual([[], files])
	})
})

describe("what the generator refuses (phase b)", () => {
	// v0: 9a0ef89116
	it("refuses a document with no operation marked x-mcp, and one whose marked operations no tool can call", () => {
		const socket = {
			get: { operationId: "chat", responses: { 101: { description: "up" } }, "x-mcp": true, "x-websocket": true },
		}
		expect(
			[
				() =>
					generateMcpServer({
						...document(),
						paths: { "/items": { get: { operationId: "items.list", responses: OK } } },
					}),
				() => generateMcpServer({ ...document(), paths: { "/chat": socket } }),
			].map((generate) =>
				(() => {
					try {
						generate()
						return "generated"
					} catch (error) {
						return (error as Error).message
					}
				})(),
			),
		).toEqual([
			"No operation is marked x-mcp: nothing to serve",
			"No operation marked x-mcp is one a tool can call yet: nothing to serve",
		])
	})

	it("refuses source the erasure cannot parse, writing no broken twin", () => {
		expect(() => erased("src/x.ts", "const a = ;\n")).toThrow("src/x.ts does not parse:")
	})
})

/** The package.json generated for `doc`. */
const pkg = (doc: Record<string, unknown>) =>
	JSON.parse(generateMcpServer(doc).files["package.json"] as string) as { name: string; version: string }

describe("the options (F2, phase a)", () => {
	it("names the server by the title's words, and its version 0.0.0 when the document's is none npm accepts or none at all", () => {
		const untagged = { ...document(), info: { title: "Shop" } }
		expect([pkg(document("9 Anyrow's API!", "v1")), pkg(untagged)].map(({ name, version }) => [name, version])).toEqual(
			[
				["anyrow-s-api-mcp", "0.0.0"],
				["shop-mcp", "0.0.0"],
			],
		)
	})

	it.each([
		["name", "Shop"],
		["name", "a b"],
		["name", "$(rm)"],
		["name", "a".repeat(61)],
		["envPrefix", "shop"],
		["envPrefix", "SHOP-X"],
	])("refuses %s %j at generate", (option, value) => {
		expect(() => generateMcpServer(document(), { [option]: value })).toThrow(
			`Invalid ${option}: ${JSON.stringify(value)}`,
		)
	})
})

describe("the written server (phase a)", SLOW, () => {
	const dir = written(generateMcpServer(document()).files)
	const lines = [initialize("2025-11-25"), request(1, "ping"), request(2, "tools/list"), request(3, "nope")]

	it("type-checks strict, erasable syntax only, the embedded SDK included", () => {
		expect(typeErrors(dir)).toEqual([])
	})

	it("answers alike compiled under node and as source under bun, and exits 0", async () => {
		const [node, bun] = await Promise.all([
			exchange([process.execPath, join(dir, "dist/server.js")], lines),
			exchange(["bun", join(dir, "src/server.ts")], lines),
		])
		expect([node.status, node.replies.length, node.replies]).toEqual([0, 4, bun.replies])
	})

	it.skipIf(!CLIENTS).each(["sdk", "v2"] as const)("lets %s connect and list its tools", async (client) => {
		const saw = await clientCheck(client, [process.execPath, join(dir, "dist/server.js")])
		expect([saw.latest, saw.tools]).toEqual([
			"2025-11-25",
			[{ inputSchema: { properties: {}, type: "object" }, name: "items_list" }],
		])
	})
})
