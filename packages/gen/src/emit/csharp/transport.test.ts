const MIXES = [
	{ realtime: false, ws: false },
	{ realtime: false, ws: true },
	{ realtime: true, ws: false },
	{ realtime: true, ws: true },
] as const

const FULL = { realtime: true, ws: true } as const

/** The committed runtime's `.cs` files, sorted. */
const committed = () =>
	readdirSync(new URL("../../runtime/csharp/", import.meta.url))
		.filter((name) => name.endsWith(".cs"))
		.sort()

const onDisk = (name: string) => readFileSync(new URL(`../../runtime/csharp/${name}`, import.meta.url), "utf8")

/** `text`'s lines, without the empty one after a final newline. */
const linesOf = (text: string) => (text.endsWith("\n") ? text.slice(0, -1) : text).split("\n")

/** Whether `line` declares something public at column 0. */
const isPublic = (line: string) => line.startsWith("public ")

/** `text`'s `namespace` lines. */
const namespaceLines = (text: string) => linesOf(text).filter((line) => line.startsWith("namespace "))

describe("runtimeFileNames: which runtime files a feature mix ships", () => {
	it("ships the 21 core files for plain HTTP, Ws.cs and WsDial.cs on top for a WebSocket API, and the realtime files on top of both for a realtime API", () => {
		expect(Object.fromEntries(MIXES.map((mix) => [JSON.stringify(mix), runtimeFileNames(mix)]))).toEqual({
			'{"realtime":false,"ws":false}': CORE,
			'{"realtime":false,"ws":true}': [...CORE, ...WS],
			'{"realtime":true,"ws":false}': ALL,
			'{"realtime":true,"ws":true}': ALL,
		})
		expect([CORE.length, WS.length, REALTIME.length, ALL.length]).toEqual([21, 2, 6, 29])
		expect(ALL).toEqual([...CORE, ...WS, ...REALTIME].sort(compareCodeUnits))
	})

	it("names exactly the .cs files committed under runtime/csharp/", () => {
		expect(runtimeFileNames(FULL)).toEqual(committed())
	})
})

describe("runtimeFiles: the runtime as shipped, in the SDK's namespace (Fb2)", () => {
	it.each(MIXES)("keys each shipped file by its name, in code-unit order (%o)", (mix) => {
		expect(Object.keys(runtimeFiles(mix, "Acme.Sdk"))).toEqual(runtimeFileNames(mix))
	})

	it("commits each file with the marker on line 1 and exactly one namespace line, namespace Honey.Runtime;", () => {
		expect(
			committed().filter((name) => {
				const text = onDisk(name)
				return linesOf(text)[0] !== MARK || namespaceLines(text).join(" | ") !== "namespace Honey.Runtime;"
			}),
		).toEqual([])
	})

	it("returns each file byte for byte as committed, its namespace line swapped for the SDK's", () => {
		const files = runtimeFiles(FULL, "Acme.Sdk")
		expect(files).toEqual(
			Object.fromEntries(
				runtimeFileNames(FULL).map((name: string) => [
					name,
					onDisk(name).replace(/^namespace Honey\.Runtime;$/m, "namespace Acme.Sdk;"),
				]),
			),
		)
	})

	it("marks every file on line 1, holds one namespace Acme.Sdk; line and no Honey.Runtime, and keeps each at most 300 lines", () => {
		const files = Object.entries<string>(runtimeFiles(FULL, "Acme.Sdk"))
		expect({
			honey: files.filter(([, text]) => text.includes("Honey.Runtime")).map(([name]) => name),
			long: files.filter(([, text]) => linesOf(text).length > 300).map(([name]) => name),
			namespaces: files
				.filter(([, text]) => namespaceLines(text).join(" | ") !== "namespace Acme.Sdk;")
				.map(([name]) => name),
			unmarked: files.filter(([, text]) => linesOf(text)[0] !== MARK).map(([name]) => name),
		}).toEqual({ honey: [], long: [], namespaces: [], unmarked: [] })
		expect(files.map(([name]) => name)).toEqual(ALL)
	})

	it("returns the same bytes on every call, in a fresh map the caller may change", () => {
		const first = runtimeFiles(FULL, "Acme")
		const second = runtimeFiles(FULL, "Acme")
		expect(second).toEqual(first)
		expect(second).not.toBe(first)
		delete first["Errors.cs"]
		expect(Object.keys(runtimeFiles(FULL, "Acme"))).toEqual(ALL)
	})

	it("reads the files from disk on every call: an edited read is what it returns (F8)", () => {
		const before = runtimeFiles(FULL, "Acme")["Config.cs"] ?? ""
		disk.edit = (text) => text.replace(MARK, "// edited on disk")
		try {
			expect(linesOf(runtimeFiles(FULL, "Acme")["Config.cs"] ?? "")[0]).toBe("// edited on disk")
		} finally {
			disk.edit = undefined
		}
		expect([linesOf(before)[0], runtimeFiles(FULL, "Acme")["Config.cs"]]).toEqual([MARK, before])
	})
})

