/**
 * The Go SDK (bit 12): a module of package `sdk` emitted from the IR alone (H2) — the vendored
 * runtime verbatim, `types.go` (every component, then every hoisted declaration in name order, then
 * the declared error keys), `client.go` (the client, its resources and methods), `doc.go` and
 * `go.mod`, plus `go.sum` when the API needs the WebSocket library. Every `.go` file carries the
 * generated-code marker.
 */
import { type OpenApiDocument, toIR } from "../../ir/build.ts"
import type { IR, IRInfo, IRSchema } from "../../ir/model.ts"
import { sdkModel } from "../../ir/sdk-model.ts"
import { lineComment } from "../shared/escape.ts"
import { compareCodeUnits } from "../shared/lang.ts"
import { goErrorKeys } from "./errors.ts"
import { needsWebSocket, runtimeFiles } from "./http.ts"
import { clientDecls, type GoCallPlan } from "./sdk-client.ts"
import { type GoTypeContext, goTopLevel, goTypeContext } from "./types.ts"

export type GoSdkOptions = {
	/** the module path go.mod declares; `example.com/sdk` by default */
	readonly modulePath?: string
	/** false: each method with a response body returns `SDKResult[T]` instead of an error status as `error` */
	readonly throwOnError?: boolean
}

export type GeneratedGoSdk = { readonly files: Readonly<Record<string, string>> }

/* the marker gopls and linters read, apart from the package doc by a blank line */
const MARKER = "// Code generated by honey. DO NOT EDIT."

/* the WebSocket library and its go.sum lines, as the Go checksum database has them; the CLI's module requires them too */
export const WEBSOCKET = "github.com/coder/websocket v1.8.15"
export const WEBSOCKET_SUM = [
	`${WEBSOCKET} h1:6B2JPeOGlpff2Uz6vOEH1Vzpi0iUz20A+lPVhPHtNUA=`,
	`${WEBSOCKET}/go.mod h1:NX3SzP+inril6yawo5CQXx8+fk145lPDC6pumgx0mVg=`,
]

/* what client.go may import, each only when its code uses it */
const CLIENT_IMPORTS: readonly (readonly [string, string])[] = [
	["context", "context"],
	["json", "encoding/json"],
	["io", "io"],
	["iter", "iter"],
	["http", "net/http"],
	["url", "net/url"],
]

/** String and rune literals and line comments: text an import check must not read as code (the CLI's cmd files too). */
export const NOT_CODE = /"(?:[^"\\\n]|\\.)*"|`[^`]*`|'(?:[^'\\\n]|\\.)*'|\/\/[^\n]*/g

/** A `.go` file of package `sdk` holding `decls`, importing each of `imports` (`[name, path]`) its code uses. */
function goFile(decls: string, imports: readonly (readonly [string, string])[]): string {
	const code = decls.replace(NOT_CODE, "")
	const used = imports.filter(([name]) => new RegExp(`\\b${name}\\.`).test(code)).map(([, path]) => `\t"${path}"`)
	const block = used.length === 0 ? "" : `import (\n${used.join("\n")}\n)\n\n`
	return `${MARKER}\n\npackage sdk\n\n${block}${decls}\n`
}

/** go.mod at the go 1.24 floor, and go.sum, requiring the WebSocket library only when `websocket`. */
function moduleFiles(modulePath: string, websocket: boolean): Record<string, string> {
	const mod = [`module ${modulePath}`, "", "go 1.24", ""]
	if (!websocket) return { "go.mod": mod.join("\n") }
	return { "go.mod": [...mod, `require ${WEBSOCKET}`, ""].join("\n"), "go.sum": `${WEBSOCKET_SUM.join("\n")}\n` }
}

/** doc.go: the package godoc, naming the API and holding its description. */
function docFile(info: IRInfo): string {
	const named = [info.title].filter((title) => title !== undefined).map((title) => ` for ${title}`)
	const text = [`Package sdk is a generated client${named.join("")}.`, info.description].filter(
		(part) => part !== undefined,
	)
	return `${MARKER}\n\n${lineComment(text.join("\n\n"), "//").join("\n")}\npackage sdk\n`
}

/** Each component's declaration in code-unit order, its description as its godoc. */
function componentDecls(ir: IR, at: GoTypeContext): string[] {
	return Object.keys(ir.schemas)
		.sort(compareCodeUnits)
		.map((name) => {
			const described = Object.hasOwn(ir.schemaDescriptions, name)
			const doc = described ? lineComment(ir.schemaDescriptions[name] as string, "//") : []
			return [...doc, goTopLevel(at.names.ref(name), ir.schemas[name] as IRSchema, at)].join("\n")
		})
}

/** The module's files for `document`, and the call plan of every method in them. */
function emitGo(document: Record<string, unknown>, options: GoSdkOptions): GeneratedGoSdk & { plans: GoCallPlan[] } {
	const ir = toIR(document as OpenApiDocument, { deriveOperationIds: true })
	const model = sdkModel(ir)
	const at = goTypeContext(ir)
	/* components first: the client's hoisted types then land beside them */
	const components = componentDecls(ir, at)
	const ops = model.opsById
	const client = clientDecls(ir, { at, ops, throwOnError: options.throwOnError ?? true })
	const errorKeys = goErrorKeys(model, at)
	const hoisted = [...at.decls].sort(([a], [b]) => compareCodeUnits(a, b)).map(([, decl]) => decl)
	const features = {
		realtime: model.ops.some((op) => op.stream === "realtime"),
		ws: model.ops.some((op) => op.stream === "ws"),
	}
	return {
		plans: client.plans,
		files: {
			...runtimeFiles(features),
			...moduleFiles(options.modulePath ?? "example.com/sdk", needsWebSocket(features)),
			"client.go": goFile(client.decls, CLIENT_IMPORTS),
			"doc.go": docFile(ir.info),
			"types.go": goFile([...components, ...hoisted, errorKeys].filter((decl) => decl !== "").join("\n\n"), [
				["json", "encoding/json"],
			]),
		},
	}
}

/** The Go SDK module for `document`, by file name. */
export function generateGoSdk(document: Record<string, unknown>, options: GoSdkOptions = {}): GeneratedGoSdk {
	return { files: emitGo(document, options).files }
}

/**
 * Each operation's call plan by id, from the very emit `generateGoSdk` runs with these options: the
 * names a test driver invokes the SDK by (G8.4), never re-derived outside the emitter.
 */
export function goCallPlans(
	document: Record<string, unknown>,
	options: GoSdkOptions = {},
): Readonly<Record<string, GoCallPlan>> {
	return Object.fromEntries(emitGo(document, options).plans.map((plan) => [plan.operation, plan]))
}
