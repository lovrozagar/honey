/* ── Go bracket-balance helper ──
 * Verifies {}, (), [] are balanced in emitted Go source.
 * Skips content inside:
 *   - raw string literals  `...`
 *   - interpreted strings  "..."
 *   - rune literals        '...'
 *   - line comments        // ...\n
 *   - block comments       /* ... * /
 * Drops <> entirely — Go generics use [] at emit sites, not <>.
 */
function assertBalancedGoBrackets(src: string): void {
	let braces = 0
	let parens = 0
	let brackets = 0
	let i = 0
	while (i < src.length) {
		/* block comment */
		if (src[i] === "/" && src[i + 1] === "*") {
			i += 2
			while (i < src.length && !(src[i] === "*" && src[i + 1] === "/")) i++
			i += 2
			continue
		}
		/* line comment */
		if (src[i] === "/" && src[i + 1] === "/") {
			while (i < src.length && src[i] !== "\n") i++
			continue
		}
		/* raw string literal (backtick) */
		if (src[i] === "`") {
			i++
			while (i < src.length && src[i] !== "`") i++
			i++
			continue
		}
		/* interpreted string literal */
		if (src[i] === '"') {
			i++
			while (i < src.length && src[i] !== '"') {
				if (src[i] === "\\") i++
				i++
			}
			i++
			continue
		}
		/* rune literal */
		if (src[i] === "'") {
			i++
			while (i < src.length && src[i] !== "'") {
				if (src[i] === "\\") i++
				i++
			}
			i++
			continue
		}
		if (src[i] === "{") braces++
		else if (src[i] === "}") braces--
		else if (src[i] === "(") parens++
		else if (src[i] === ")") parens--
		else if (src[i] === "[") brackets++
		else if (src[i] === "]") brackets--
		i++
	}
	expect(braces, "unbalanced {}").toBe(0)
	expect(parens, "unbalanced ()").toBe(0)
	expect(brackets, "unbalanced []").toBe(0)
}

