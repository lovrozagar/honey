/**
 * The generated sources module (plan 39 7.5): a generation with a named OpenAPI document writes
 * `src/_gen/openapi-sources.gen.ts`, each named document's files as `{ asset }` sources under the assets directory
 * (`codegen.assetsDir`, else wrangler's `assets.directory`, its binding carried when it is not `ASSETS`), which
 * `serveStaticOpenApi` serves spread as they are. A named document outside that directory, or no directory, is an error.
 */
import { existsSync, readFileSync } from "node:fs"
import { join } from "node:path"
import { afterEach, describe, expect, it } from "vitest"
import { serveStaticOpenApi } from "../openapi/static.ts"
import { honey } from "../routing/app.ts"
import { type Project, project } from "./__fixtures__/project.ts"
import { type HoneyCodegenConfig, resolveHoneyConfig } from "./config.ts"
import { generateAndWrite } from "./generate.ts"
import { jsoncToJson, openApiSourcesOf } from "./openapi-sources.ts"

const projects: Project[] = []
afterEach(() => {
	for (const made of projects.splice(0)) made.done()
})

const SOURCES = "src/_gen/openapi-sources.gen.ts"

/* comments, a trailing comma and a `//` inside a string, as a hand-kept wrangler.jsonc has them */
const WRANGLER = `{
	// the Worker
	"name": "shop", /* its assets: */
	"compatibility_flags": ["nodejs_compat"],
	"routes": [{ "pattern": "https://shop.example.com/*" }],
	"assets": { "binding": "DOCS", "directory": "./public", },
}
`

/** The sources module `codegen` gives a fresh project of `files` (`null`: none), or the error it threw. */
function generated(codegen: HoneyCodegenConfig, files: Record<string, string> = {}) {
	const made = project(files, { link: true })
	projects.push(made)
	const config = resolveHoneyConfig({ app: "src/app.ts", codegen: { tree: false, ...codegen } })
	try {
		return { made, text: openApiSourcesOf(config, made.dir) }
	} catch (error) {
		return { error: (error as Error).message, made }
	}
}

const doc = (entry: object) => ({ title: "Shop", version: "1", ...entry })

describe("jsoncToJson", () => {
	it("leaves out comments and trailing commas, and every string as written, an unclosed comment to the end", () => {
		const text = '{ "a": "x // y /* z */", "b": "q\\"//", "c": [1, 2, ], } // end'
		expect([JSON.parse(jsoncToJson(text)), jsoncToJson("[1] /* open"), jsoncToJson("[1] // last")]).toEqual([
			{ a: "x // y /* z */", b: 'q"//', c: [1, 2] },
			"[1]  ",
			"[1] ",
		])
	})
})

describe("openapi-sources.gen.ts (plan 39 7.5)", () => {
	it("holds each named document's files under wrangler's assets directory, which serveStaticOpenApi serves", async () => {
		const { made, text } = generated(
			{
				openApi: [
					doc({ formats: ["json", "yaml"], name: "public", path: "public/openapi.public.json" }),
					doc({ name: "internal", path: "public/docs/internal.json" }),
					doc({ path: "src/_gen/contract.json" }),
				],
			},
			{ "wrangler.jsonc": WRANGLER },
		)
		expect(text).toBe(
			[
				"/** Where each named OpenAPI document is, as serveStaticOpenApi sources. Generated by honey generate. */",
				"export const openApiSources = {",
				'\t"public": {"json":{"asset":"/openapi.public.json","binding":"DOCS"},"yaml":{"asset":"/openapi.public.yaml","binding":"DOCS"}},',
				'\t"internal": {"json":{"asset":"/docs/internal.json","binding":"DOCS"}},',
				"} as const",
				"",
			].join("\n"),
		)
		made.write(SOURCES, text as string)
		const { openApiSources } = (await import(join(made.dir, SOURCES))) as {
			openApiSources: { public: { json: { asset: string; binding: string } } }
		}
		const asked: string[] = []
		const env = {
			DOCS: { fetch: async (url: URL) => (asked.push(url.pathname), new Response('{"openapi":"3.1.0"}')) },
		}
		const app = serveStaticOpenApi(honey(), { ...openApiSources.public, path: "/v1/spec" })
		const res = await app.fetch(new Request("https://shop.example.com/v1/spec.json"), env)
		expect([res.status, await res.text(), asked]).toEqual([200, '{"openapi":"3.1.0"}', ["/openapi.public.json"]])
	})

	it("takes codegen.assetsDir over wrangler, the default binding left implied, and writes nothing with no named document", async () => {
		const own = generated(
			{ assetsDir: "dist/assets", openApi: doc({ name: "api", path: "dist/assets/api.json" }) },
			{ "wrangler.jsonc": WRANGLER },
		)
		const plain = generated(
			{ openApi: doc({ name: "api", path: "public/api.json" }) },
			{ "wrangler.json": '{ "assets": { "binding": "ASSETS", "directory": "public" } }' },
		)
		const unnamed = generated({ openApi: doc({ path: "public/x.json" }) })
		expect([own.text?.split("\n")[2], plain.text?.split("\n")[2], unnamed.text]).toEqual([
			'\t"api": {"json":{"asset":"/api.json"}},',
			'\t"api": {"json":{"asset":"/api.json"}},',
			null,
		])
	})
})

describe("openapi-sources.gen.ts: what it refuses (plan 39 7.5)", () => {
	it("refuses a named document outside the assets directory, and a named one with no directory to resolve against", async () => {
		const outside = generated(
			{ openApi: doc({ name: "public", path: "src/_gen/public.json" }) },
			{ "wrangler.jsonc": WRANGLER },
		)
		const none = generated(
			{ openApi: doc({ name: "public", path: "public/x.json" }) },
			{ "wrangler.jsonc": '{ "name": "shop" }' },
		)
		const toml = generated(
			{ openApi: doc({ name: "public", path: "public/x.json" }) },
			{ "wrangler.toml": '[assets]\ndirectory = "./public"\n' },
		)
		expect([outside.error, none.error, toml.error]).toEqual([
			'codegen.openApi "public": src/_gen/public.json is outside the assets directory public, so no asset serves it',
			'codegen.openApi "public" is named, so its files are listed as assets: set codegen.assetsDir, or assets.directory in wrangler.jsonc',
			'codegen.openApi "public" is named, so its files are listed as assets: wrangler.toml is not read: set codegen.assetsDir, or keep the Worker\'s config in wrangler.json or wrangler.jsonc',
		])
	})
})

describe("openapi-sources.gen.ts, imported by the app it is generated for (plan 39 7.5)", () => {
	/* the module depends on the config alone, so a generation writes it before it loads the app that imports it */
	const APP = [
		'import { honey } from "@lovrozagar/honey"',
		'import { serveStaticOpenApi } from "@lovrozagar/honey/openapi/static"',
		'import { openApiSources } from "./_gen/openapi-sources.gen.ts"',
		"export const app = honey()",
		'app.get("/health").handler((c) => c.res.text("ok", "up"))',
		'serveStaticOpenApi(app, { ...openApiSources.public, path: "/v1/spec" })',
		"",
	].join("\n")

	it("is written on the first generation, which loads that app, and a second generation changes nothing", async () => {
		const made = project({ "src/app.ts": APP, "wrangler.jsonc": WRANGLER })
		projects.push(made)
		const config = resolveHoneyConfig({
			app: "src/app.ts",
			codegen: { openApi: doc({ name: "public", path: "public/openapi.public.json" }), tree: false },
		})
		const relative = (files: string[]) => files.map((file) => file.slice(made.dir.length + 1)).sort()
		const absent = existsSync(join(made.dir, SOURCES))
		const first = relative(await generateAndWrite(config, made.dir, { report: () => {} }))
		const text = readFileSync(join(made.dir, SOURCES), "utf8")
		const second = await generateAndWrite(config, made.dir, { report: () => {} })
		expect([absent, first, text.split("\n")[2], second]).toEqual([
			false,
			["public/openapi.public.json", SOURCES],
			'\t"public": {"json":{"asset":"/openapi.public.json","binding":"DOCS"}},',
			[],
		])
	}, 60_000)
})
