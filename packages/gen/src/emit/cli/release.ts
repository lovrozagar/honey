/**
 * The CLI's release (bit 17 phase g): `.goreleaser.yaml` builds six static binaries (linux, darwin, windows × amd64,
 * arm64; CGO off, trimmed paths, stripped, the tag linked in as the version) into archives named without the
 * version, `<bin>_<os>_<arch>` (.tar.gz, .zip for windows), so a release's `latest/download` resolves them, beside
 * `checksums.txt`; Homebrew and Scoop stay commented out until a tap and a bucket are named.
 * `.github/workflows/release.yml` runs it on a `v*` tag alone: contents read by default and write on the release job
 * only, checkout keeping no credentials, every action pinned by commit. Every value is a validated option (the
 * binary, the module path, the repository), never spec text.
 */

/* the marker generated YAML carries on its first line */
const MARKER = "# Code generated by honey. DO NOT EDIT."

/** The tools release.yml runs, each pinned by commit (its release in the comment beside it). */
export const RELEASE_ACTIONS = {
	checkout: "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1",
	goreleaser: "goreleaser/goreleaser-action@f06c13b6b1a9625abc9e6e439d9c05a8f2190e94 # v7.2.3",
	setupGo: "actions/setup-go@b7ad1dad31e06c5925ef5d2fc7ad053ef454303e # v7.0.0",
}

/** A value as a YAML double-quoted scalar (a JSON string is one): a name like `true` or `1e3` stays a string. */
const q = (value: string) => JSON.stringify(value)

/** The goreleaser release the action installs: the one the tests check the config with. */
export const GORELEASER_VERSION = "v2.18.3"

/** .goreleaser.yaml for the CLI `bin` in module `modulePath`, released to `repo` (owner/name) when one is given. */
export function goreleaserFile(bin: string, modulePath: string, repo: string | undefined): string {
	const [owner, name] = repo?.split("/") ?? []
	const tapOwner = owner ?? "OWNER"
	/* without a repository, goreleaser releases to the git remote's */
	const release =
		repo === undefined ? "" : `release:\n  github:\n    owner: ${q(owner as string)}\n    name: ${q(name as string)}\n`
	return `${MARKER}
# ${bin}'s release: six static binaries, each archive named ${bin}_<os>_<arch>, and checksums.txt (release.yml).
version: 2
project_name: ${q(bin)}
builds:
  - id: ${q(bin)}
    main: .
    binary: ${q(bin)}
    env:
      - CGO_ENABLED=0
    flags:
      - -trimpath
    ldflags:
      - ${q(`-s -w -X ${modulePath}/internal/cli.Version={{ .Tag }}`)}
    goos: [linux, darwin, windows]
    goarch: [amd64, arm64]
archives:
  - id: ${q(bin)}
    name_template: "{{ .ProjectName }}_{{ .Os }}_{{ .Arch }}"
    formats: [tar.gz]
    format_overrides:
      - goos: windows
        formats: [zip]
checksum:
  name_template: checksums.txt
  algorithm: sha256
changelog:
  disable: true
${release}# Homebrew and Scoop, off until a tap and a bucket exist: uncomment, then name them.
# brews:
#   - repository: { owner: ${tapOwner}, name: homebrew-tap }
# scoops:
#   - repository: { owner: ${tapOwner}, name: scoop-bucket }
`
}

/** .github/workflows/release.yml: goreleaser on a `v*` tag, publishing the release with the token's write. */
export function releaseWorkflow(bin: string): string {
	return `${MARKER}
# Releases ${bin} on a v* tag: goreleaser builds the six binaries and publishes them beside checksums.txt.
name: release
on:
  push:
    tags:
      - "v*"
permissions:
  contents: read
jobs:
  release:
    runs-on: ubuntu-latest
    permissions:
      contents: write
    steps:
      - uses: ${RELEASE_ACTIONS.checkout}
        with:
          fetch-depth: 0
          persist-credentials: false
      - uses: ${RELEASE_ACTIONS.setupGo}
        with:
          go-version-file: go.mod
          cache: false
      - uses: ${RELEASE_ACTIONS.goreleaser}
        with:
          distribution: goreleaser
          version: ${GORELEASER_VERSION}
          args: release --clean
        env:
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
`
}
