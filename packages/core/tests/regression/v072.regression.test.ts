/**
 * Regression guards for the problems found migrating a Workers app to 0.7.1: dangling `$ref`s
 * for nested schemas shared between bodies, `honey generate` started by Bun running under Node,
 * a stale route tree breaking the generation that would replace it, and declared security
 * schemes reported as undeclared by the SDK document.
 */
import { execFileSync, spawnSync } from "node:child_process"
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import { afterAll, describe, expect, it, vi } from "vitest"
import * as z from "zod"
import { generateOpenApi, generateRouteTreeFromApp } from "../../src/codegen.ts"
import { honey } from "../../src/index.ts"
import { generateAndWrite, resolveHoneyConfig } from "../../src/plugin.ts"

const CORE = resolve(import.meta.dirname, "../..")
const ROOT = resolve(CORE, `.tmp-v072-${process.pid}`)

afterAll(() => rmSync(ROOT, { force: true, recursive: true }))

function project(name: string, files: Record<string, string>): string {
	const dir = join(ROOT, name)
	rmSync(dir, { force: true, recursive: true })
	for (const [rel, content] of Object.entries(files)) {
		mkdirSync(join(dir, rel, ".."), { recursive: true })
		writeFileSync(join(dir, rel), content)
	}
	return dir
}

function danglingRefs(doc: unknown): string[] {
	const have = new Set(Object.keys((doc as { components?: { schemas?: object } }).components?.schemas ?? {}))
	const refs = new Set<string>()
	JSON.stringify(doc, (key, value: unknown) => {
		if (key === "$ref" && typeof value === "string" && value.startsWith("#/components/schemas/")) {
			refs.add(value.slice("#/components/schemas/".length))
		}
		return value
	})
	return [...refs].filter((r) => !have.has(r)).sort()
}

describe("0.7.2 regressions", () => {
	// regression: V072-1 — a nested object shared by two bodies (required in one, optional in the other)
	it("V072-1: nested schemas hoisted from a shared object are all emitted", async () => {
		const assertion = z.object({
			clientExtensionResults: z.object({}),
			id: z.string(),
			response: z.object({ signature: z.string() }),
		})
		const app = honey()
		app
			.post("/v1/auth/login/verify")
			.input({ json: z.object({ response: assertion }) })
			.handler((c) => c.res.json("ok", { ok: true }))
		app
			.post("/v1/auth/reauth")
			.input({ json: z.object({ passkey: assertion.optional() }) })
			.handler((c) => c.res.json("ok", { ok: true }))
		const doc = await generateOpenApi(app, { info: { title: "t", version: "1" } })
		expect(danglingRefs(doc)).toEqual([])
	})

	// regression: V072-2 — `bun run generate` ran the bin's node shebang, so Bun-only module loading was lost
	it("V072-2: honey started from a Bun script runs generation under Bun", () => {
		const bun = execFileSync("bun", ["-e", "console.log(process.execPath)"], { encoding: "utf8" }).trim()
		const dir = project("bun-text-module", {
			"src/app.ts": [
				'import terms from "./terms.md"',
				'import { honey } from "@lovrozagar/honey"',
				"export const app = honey()",
				'app.get("/terms").handler((c) => c.res.text("ok", String(terms)))',
				"",
			].join("\n"),
			"src/terms.md": "# Terms\n",
			"tsconfig.json": JSON.stringify({ compilerOptions: { customConditions: ["honey-source"] } }),
		})
		const run = spawnSync("node", [join(CORE, "bin/honey.js"), "generate", "--app", "src/app.ts"], {
			cwd: dir,
			encoding: "utf8",
			env: { ...process.env, npm_config_user_agent: "bun/1.3.11 npm/? node/v24 linux x64", npm_execpath: bun },
			timeout: 60_000,
		})
		expect(`${run.stdout}${run.stderr}`).not.toContain("ERR_UNKNOWN_FILE_EXTENSION")
		expect(run.status).toBe(0)
	}, 90_000)

	// regression: V072-3 — the gateway's previous routes.gen.ts (older format) threw inside `honey generate`
	it("V072-3: generation replaces a route tree written by an older honey", async () => {
		const dir = project("stale-v1", {
			"src/_gen/routes.gen.ts": [
				"/* @generated by an older honey */",
				"export const routeTree = { root: { s: {}, m: null, d: null, w: null, ws: null }, meta: {}, handlers: {} }",
				"",
			].join("\n"),
			"src/app.ts": [
				'import { honey } from "@lovrozagar/honey"',
				'import { routeTree } from "./_gen/routes.gen.ts"',
				"export const app = honey().routeTree(routeTree as never)",
				'app.get("/health").handler((c) => c.res.json("ok", { ok: true }))',
				"",
			].join("\n"),
		})
		await generateAndWrite(resolveHoneyConfig({ app: "src/app.ts", codegen: { tree: true } }), dir)
		expect(readFileSync(join(dir, "src/_gen/routes.gen.ts"), "utf8")).toContain('"GET /health"')
	}, 60_000)

	// regression: V072-3 — a v2 tree missing a route the app now registers threw inside `honey generate`
	it("V072-3: generation replaces a route tree that is out of date", async () => {
		const old = honey()
		old.get("/a").handler((c) => c.res.json("ok", {}))
		const dir = project("stale-v2", {
			"src/_gen/routes.gen.ts": generateRouteTreeFromApp(old),
			"src/app.ts": [
				'import { honey } from "@lovrozagar/honey"',
				'import { routeTree } from "./_gen/routes.gen.ts"',
				"export const app = honey().routeTree(routeTree)",
				'app.get("/a").handler((c) => c.res.json("ok", {}))',
				'app.get("/b").handler((c) => c.res.json("ok", {}))',
				"",
			].join("\n"),
		})
		await generateAndWrite(resolveHoneyConfig({ app: "src/app.ts", codegen: { tree: true } }), dir)
		expect(readFileSync(join(dir, "src/_gen/routes.gen.ts"), "utf8")).toContain('"GET /b"')
	}, 60_000)

	it("V072-3 guard: outside generation a stale tree still fails loudly", () => {
		const stale = { handlers: {}, meta: {}, root: { d: null, m: null, s: {}, w: null, ws: null } }
		expect(() => honey().routeTree(stale as never)).toThrow("Run `honey generate`")
	})

	// regression: V072-4 — the SDK document was built without the configured security schemes
	it.fails("V072-4: a scheme declared in the openApi config is not reported as undeclared by the SDK step", async () => {
		const dir = project("sdk-schemes", {
			"src/app.ts": [
				'import { honey } from "@lovrozagar/honey"',
				"export const app = honey()",
				'app.get("/t").meta({ operationId: "t.get", security: "iaTesterKey" }).handler((c) => c.res.json("ok", {}))',
				"",
			].join("\n"),
		})
		const messages: string[] = []
		const capture = (...args: unknown[]) => void messages.push(args.map(String).join(" "))
		const warn = vi.spyOn(console, "warn").mockImplementation(capture)
		const error = vi.spyOn(console, "error").mockImplementation(capture)
		try {
			await generateAndWrite(
				resolveHoneyConfig({
					app: "src/app.ts",
					codegen: {
						openApi: {
							path: "src/_gen/openapi.gen.json",
							securitySchemes: { iaTesterKey: { in: "header", name: "x-ia-tester-key", type: "apiKey" } },
							title: "t",
							version: "1",
						},
						sdk: true,
						tree: false,
					},
				}),
				dir,
			)
		} finally {
			warn.mockRestore()
			error.mockRestore()
		}
		expect(messages.filter((m) => m.includes("UNKNOWN_SECURITY_SCHEME") || m.includes("not declared"))).toEqual([])
	}, 60_000)
})
