/**
 * The generated MCP server as files (bit 18): a package an agent's MCP client starts as a command. Its TypeScript under
 * `src/` (the entry, the tools, the vendored runtime joined into one module, the API's own TS SDK under `src/sdk/`), and
 * the same code with its types erased under `dist/`, CommonJS, which the package's bin runs: node refuses to strip
 * types under an installed package's folder, so an installed server must ship JavaScript. The erasure is jiti's
 * transform, gen's own dependency, deterministic whichever runtime generates. No dependency, no build step.
 */
import { createJiti } from "jiti"
import { type OpenApiDocument, toIR } from "../../ir/build.ts"
import type { IR } from "../../ir/model.ts"
import { binaryNameOf } from "../cli/module.ts"
import { tsString } from "../shared/escape.ts"
import { generateSdk } from "../ts/sdk.ts"
import { literal } from "./literal.ts"
import { mcpRuntimeSource } from "./runtime.ts"
import { toolsOf, type ToolSpec, untoolable } from "./tools.ts"

export type McpServerOptions = {
	/** the server's name: lowercase words joined by `-`, at most 60 characters; by default the document title's */
	readonly name?: string
	/** the prefix of its environment variables; by default the name's words, uppercased, joined by `_` */
	readonly envPrefix?: string
}

export type GeneratedMcpServer = {
	readonly files: Readonly<Record<string, string>>
	/** each operation marked x-mcp that no tool serves yet: its id and what it is */
	readonly skipped: readonly string[]
}

/* a name leaves room for the bin's `-mcp`; a prefix is uppercase words joined by `_` */
const NAME = /^(?=.{1,60}$)[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/
const ENV_PREFIX = /^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*$/
/* a version npm accepts in a package.json */
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/

const MARKER = "// Code generated by honey. DO NOT EDIT."

/** The options with their defaults filled, each refused unless it matches its grammar (F2). */
function resolved(options: McpServerOptions, title: string | undefined) {
	const name = options.name ?? binaryNameOf(title)
	if (!NAME.test(name)) throw new Error(`Invalid name: ${JSON.stringify(name)}`)
	const envPrefix = options.envPrefix ?? name.toUpperCase().replaceAll("-", "_")
	if (!ENV_PREFIX.test(envPrefix)) throw new Error(`Invalid envPrefix: ${JSON.stringify(envPrefix)}`)
	return { envPrefix, name }
}

/** The entry: the tools served over stdio under the server's name and version. */
const entrySource = (app: { name: string; version: string; envPrefix: string }, ir: IR) =>
	`${MARKER}

// The ${app.name} MCP server: its tools over stdio, for the MCP client that starts it. The API key is
// $${app.envPrefix}_API_KEY, sent as the API's scheme says; the API is at $${app.envPrefix}_BASE_URL, else its first server, and
// with neither it refuses to start. A call waits $${app.envPrefix}_TIMEOUT_MS milliseconds at most, 30 s by default, an
// event stream's collect too. SIGINT and SIGTERM abort every call in flight and exit 0, no later reply written.
// The API's answer is read at most 1 MiB, past it refused.
import { BYTES_MAX, bindTools, createSession, serveStdio } from "./mcp.runtime"
import { Api } from "./sdk/api.index.gen"
import { toolSpecs } from "./tools.gen"

const key = process.env[${tsString(`${app.envPrefix}_API_KEY`)}] ?? ""
const timeout = process.env[${tsString(`${app.envPrefix}_TIMEOUT_MS`)}] || "30000"
if (!/^[1-9][0-9]{0,9}$/.test(timeout) || Number(timeout) > 2147483647) {
	process.stderr.write(${tsString(`Invalid $${app.envPrefix}_TIMEOUT_MS: a whole number of milliseconds, 1 to 2147483647\n`)})
	process.exit(1)
}
const baseURL = process.env[${tsString(`${app.envPrefix}_BASE_URL`)}] || ${tsString(ir.servers[0] ?? "")}
if (baseURL === "") {
	process.stderr.write(${tsString(`No API to call: set $${app.envPrefix}_BASE_URL, since the API names no server\n`)})
	process.exit(1)
}
const config = {
	baseURL,
	headers: key === "" ? {} : { ${tsString(ir.auth.headerName)}: ${tsString(ir.auth.prefix)} + key },
	maxResponseBytes: BYTES_MAX,
	throwOnError: false,
	timeout: Number(timeout),
}
const client = new Api(config)
/* a collect's own client: its answer tells that collect its stream opened */
const opening = (seen: () => void) => new Api({ ...config, onResponse: [() => void seen()] })
const stop = new AbortController()
for (const signal of ["SIGINT", "SIGTERM"]) process.once(signal, () => stop.abort())

void serveStdio(
	createSession(
		{ name: ${tsString(app.name)}, version: ${tsString(app.version)} },
		bindTools(toolSpecs, client, { opening, secret: key, timeout: Number(timeout) }),
	),
	undefined,
	stop.signal,
).then(() => stop.signal.aborted && process.stdout.write("", () => process.exit(0)))
`

/** tools.gen.ts: every tool's spec, as data the runtime binds to the SDK client. */
const toolsSource = (specs: readonly ToolSpec[]) =>
	`${MARKER}\n\nimport type { ToolSpec } from "./mcp.runtime"\n\nexport const toolSpecs: readonly ToolSpec[] = ${literal(specs)}\n`

/** The package: its bin the compiled entry, no dependency. */
const packageJson = (name: string, version: string) =>
	`${JSON.stringify(
		{
			bin: { [`${name}-mcp`]: "dist/server.js" },
			description: `The ${name} API as MCP tools`,
			engines: { node: ">=22" },
			files: ["dist", "src"],
			name: `${name}-mcp`,
			type: "module",
			version: SEMVER.test(version) ? version : "0.0.0",
		},
		null,
		"\t",
	)}\n`

/** `source` with its types erased, as CommonJS; the entry gets the shebang a bin needs. */
export function erased(path: string, source: string): string {
	const jiti = createJiti(import.meta.url, { fsCache: false, moduleCache: false })
	const code = jiti.transform({ filename: path, source, ts: true })
	/* jiti reports a parse error as code that throws it on load: refused here, so no broken twin is ever written */
	if (code.includes("__JITI_ERROR__"))
		throw new Error(`${path} does not parse: ${code.slice(code.indexOf("{"), code.lastIndexOf("}") + 1)}`)
	return `${path === "src/server.ts" ? "#!/usr/bin/env node\n" : ""}${code.trimEnd()}\n`
}

/** The MCP server for `document`, as its package's files. */
export function generateMcpServer(
	document: Record<string, unknown>,
	options: McpServerOptions = {},
): GeneratedMcpServer {
	const ir = toIR(document as OpenApiDocument, { deriveOperationIds: true })
	const { envPrefix, name } = resolved(options, ir.info.title)
	const version = ir.info.version ?? "0.0.0"
	const specs = toolsOf(ir)
	if (specs.length === 0)
		throw new Error(
			ir.operations.some((op) => op.extensions.mcp === true)
				? "No operation marked x-mcp is one a tool can call yet: nothing to serve"
				: "No operation is marked x-mcp: nothing to serve",
		)
	const sdk = generateSdk(document, { name: "Api", stem: "api" })
	const source: Record<string, string> = {
		"src/mcp.runtime.ts": mcpRuntimeSource(),
		"src/server.ts": entrySource({ envPrefix, name, version }, ir),
		"src/tools.gen.ts": toolsSource(specs),
		...Object.fromEntries(Object.entries(sdk.files).map(([file, text]) => [`src/sdk/${file}`, text])),
	}
	const compiled = Object.fromEntries(
		Object.entries(source).map(([path, text]) => [
			path.replace(/^src\//, "dist/").replace(/\.ts$/, ".js"),
			erased(path, text),
		]),
	)
	return {
		files: {
			"package.json": packageJson(name, version),
			...source,
			"dist/package.json": `${JSON.stringify({ type: "commonjs" }, null, "\t")}\n`,
			...compiled,
		},
		skipped: ir.operations.flatMap((op) => {
			const what = op.extensions.mcp === true ? untoolable(op) : undefined
			return what === undefined ? [] : [`${op.id} (${what})`]
		}),
	}
}
