/**
 * The CLI's cmd package as files (bit 17): root.go wires the App and its top-level commands; client.go builds the SDK
 * client from the run's settings (the target announced, the redirect policy passed, --verbose's hooks) and returns an
 * answer outside 2xx as cli.APIError; one `<name>_cmds.go` per top-level command, a name the package already holds
 * suffixed; each file's imports in gofmt's groups, only the packages its code names, cobra only where it is named;
 * every file gofmt-clean as written.
 */
import { spawnSync } from "node:child_process"
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { describe, expect, it } from "vitest"
import { toIR, type OpenApiDocument } from "../../ir/build.ts"
import { sdkModel } from "../../ir/sdk-model.ts"
import { goCacheDir, gofmtPath, withGo } from "../go/__fixtures__/go-env.ts"
import { goCallPlans } from "../go/sdk.ts"
import { commandTree } from "./commands.ts"
import { discoveryEntries } from "./discovery.ts"
import { cmdFiles } from "./layout.ts"
import { SPAWN_TIMEOUT } from "../../gen/__fixtures__/spawn-timeout.ts"

const OK = { 200: { content: { "application/json": { schema: { type: "object" } } }, description: "ok" } }
const ID = { in: "path", name: "id", required: true, schema: { type: "string" } }

/**
 * A document with four top-level commands, `root` among them; a summary naming packages only inside text; an any body,
 * whose command names encoding/json beside net/http.
 */
const document = (server: boolean) => ({
	info: { title: "Shop", version: "1" },
	openapi: "3.1.0",
	...(server ? { servers: [{ url: "https://api.shop.test" }] } : {}),
	paths: {
		"/items": { get: { operationId: "items.list", responses: OK, summary: "List items; see errors.Is and http.Get" } },
		"/raw": {
			post: {
				operationId: "raw.send",
				requestBody: { content: { "application/json": { schema: {} } } },
				responses: OK,
			},
		},
		"/root": { get: { operationId: "root.get", responses: OK } },
		"/users/{id}": { get: { operationId: "users.get", parameters: [ID], responses: OK } },
	},
})

/** layout's files for `document(server)`, as module.ts builds them. */
function files(server = true): Record<string, string> {
	const spec = document(server)
	const ir = toIR(spec as OpenApiDocument, { deriveOperationIds: true })
	const model = sdkModel(ir)
	const nodes = commandTree(model.ops, goCallPlans(spec))
	const app = { binaryName: "shop", envPrefix: "SHOP", modulePath: "example.com/shop", short: "Shop" }
	return cmdFiles(app, ir, nodes, discoveryEntries(nodes, model))
}

const MARKER = "// Code generated by honey. DO NOT EDIT.\n\n"

/** A file's import block: its lines, groups apart by a blank line. */
const importsIn = (text: string) => /\nimport \(\n([\s\S]*?)\n\)\n/.exec(text)?.[1]?.split("\n") ?? []

describe("cmd/root.go (bit 17)", () => {
	// v0: b36c42fa3b
	it("wires the App (name, title, prefix, server, discovery, skill) and each top-level command, in path order", () => {
		expect(files()["cmd/root.go"]).toBe(
			`${MARKER}// Package cmd holds the shop commands.
package cmd

import (
	"github.com/spf13/cobra"

	"example.com/shop/internal/cli"
)

// Root is the shop command, skill the agent skill it ships; every other command hangs under it.
func Root(skill string) *cobra.Command {
	return cli.Root(cli.App{Name: "shop", Short: "Shop", EnvPrefix: "SHOP", Server: "https://api.shop.test", Discovery: discovery, Skill: skill}, newItemsCmd(), newRawCmd(), newRootCmd(), newUsersCmd())
}
`,
		)
	})

	it("names no server where the API declares none", () => {
		expect(files(false)["cmd/root.go"]).toContain(
			'cli.App{Name: "shop", Short: "Shop", EnvPrefix: "SHOP", Discovery: discovery, Skill: skill}',
		)
	})
})

const CLIENT = `${MARKER}package cmd

import (
	"errors"

	"github.com/spf13/cobra"

	"example.com/shop/internal/cli"
	"example.com/shop/internal/sdk"
)

// newClient is the API client the run's settings configure.
func newClient(c *cobra.Command) (*sdk.Client, error) {
	s, err := cli.Settings(c)
	if err != nil {
		return nil, err
	}
	s.Announce()
	return sdk.NewClient(sdk.Config{
		BaseURL: s.BaseURL, BearerToken: s.APIKey, Headers: s.Headers, Timeout: s.Timeout,
		Redirect: sdk.RedirectPolicy(s.Redirect),
		OnRequest: []func(*sdk.RequestContext) error{func(rc *sdk.RequestContext) error {
			s.LogRequest(rc.Method, rc.URL, rc.Headers)
			return nil
		}},
		OnResponse: []func(*sdk.ResponseContext) error{func(rc *sdk.ResponseContext) error {
			s.LogResponse(rc.Status, rc.Headers)
			return nil
		}},
	}), nil
}

// failed is err as the CLI reports it: an answer outside 2xx with its status, error key and message.
func failed(err error) error {
	var answer *sdk.ClientError
	if errors.As(err, &answer) {
		return &cli.APIError{Status: answer.StatusCode, Key: string(answer.Key), Message: answer.Message, Err: err}
	}
	return err
}
`

describe("cmd/client.go (bit 17)", () => {
	// v0: d7c82d4b2a
	it("configures the SDK client by the run's settings: the target announced, the redirect policy, --verbose's hooks, an answer outside 2xx as cli.APIError", () => {
		expect(files()["cmd/client.go"]).toBe(CLIENT)
	})

	it("refuses a run with no base URL as a usage error where the API declares no server", () => {
		const refusal = [
			"\ts.Announce()",
			'\tif s.BaseURL == "" {',
			'\t\treturn nil, cli.Usage("no base URL: set --base-url, $SHOP_BASE_URL or base_url in the config file")',
			"\t}",
		]
		const client = files(false)["cmd/client.go"] ?? ""
		expect([
			client.includes(refusal.slice(1).join("\n")),
			client.indexOf(refusal[1] as string) < client.indexOf(refusal[0] as string),
		]).toEqual([true, true])
	})
})

describe("the cmd files (bit 17)", () => {
	// v0: 5a5855b2dc
	// v0: 06b9246d0f
	it("writes one <name>_cmds.go per top-level command beside root.go, client.go and discovery.go, a held name suffixed", () => {
		const all = files()
		expect([Object.keys(all).sort(), all["cmd/root2_cmds.go"]?.includes("func newRootCmd() *cobra.Command {")]).toEqual(
			[
				[
					"cmd/client.go",
					"cmd/discovery.go",
					"cmd/items_cmds.go",
					"cmd/raw_cmds.go",
					"cmd/root.go",
					"cmd/root2_cmds.go",
					"cmd/users_cmds.go",
				],
				true,
			],
		)
	})

	it("holds a group and every command below it in its file", () => {
		const items = files()["cmd/items_cmds.go"] ?? ""
		expect([
			items.includes("func newItemsCmd() *cobra.Command {"),
			items.includes("func newItemsListCmd() *cobra.Command {"),
		]).toEqual([true, true])
	})

	it("opens every file with the generated marker, apart from the package by a blank line", () => {
		expect(Object.values(files()).filter((text) => !text.startsWith(MARKER))).toEqual([])
	})
})

describe("the cmd files' imports (bit 17)", () => {
	it("groups the standard library, cobra and the module's own packages as gofmt does, each sorted", () => {
		expect(importsIn(files()["cmd/raw_cmds.go"] ?? "")).toEqual([
			'\t"encoding/json"',
			'\t"net/http"',
			"",
			'\t"github.com/spf13/cobra"',
			"",
			'\t"example.com/shop/internal/cli"',
			'\t"example.com/shop/internal/sdk"',
		])
	})

	it("imports only what a file's code names: a package named inside a string never, cobra only where named", () => {
		expect([importsIn(files()["cmd/discovery.go"] ?? ""), importsIn(files()["cmd/root.go"] ?? "")]).toEqual([
			['\t"example.com/shop/internal/cli"'],
			['\t"github.com/spf13/cobra"', "", '\t"example.com/shop/internal/cli"'],
		])
	})
})

describe.skipIf(!withGo())("the cmd files, as gofmt reads them (bit 17)", () => {
	it("writes every cmd file gofmt-clean as written, with a server and without", { timeout: SPAWN_TIMEOUT }, () => {
		const dir = mkdtempSync(join(goCacheDir("tmp"), "layout-"))
		for (const declared of [true, false])
			for (const [name, text] of Object.entries(files(declared))) {
				const path = join(dir, String(declared), name)
				mkdirSync(dirname(path), { recursive: true })
				writeFileSync(path, text)
			}
		const listed = spawnSync(gofmtPath(), ["-l", dir], { encoding: "utf8" })
		expect([listed.status, listed.stdout, listed.stderr]).toEqual([0, "", ""])
	})
})
