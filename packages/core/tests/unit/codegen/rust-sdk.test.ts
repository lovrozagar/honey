/** Write generated SDK sources to a temp dir, run `fn`, then delete the sources (artifacts live in CARGO_TARGET_DIR). */
function withTempSdk(prefix: string, files: Record<string, string>, fn: (dir: string) => void): void {
	const dir = mkdtempSync(join(tmpdir(), prefix))
	try {
		for (const [relPath, content] of Object.entries(files)) {
			const fullPath = join(dir, relPath)
			mkdirSync(join(fullPath, ".."), { recursive: true })
			writeFileSync(fullPath, content, "utf8")
		}
		fn(dir)
	} finally {
		rmSync(dir, { force: true, recursive: true })
	}
}

/* ── Rust bracket-balance helper ──
 * Verifies {}, (), [], <> are balanced in emitted Rust source.
 * Skips content inside:
 *   - raw string literals  r#"..."#
 *   - regular strings      "..."
 *   - line comments        // ...\n   (also ///\n)
 *   - block comments       /* ... * /
 * Tracks <> for Rust generics.
 */
function assertBalancedRustBrackets(src: string): void {
	let braces = 0
	let parens = 0
	let brackets = 0
	let angles = 0
	let i = 0
	while (i < src.length) {
		/* block comment */
		if (src[i] === "/" && src[i + 1] === "*") {
			i += 2
			while (i < src.length && !(src[i] === "*" && src[i + 1] === "/")) i++
			i += 2
			continue
		}
		/* line comment (includes ///) */
		if (src[i] === "/" && src[i + 1] === "/") {
			while (i < src.length && src[i] !== "\n") i++
			continue
		}
		/* raw string literal r#"..."# */
		if (src[i] === "r" && src[i + 1] === "#" && src[i + 2] === '"') {
			i += 3
			while (i < src.length && !(src[i] === '"' && src[i + 1] === "#")) i++
			i += 2
			continue
		}
		/* regular string literal */
		if (src[i] === '"') {
			i++
			while (i < src.length && src[i] !== '"') {
				if (src[i] === "\\") i++
				i++
			}
			i++
			continue
		}
		if (src[i] === "{") braces++
		else if (src[i] === "}") braces--
		else if (src[i] === "(") parens++
		else if (src[i] === ")") parens--
		else if (src[i] === "[") brackets++
		else if (src[i] === "]") brackets--
		else if (src[i] === "<") angles++
		else if (src[i] === ">") angles--
		i++
	}
	expect(braces, "unbalanced {}").toBe(0)
	expect(parens, "unbalanced ()").toBe(0)
	expect(brackets, "unbalanced []").toBe(0)
	expect(angles, "unbalanced <>").toBe(0)
}

