/**
 * The crate's manifest and lock (contract 18 §5.2). `Cargo.toml` declares the trimmed dependency set (G9)
 * at caret floors equal to the locked versions (Fb7), `tokio-tungstenite` only for a WebSocket or realtime
 * API (Fb3). `Cargo.lock` is cut from the one committed template: its root entry renamed to the crate, and
 * for an HTTP-only crate every package only `tokio-tungstenite` reached dropped, each reference then written
 * as cargo writes it, so `--locked` accepts the lock as it is.
 */
import { compareCodeUnits } from "../shared/lang.ts"

/** The emitted `rust-version`: the toolchain floor every SDK builds with (Fb2). */
export const RUST_VERSION = "1.85"

/** The emitted edition, which the floor forces. */
export const EDITION = "2024"

/** The crate's name and version as Cargo.toml and the lock root carry them. */
export type CrateIdentity = { readonly name: string; readonly version: string }

/* the dependency the WebSocket and realtime runtime files need, and only they */
const WEBSOCKET = "tokio-tungstenite"

/* each dependency's requirement line, in name order: the floors are the template lock's versions */
const DEPENDENCIES: readonly (readonly [name: string, requirement: string])[] = [
	["bytes", '"1.12.1"'],
	["futures-util", '{ version = "0.3.34", default-features = false, features = ["std", "sink"] }'],
	[
		"reqwest",
		'{ version = "0.13.5", default-features = false, features = ["rustls", "http2", "json", "stream", "gzip", "deflate"] }',
	],
	["serde", '{ version = "1.0.229", features = ["derive"] }'],
	["serde_json", '"1.0.154"'],
	["tokio", '{ version = "1.53.3", features = ["rt", "macros", "time", "sync"] }'],
	[WEBSOCKET, '{ version = "0.30.0", default-features = false, features = ["connect", "rustls-tls-native-roots"] }'],
	["url", '"2.5.8"'],
]

const MARKER = "# @generated by honey. DO NOT EDIT."

/* a semver version: it lands inside a TOML string, so nothing else may */
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/

/** `name` as a crate name, else throws: lower case, a letter first, then letters, digits, `_` and `-`. */
export function validateCrateName(name: string): string {
	if (!/^[a-z][a-z0-9_-]*$/.test(name)) throw new Error(`Invalid crate name: ${JSON.stringify(name)}`)
	return name
}

/** `version` as a crate version, else throws: a semver version. */
export function validateCrateVersion(version: string): string {
	if (!SEMVER.test(version)) throw new Error(`Invalid crate version: ${JSON.stringify(version)}`)
	return version
}

/** Cargo.toml: the package at the floor, the library `sdk`, the dependencies (`tokio-tungstenite` only when `ws`). */
export function cargoToml(crate: CrateIdentity, ws: boolean): string {
	const dependencies = DEPENDENCIES.filter(([name]) => ws || name !== WEBSOCKET)
	return [
		MARKER,
		"[package]",
		`name = "${crate.name}"`,
		`version = "${crate.version}"`,
		`edition = "${EDITION}"`,
		`rust-version = "${RUST_VERSION}"`,
		"",
		"[lib]",
		'name = "sdk"',
		'path = "src/lib.rs"',
		"",
		"[dependencies]",
		...dependencies.map(([name, requirement]) => `${name} = ${requirement}`),
		"",
	].join("\n")
}

/** One `[[package]]` of a lock: its text, and what the cut reads of it. */
type Package = {
	readonly name: string
	readonly version: string
	readonly root: boolean
	readonly dependencies: readonly string[]
	readonly text: string
}

const SEPARATOR = "\n[[package]]\n"

/** The value of `key = "…"` in a package's text. */
const field = (text: string, key: string) => new RegExp(`^${key} = "([^"]*)"$`, "m").exec(text)?.[1] as string

function parsed(text: string): Package {
	return {
		dependencies: [...text.matchAll(/^ "([^"]+)",$/gm)].map((match) => match[1] as string),
		name: field(text, "name"),
		root: !/^source = /m.test(text),
		text,
		version: field(text, "version"),
	}
}

/** The package a dependency reference (`name`, `name version` or `name version (source)`) names. */
function resolve(packages: readonly Package[], reference: string): Package {
	const [name, version] = reference.split(" ")
	return packages.find((p) => p.name === name && (version === undefined || p.version === version)) as Package
}

/** `root` and every package it reaches. */
function reachable(packages: readonly Package[], root: Package): Package[] {
	const seen = new Set<Package>()
	const stack = [root]
	for (let at = stack.pop(); at !== undefined; at = stack.pop()) {
		if (seen.has(at)) continue
		seen.add(at)
		stack.push(...at.dependencies.map((reference) => resolve(packages, reference)))
	}
	return packages.filter((p) => seen.has(p))
}

/** A dependency list line as cargo writes it: the version only while another version of the name is locked. */
function referenced(kept: readonly Package[], reference: string): string {
	const name = reference.split(" ")[0] as string
	return kept.filter((p) => p.name === name).length > 1 ? reference : name
}

/** `p`'s text with every dependency reference rewritten for `kept`. */
const rewritten = (p: Package, kept: readonly Package[]) =>
	p.text.replace(/^ "([^"]+)",$/gm, (_, reference: string) => ` "${referenced(kept, reference)}",`)

/** The root entry as `crate`, without `tokio-tungstenite` unless `ws`. */
function rootOf(root: Package, crate: CrateIdentity, ws: boolean): Package {
	const named = root.text
		.replace(/^name = ".*"$/m, `name = "${crate.name}"`)
		.replace(/^version = ".*"$/m, `version = "${crate.version}"`)
	return parsed(ws ? named : named.replace(new RegExp(`^ "${WEBSOCKET}( [^"]*)?",\\n`, "m"), ""))
}

/**
 * The crate's Cargo.lock from `template`: the root entry as `crate`, at its name's place among the packages;
 * without `ws`, `tokio-tungstenite` and every package only it reached gone. A crate named like a locked
 * package is refused: the lock could not tell the two apart.
 */
export function cargoLock(template: string, crate: CrateIdentity, ws: boolean): string {
	const [head, ...blocks] = template.split(SEPARATOR)
	const packages = blocks.map(parsed)
	if (packages.some((p) => !p.root && p.name === crate.name))
		throw new Error(`Invalid crate name: ${JSON.stringify(crate.name)} is a dependency's name`)
	const all = packages.map((p) => (p.root ? rootOf(p, crate, ws) : p))
	const kept = reachable(all, all.find((p) => p.root) as Package)
	const ordered = kept.toSorted((a, b) => compareCodeUnits(a.name, b.name))
	return [head, ...ordered.map((p) => rewritten(p, kept))].join(SEPARATOR)
}
