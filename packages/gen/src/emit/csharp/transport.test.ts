/**
 * The vendored C# runtime's reader (contract 45 §5, §7.7; contract 50 §1, §2): the file set each feature mix ships,
 * the core for every SDK, the WebSocket files for a WebSocket or realtime API and the realtime files for a realtime
 * API; each file as committed, one `namespace Honey.Runtime;` line swapped for the SDK's own namespace (Fb2), marked
 * on line 1 and at most 300 lines; the files read from `runtime/csharp/` on every call (the F8 target); and the
 * top-level type names the type scope reserves: the exception hierarchy of `Errors.cs` (Fb14), the public stream
 * surface in its feature files, and `Transport`, partial across the files that add its stream entry points.
 */
import { readdirSync, readFileSync } from "node:fs"
