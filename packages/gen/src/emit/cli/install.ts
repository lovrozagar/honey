/**
 * The CLI's install scripts (bit 17 phase g, D8 of the release program): `install.sh` (Linux and macOS) and
 * `install.ps1` (Windows), written by installgen from the layout `release.ts` publishes. Each reads the latest tag
 * from the release's `version.txt` (a version by `<PREFIX>_VERSION` over it), downloads this platform's archive
 * `<bin>_<os>_<arch>` and `checksums.txt` from the repository's GitHub Releases, checks `checksums.txt` with cosign
 * against the repository's release workflow on that exact tag when cosign is on PATH (`<PREFIX>_INSTALL_VERIFY=require`
 * refuses without it), checks the archive's sha256 against it, and installs the binary to `<PREFIX>_INSTALL_DIR`,
 * `~/.local/bin` by default. installgen holds the scripts' hardening and their tests; this file holds the layout.
 * Beside the scripts goes `installgen.config.mts`, the same config as a file, which the release workflow's
 * `installgen check` reads to prove a release serves every file the scripts fetch: both are written from one
 * `layout`, and a test holds the file's scripts byte for byte to the emitted ones. Without a repository there is
 * nowhere to download from, so there are no scripts and no config.
 */
import { generateInstallers, type InstallgenConfig } from "@lovrozagar/installgen"

/** The options the scripts are written from: the binary, its repository, the variables' prefix, the scripts' URL. */
export type InstallApp = {
	readonly bin: string
	readonly repo: string
	readonly prefix: string
	readonly installUrl: string
}

/** The issuer of the OIDC token a GitHub Actions run signs with. */
export const ISSUER = "https://token.actions.githubusercontent.com"

/** The installgen release the scripts are written by, and the release workflow's `npx` runs `check` with. */
export const INSTALLGEN_VERSION = "0.3.0"

/** The name `installgen` finds its config by, in the module's root, where the release workflow runs it. */
export const INSTALLGEN_CONFIG = "installgen.config.mts"

/**
 * The layout both configs spell: every plain value, and the fixed pieces of each path around its tokens. The pieces
 * hold only the binary name and the repository, each refused at generate unless it matches its grammar (lowercase
 * words joined by `-`; GitHub's owner/name), so the config file writes them into its template literals as they are.
 */
function layout(app: InstallApp, base: string) {
	return {
		asset: [`download/`, `/${app.bin}_`, `_`] as const,
		checksums: [`download/`, `/checksums.txt`] as const,
		identity: [`https://github.com/${app.repo}/.github/workflows/release.yml@refs/tags/`] as const,
		plain: {
			baseUrl: base,
			envPrefix: app.prefix,
			installDir: "~/.local/bin",
			latestPath: "latest/download/version.txt",
			message: `Run \`${app.bin} --help\` to get started.`,
			name: app.bin,
			scriptUrls: { ps1: `${app.installUrl}/install.ps1`, sh: `${app.installUrl}/install.sh` },
		},
	}
}

/** installgen's config for `app`, its files under `base` (the repository's GitHub Releases outside a test). */
export function installerConfig(app: InstallApp, base = `https://github.com/${app.repo}/releases`): InstallgenConfig {
	const { asset, checksums, identity, plain } = layout(app, base)
	return {
		...plain,
		assetPath: ({ arch, os, tag }) =>
			`${asset[0]}${tag}${asset[1]}${os}${asset[2]}${arch}${os === "windows" ? ".zip" : ".tar.gz"}`,
		checksumsPath: ({ tag }) => `${checksums[0]}${tag}${checksums[1]}`,
		signature: { identity: ({ tag }) => `${identity[0]}${tag}`, issuer: ISSUER },
	}
}

/**
 * `installgen.config.mts` for `app`: `installerConfig`'s config as a module installgen loads with no local install
 * (its one import is type-only, which Node 22.18+ strips), so `npx @lovrozagar/installgen@<version> check` runs in the
 * module's root.
 */
export function installgenConfigFile(app: InstallApp): string {
	const { asset, checksums, identity, plain } = layout(app, `https://github.com/${app.repo}/releases`)
	const value = (key: keyof typeof plain) => `\t${key}: ${JSON.stringify(plain[key])},\n`
	return `// Code generated by honey. DO NOT EDIT.
// installgen's config for ${app.bin}'s install scripts, as honey wrote them: the release workflow runs
// \`npx @lovrozagar/installgen@${INSTALLGEN_VERSION} check\` with it to prove a release serves every file they fetch.
import type { InstallgenConfig } from "@lovrozagar/installgen"

export default {
	assetPath: ({ arch, os, tag }) =>
		\`${asset[0]}\${tag}${asset[1]}\${os}${asset[2]}\${arch}\${os === "windows" ? ".zip" : ".tar.gz"}\`,
${value("baseUrl")}	checksumsPath: ({ tag }) => \`${checksums[0]}\${tag}${checksums[1]}\`,
${value("envPrefix")}${value("installDir")}${value("latestPath")}${value("message")}${value("name")}${value("scriptUrls")}	signature: {
		identity: ({ tag }) => \`${identity[0]}\${tag}\`,
		issuer: ${JSON.stringify(ISSUER)},
	},
} satisfies InstallgenConfig
`
}

/** `install.sh`, `install.ps1` and `installgen.config.mts` for `app`, by file name. */
export function installFiles(app: InstallApp): Record<string, string> {
	const { ps1, sh } = generateInstallers(installerConfig(app))
	/* every platform is configured, so installgen writes both */
	const scripts: [string, string | undefined][] = [
		["install.ps1", ps1],
		["install.sh", sh],
	]
	return {
		...Object.fromEntries(scripts.filter((entry): entry is [string, string] => entry[1] !== undefined)),
		[INSTALLGEN_CONFIG]: installgenConfigFile(app),
	}
}
