/**
 * The generated MCP server as files (bit 18): a package an agent's MCP client starts as a command. Its TypeScript under
 * `src/` (the entry, the tools, the vendored runtime joined into one module, the API's own TS SDK under `src/sdk/`), and
 * the same code with its types erased under `dist/`, ES modules, which the package's bin runs: node refuses to strip
 * types under an installed package's folder, so an installed server must ship JavaScript. The erasure is oxc's
 * transform, the one the TS package compiles with (plan 39 8.3), deterministic whichever runtime generates. No
 * dependency, no build step. With an `mcpName`, the MCP registry's server.json beside package.json (registry.ts).
 */
import { type OpenApiDocument, toIR } from "../../ir/build.ts"
import type { IR } from "../../ir/model.ts"
import { binaryNameOf } from "../cli/module.ts"
import { checked, type Metadata, NPM_NAME, type PackageIdentity, packageOn, SEMVER } from "../shared/metadata.ts"
import { tsString } from "../shared/escape.ts"
import { compiled, npmFields } from "../ts/package.ts"
import { generateSdk } from "../ts/sdk.ts"
import { literal } from "./literal.ts"
import { serverJson } from "./registry.ts"
import { mcpRuntimeSource } from "./runtime.ts"
import { toolsOf, type ToolSpec, untoolable } from "./tools.ts"

export type McpServerOptions = {
	/** the server's name: lowercase words joined by `-`, at most 60 characters; by default the document title's */
	readonly name?: string
	/** the prefix of its environment variables; by default the name's words, uppercased, joined by `_` */
	readonly envPrefix?: string
	/** the version its server info and package.json carry, one npm accepts; by default the document's */
	readonly version?: string
	/** the npm name it publishes under; `<name>-mcp` by default, the bin's name either way */
	readonly packageName?: string
	/** the MCP registry's name for it, `namespace/name` (`io.github.acme/shop`): package.json's `mcpName`, which the
	 * registry checks the npm package by; none by default */
	readonly mcpName?: string
}

export type GeneratedMcpServer = {
	readonly files: Readonly<Record<string, string>>
	/** the package as npm lists it, and as the MCP registry does when it has an `mcpName` */
	readonly packages: readonly PackageIdentity[]
	/** each operation marked x-mcp that no tool serves: its id and what it is */
	readonly skipped: readonly string[]
}

/* a name leaves room for the bin's `-mcp`; a prefix is uppercase words joined by `_` */
const NAME = /^(?=.{1,60}$)[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/
const ENV_PREFIX = /^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*$/
/* a server name as the MCP registry's server.json schema (2025-12-11) takes it: a reverse-DNS namespace, `/`, a name */
const MCP_NAME = /^(?=.{3,200}$)[a-zA-Z0-9.-]+\/[a-zA-Z0-9._-]+$/

const MARKER = "// Code generated by honey. DO NOT EDIT."

/** The options with their defaults filled, each refused unless it matches its grammar (F2). */
export function resolved(options: McpServerOptions, title: string | undefined) {
	const name = options.name ?? binaryNameOf(title)
	if (!NAME.test(name)) throw new Error(`Invalid name: ${JSON.stringify(name)}`)
	const envPrefix = options.envPrefix ?? name.toUpperCase().replaceAll("-", "_")
	if (!ENV_PREFIX.test(envPrefix)) throw new Error(`Invalid envPrefix: ${JSON.stringify(envPrefix)}`)
	if (options.version !== undefined && !SEMVER.test(options.version))
		throw new Error(`Invalid version: ${JSON.stringify(options.version)}`)
	return { envPrefix, name }
}

/** The server's name, version and environment prefix, and whether a tool of it takes a file. */
type App = { readonly name: string; readonly version: string; readonly envPrefix: string; readonly files: boolean }

/* a cap in bytes from the environment: a whole number, its default when unset */
const BYTES = `const bytes = (name: string, fallback: string): number => {
	const text = process.env[name] || fallback
	if (/^(?:0|[1-9][0-9]{0,14})$/.test(text)) return Number(text)
	process.stderr.write("Invalid $" + name + ": a whole number of bytes\\n")
	return process.exit(1)
}`

/** A file-taking server's reader, its root and caps from the environment, the root refused at start unless a directory. */
const filesSource = (prefix: string) => `const inline = bytes(${tsString(`${prefix}_MAX_INLINE_BYTES`)}, "1048576")
const read = fileReader(
	process.env[${tsString(`${prefix}_FILE_ROOT`)}] || process.cwd(),
	bytes(${tsString(`${prefix}_MAX_FILE_BYTES`)}, "52428800"),
)
if (read === undefined) {
	process.stderr.write(${tsString(`Invalid $${prefix}_FILE_ROOT: not a directory\n`)})
	process.exit(1)
}
`

/** The entry's note on files, when a tool takes one. */
const filesNote = (prefix: string) => `
// A file argument is inline (the file-uploads extension's FileInput, at most $${prefix}_MAX_INLINE_BYTES decoded in one
// call, 1 MiB by default) or a path under $${prefix}_FILE_ROOT (the working directory by default), read whole, at most
// $${prefix}_MAX_FILE_BYTES (50 MiB by default). An upload (a FileInput without data) and a URL are a mounted server's.`

/** The entry's note on --http. */
const httpNote = (prefix: string) => `//
// With --http it serves Streamable HTTP at /mcp instead, on --host (127.0.0.1 by default; another needs --expose,
// which also answers for any Host name) and --port (8000 by default; 0 picks one), and says where on stderr. Every
// request sends $${prefix}_MCP_TOKEN as \`Authorization: Bearer\`; with no token it refuses to start unless
// --no-auth, which --expose refuses. The token is never sent to the API. A browser Origin other than the server's own is
// refused unless listed in $${prefix}_MCP_ORIGINS (comma-separated); a body is read at most
// $${prefix}_MAX_BODY_BYTES, 4 MiB by default. A file argument over HTTP is inline: no path is read.`

/** The command line read, each refusal at start, and $<PREFIX>_MCP_TOKEN: stdio with none, Streamable HTTP with --http. */
const flagsSource = (prefix: string) => `const refuse = (message: string): never => {
	process.stderr.write(message + "\\n")
	return process.exit(1)
}
/* the command line: nothing for stdio; --http [--port N] [--host H] [--no-auth] [--expose] for Streamable HTTP */
const flags = new Map<string, string>()
const args = process.argv.slice(2)
for (let at = 0; at < args.length; at++) {
	const arg = args[at] as string
	if (!["--http", "--port", "--host", "--no-auth", "--expose"].includes(arg) || flags.has(arg))
		refuse("Unknown argument: " + arg)
	flags.set(arg, arg === "--port" || arg === "--host" ? (args[++at] ?? "") : "")
}
const http = flags.has("--http")
if (flags.size > 0 && !http) refuse("--port, --host, --no-auth and --expose serve HTTP: pass --http")
const token = process.env[${tsString(`${prefix}_MCP_TOKEN`)}] || undefined
if (http && token === undefined && !flags.has("--no-auth"))
	refuse(${tsString(`No token: set $${prefix}_MCP_TOKEN, which every request sends as Authorization: Bearer, or pass --no-auth`)})
if (token !== undefined && flags.has("--no-auth")) refuse(${tsString(`--no-auth, yet $${prefix}_MCP_TOKEN is set: unset one`)})
const host = flags.get("--host") ?? "127.0.0.1"
const exposed = flags.has("--expose")
if (!exposed && !["127.0.0.1", "localhost", "::1"].includes(host))
	refuse("--host " + host + " is no loopback address: pass --expose to serve beyond this machine")
if (exposed && token === undefined) refuse(${tsString(`--expose needs $${prefix}_MCP_TOKEN`)})
const port = flags.get("--port") ?? "8000"
if (!/^(?:0|[1-9][0-9]{0,4})$/.test(port) || Number(port) > 65535) refuse("Invalid --port: 0 to 65535")
${BYTES}
`

/** The protocol over the bound tools, served over Streamable HTTP with --http, else over stdio. */
const serveSource = (app: App) => `const protocol = createProtocol(
	{ name: ${tsString(app.name)}, version: ${tsString(app.version)} },
	bindTools(toolSpecs, client, { opening, secrets: [key, token ?? "", ...Object.values(headers)], timeout: Number(timeout)${app.files ? ", inline" : ""} }),${app.files ? "\n\tfilesCapability(inline)," : ""}
)
if (http) {
	const max = bytes(${tsString(`${app.envPrefix}_MAX_BODY_BYTES`)}, "4194304")
	const origins = (process.env[${tsString(`${app.envPrefix}_MCP_ORIGINS`)}] ?? "").split(",").map((each) => each.trim()).filter(Boolean)
	for (const signal of ["SIGINT", "SIGTERM"]) process.once(signal, () => process.exit(0))
	listenHttp(serveHttp(protocol, { max, origins }), { exposed, host, port: Number(port), token }).then(
		(server) => {
			const { port: bound } = server.address() as { port: number }
			process.stderr.write(${tsString(`${app.name} MCP server on http://`)} + (host.includes(":") ? "[" + host + "]" : host) + ":" + bound + "/mcp\\n")
		},
		(error: Error) => refuse("Cannot listen on " + host + ":" + port + ": " + error.message),
	)
} else {
	const stop = new AbortController()
	for (const signal of ["SIGINT", "SIGTERM"]) process.once(signal, () => stop.abort())
	void serveStdio(protocol, undefined, stop.signal${app.files ? ", read" : ""}).then(
		() => stop.signal.aborted && process.stdout.write("", () => process.exit(0)),
	)
}
`

/** The entry: the tools served over stdio, or Streamable HTTP with --http, under the server's name and version. */
const entrySource = (app: App, ir: IR) =>
	`${MARKER}

// The ${app.name} MCP server: its tools over stdio, for the MCP client that starts it. The API key is
// $${app.envPrefix}_API_KEY, sent as the API's scheme says; the API is at $${app.envPrefix}_BASE_URL, else its first server, and
// with neither it refuses to start. A call waits $${app.envPrefix}_TIMEOUT_MS milliseconds at most, 30 s by default, an
// event stream's collect too. $${app.envPrefix}_HEADERS, a JSON object of string values, goes on every call, each value
// scrubbed as the key is; $${app.envPrefix}_REDIRECT is same-origin (the default) or follow. SIGINT and SIGTERM abort
// every call in flight and exit 0, no later reply written. The API's answer is read at most 1 MiB, past it refused.${app.files ? filesNote(app.envPrefix) : ""}
${httpNote(app.envPrefix)}
import { ${app.files ? "BYTES_MAX, bindTools, configHeaders, createProtocol, fileReader, filesCapability, listenHttp, serveHttp, serveStdio" : "BYTES_MAX, bindTools, configHeaders, createProtocol, listenHttp, serveHttp, serveStdio"} } from "./mcp.runtime.js"
import { Api } from "./sdk/api.index.gen.js"
import { headerValue } from "./sdk/api.runtime.gen.js"
import { toolSpecs } from "./tools.gen.js"

${flagsSource(app.envPrefix)}
const key = process.env[${tsString(`${app.envPrefix}_API_KEY`)}] ?? ""
const timeout = process.env[${tsString(`${app.envPrefix}_TIMEOUT_MS`)}] || "30000"
if (!/^[1-9][0-9]{0,9}$/.test(timeout) || Number(timeout) > 2147483647) {
	process.stderr.write(${tsString(`Invalid $${app.envPrefix}_TIMEOUT_MS: a whole number of milliseconds, 1 to 2147483647\n`)})
	process.exit(1)
}
const baseURL = process.env[${tsString(`${app.envPrefix}_BASE_URL`)}] || ${tsString(ir.servers[0] ?? "")}
if (baseURL === "") {
	process.stderr.write(${tsString(`No API to call: set $${app.envPrefix}_BASE_URL, since the API names no server\n`)})
	process.exit(1)
}
const headers = configHeaders(process.env[${tsString(`${app.envPrefix}_HEADERS`)}], ${tsString(`${app.envPrefix}_HEADERS`)}, headerValue)
if (typeof headers === "string") {
	process.stderr.write(headers + ${tsString("\n")})
	process.exit(1)
}
const redirect = process.env[${tsString(`${app.envPrefix}_REDIRECT`)}] || "same-origin"
if (redirect !== "same-origin" && redirect !== "follow") {
	process.stderr.write(${tsString(`Invalid $${app.envPrefix}_REDIRECT: same-origin or follow
`)})
	process.exit(1)
}
const config = {
	baseURL,
	headers: key === "" ? headers : { ...headers, ${tsString(ir.auth.headerName)}: ${tsString(ir.auth.prefix)} + key },
	maxResponseBytes: BYTES_MAX,
	redirect: redirect as "follow" | "same-origin",
	timeout: Number(timeout),
}
${app.files ? filesSource(app.envPrefix) : ""}const client = new Api(config)
/* a collect's own client: its answer tells that collect its stream opened */
const opening = (seen: () => void) => new Api({ ...config, onResponse: [() => void seen()] })
${serveSource(app)}`

/** tools.gen.ts: every tool's spec, as data the runtime binds to the SDK client. */
const toolsSource = (specs: readonly ToolSpec[]) =>
	`${MARKER}\n\nimport type { ToolSpec } from "./mcp.runtime.js"\n\nexport const toolSpecs: readonly ToolSpec[] = ${literal(specs)}\n`

/** How the package is published: its npm name, and its MCP registry name when it has one. */
type Published = { readonly packageName: string; readonly mcpName?: string }

/**
 * The package: its bin the compiled entry, no dependency, its metadata the run's, the description the server's own
 * when the run gives none.
 */
const packageJson = (name: string, version: string, published: Published, metadata: Metadata) =>
	`${JSON.stringify(
		{
			name: published.packageName,
			version,
			...(published.mcpName === undefined ? {} : { mcpName: published.mcpName }),
			description: `The ${name} API as MCP tools`,
			...npmFields(metadata),
			type: "module",
			bin: { [`${name}-mcp`]: "dist/server.js" },
			files: ["dist", "src"],
			engines: { node: ">=22" },
		},
		null,
		"\t",
	)}\n`

/** `source` with its types erased, as ES module JavaScript; the entry gets the shebang a bin needs. */
export function erased(path: string, source: string): string {
	return `${path === "src/server.ts" ? "#!/usr/bin/env node\n" : ""}${compiled(path, source, false).code.trimEnd()}\n`
}

/**
 * What a publish reads, `app` at the version npm takes: package.json, server.json when it has an `mcpName`, and the
 * package on each registry.
 */
function released(app: App, published: Published, ir: IR, metadata: Metadata) {
	const { mcpName, packageName } = published
	const listing = mcpName === undefined ? undefined : { ...app, mcpName, packageName }
	return {
		files: {
			"package.json": packageJson(app.name, app.version, published, metadata),
			...(listing === undefined ? {} : { "server.json": serverJson(listing, ir, metadata) }),
		},
		packages: [
			packageOn("npm", packageName, app.version),
			...(mcpName === undefined ? [] : [packageOn("mcp-registry", mcpName, app.version)]),
		],
	}
}

/** The MCP server for `document`, as its package's files, its package.json carrying `metadata`. */
export function generateMcpServer(
	document: Record<string, unknown>,
	options: McpServerOptions = {},
	metadata: Metadata = {},
): GeneratedMcpServer {
	const ir = toIR(document as OpenApiDocument, { deriveOperationIds: true })
	const { envPrefix, name } = resolved(options, ir.info.title)
	const published = {
		mcpName: checked("mcpName", options.mcpName, MCP_NAME),
		packageName: checked("packageName", options.packageName ?? `${name}-mcp`, NPM_NAME) as string,
	}
	const version = options.version ?? ir.info.version ?? "0.0.0"
	/* what npm and the registries take: the version when it is semver, else 0.0.0 */
	const publishable = SEMVER.test(version) ? version : "0.0.0"
	const specs = toolsOf(ir)
	if (specs.length === 0)
		throw new Error(
			ir.operations.some((op) => op.extensions.mcp === true)
				? "No operation marked x-mcp is one a tool can call yet: nothing to serve"
				: "No operation is marked x-mcp: nothing to serve",
		)
	const files = specs.some((spec) => spec.parts?.some(([, , kind]) => kind !== "text"))
	const sdk = generateSdk(document, { name: "Api", stem: "api" })
	const source: Record<string, string> = {
		"src/mcp.runtime.ts": mcpRuntimeSource(),
		"src/server.ts": entrySource({ envPrefix, files, name, version }, ir),
		"src/tools.gen.ts": toolsSource(specs),
		...Object.fromEntries(Object.entries(sdk.files).map(([file, text]) => [`src/sdk/${file}`, text])),
	}
	const release = released({ envPrefix, files, name, version: publishable }, published, ir, metadata)
	const compiled = Object.fromEntries(
		Object.entries(source).map(([path, text]) => [
			path.replace(/^src\//, "dist/").replace(/\.ts$/, ".js"),
			erased(path, text),
		]),
	)
	return {
		files: { ...release.files, ...source, ...compiled },
		packages: release.packages,
		skipped: ir.operations.flatMap((op) => {
			const what = op.extensions.mcp === true ? untoolable(op) : undefined
			return what === undefined ? [] : [`${op.id} (${what})`]
		}),
	}
}
