/** One `[[package]]` of a Cargo.lock; the root (the crate itself) is the one without a `source`. */
type LockPackage = { name: string; version: string; source?: string; dependencies?: string[] }
/** A dependency requirement: `"1.2.3"` or `{ version = "1.2.3", … }`. */
type Requirement = string | { version: string; "default-features"?: boolean; features?: string[] }

