/* a binary: lowercase words joined by `-`, at most 64 characters (its agent skill's name is the binary's); a module
 * path: a dotted domain, then path elements (Go's module.CheckPath, less its rarely used characters); an environment
 * prefix: uppercase words joined by `_` */
const BINARY_NAME = /^(?=.{1,64}$)[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/
const MODULE_PATH =
	/^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+(?:\/[A-Za-z0-9_~-](?:[A-Za-z0-9._~-]*[A-Za-z0-9_~-])?)*$/
const ENV_PREFIX = /^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*$/
/* a GitHub repository: its owner 1 to 39 letters, digits and single inner hyphens; its name 1 to 100 of letters,
 * digits, `.`, `_` and `-`, not `.` or `..` and not ending in `.git` */
const REPO = /^[A-Za-z0-9](?:-?[A-Za-z0-9]){0,38}\/(?!\.\.?$)(?![\s\S]*\.git$)[A-Za-z0-9._-]{1,100}$/

const refuse = (option: string, value: string): never => {
	throw new Error(`Invalid ${option}: ${JSON.stringify(value)}`)
}

/** The binary name a title gives: its letters and digits, lowercased, joined by `-`; `api` when it has none. */
export const binaryNameOf = (title: string | undefined): string =>
	(title ?? "")
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, "-")
		.replace(/^[^a-z]+|-+$/g, "") || "api"

/** The options with every default filled, each refused unless it matches its grammar. */
function resolved(
	options: GoCliOptions,
	title: string | undefined,
): Required<Omit<GoCliOptions, "repo">> & Pick<GoCliOptions, "repo"> {
	const binaryName = options.binaryName ?? binaryNameOf(title)
	if (!BINARY_NAME.test(binaryName)) refuse("binaryName", binaryName)
	const modulePath = options.modulePath ?? `example.com/${binaryName}`
	if (!MODULE_PATH.test(modulePath)) refuse("modulePath", modulePath)
	const envPrefix = options.envPrefix ?? binaryName.toUpperCase().replaceAll("-", "_")
	if (!ENV_PREFIX.test(envPrefix)) refuse("envPrefix", envPrefix)
	if (options.repo !== undefined && !REPO.test(options.repo)) refuse("repo", options.repo)
	return { binaryName, envPrefix, modulePath, repo: options.repo }
}

/** A go.sum line's order key: its module path, then its version with each number zero-padded, as Go sorts them. */
const sumKey = (line: string) => line.replace(/\d+/g, (digits) => digits.padStart(20, "0"))

/** A require directive as `go mod tidy` writes it: one requirement on its line, more in a block. */
const requireOf = (lines: readonly string[]) =>
	lines.length === 1 ? `require ${lines[0]}\n` : `require (\n${lines.map((line) => `\t${line}`).join("\n")}\n)\n`

/** go.mod and go.sum: the CLI's requirements, and the WebSocket library's when the embedded SDK needs it. */
function moduleFiles(modulePath: string, websocket: boolean): Record<string, string> {
	const direct = requireOf((websocket ? [...DIRECT, WEBSOCKET] : DIRECT).sort(compareCodeUnits))
	const indirect = requireOf(INDIRECT.map((line) => `${line} // indirect`))
	const sum = (websocket ? [...SUM, ...WEBSOCKET_SUM] : SUM).sort((a, b) => compareCodeUnits(sumKey(a), sumKey(b)))
	return {
		"go.mod": `module ${modulePath}\n\ngo 1.24\n\n${direct}\n${indirect}`,
		"go.sum": `${sum.join("\n")}\n`,
	}
}

/** main.go: the root command, its skill embedded, run with the process's arguments; its exit code the process's. */
const mainFile = (modulePath: string, binaryName: string) => `${MARKER}

package main

import (
\t_ "embed"
\t"os"

\t"${modulePath}/cmd"
\t"${modulePath}/internal/cli"
)

// skill is the agent skill the module ships, as \`${binaryName} skill\` prints it.
//
//go:embed ${skillPath(binaryName)}
var skill string

func main() {
\tos.Exit(cli.Run(cmd.Root(skill), os.Args[1:], os.Stdout, os.Stderr))
}
`

/** The vendored CLI runtime, by its path in the module: SOCKET only when `websocket`. */
const runtimeFiles = (websocket: boolean): Record<string, string> =>
	Object.fromEntries(
		CLI_RUNTIME.filter((name) => websocket || name !== SOCKET).map((name) => [
			`internal/cli/${name}`,
			readFileSync(new URL(`../../runtime/cli/${name}`, import.meta.url), "utf8"),
		]),
	)

/** The API's Go SDK under `internal/sdk/`, its module files left to the CLI's; whether it needs the WebSocket library. */
function embeddedSdk(document: Record<string, unknown>, modulePath: string) {
	const { files } = generateGoSdk(document, { modulePath: `${modulePath}/internal/sdk` })
	const embedded = Object.entries(files)
		.filter(([name]) => name !== "go.mod" && name !== "go.sum")
		.map(([name, text]): [string, string] => [`internal/sdk/${name}`, text])
	return { files: Object.fromEntries(embedded), websocket: Object.hasOwn(files, "go.sum") }
}

/** The CLI module for `document`, by file name. */
export function generateGoCli(document: Record<string, unknown>, options: GoCliOptions = {}): GeneratedGoCli {
	const ir = toIR(document as OpenApiDocument, { deriveOperationIds: true })
	const { binaryName, envPrefix, modulePath, repo } = resolved(options, ir.info.title)
	const install = { bin: binaryName, prefix: envPrefix, repo }
	const sdk = embeddedSdk(document, modulePath)
	const model = sdkModel(ir)
	const nodes = commandTree(model.ops, goCallPlans(document))
	const app = { binaryName, envPrefix, modulePath, short: ir.info.title ?? binaryName }
	return {
		files: {
			...moduleFiles(modulePath, sdk.websocket),
			"main.go": mainFile(modulePath, binaryName),
			[skillPath(binaryName)]: skillFile(binaryName, app.short, envPrefix, model.ops),
			".goreleaser.yaml": goreleaserFile(binaryName, modulePath, repo),
			".github/workflows/release.yml": releaseWorkflow(binaryName),
			"install.sh": installSh(install),
			"install.ps1": installPs1(install),
			...cmdFiles(app, ir, nodes, discoveryEntries(nodes, model)),
			...runtimeFiles(sdk.websocket),
			...sdk.files,
		},
	}
}
