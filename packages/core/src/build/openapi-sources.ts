/**
 * The generated sources module (plan 39 7.5): where a generation wrote each named OpenAPI document, as the `{ asset }`
 * sources `serveStaticOpenApi` already takes, so a Worker spreads `openApiSources.<name>` instead of repeating the
 * paths. Asset paths are relative to the assets directory: `codegen.assetsDir`, else wrangler's `assets.directory`
 * (wrangler.json or wrangler.jsonc; wrangler.toml is not read), its binding carried when it is not `ASSETS`.
 */
import { existsSync, readFileSync } from "node:fs"
import { relative, resolve, sep } from "node:path"
import { openApiOutputPaths, type ResolvedHoneyConfig } from "./config.ts"

/** The index just past the string that opens at `start`, its escapes skipped. */
function afterString(text: string, start: number): number {
	let at = start + 1
	while (at < text.length && text[at] !== '"') at += text[at] === "\\" ? 2 : 1
	return at + 1
}

/** `text` with every character outside a string through `each`, which returns what to keep and where to go on. */
function scan(text: string, each: (at: number) => [kept: string, next: number]): string {
	let out = ""
	let at = 0
	while (at < text.length) {
		const [kept, next] = text[at] === '"' ? [text.slice(at, afterString(text, at)), afterString(text, at)] : each(at)
		out += kept
		at = next
	}
	return out
}

/** JSONC as JSON: its `//` and block comments and its trailing commas left out, every string as written. */
export function jsoncToJson(text: string): string {
	const uncommented = scan(text, (at) => {
		if (text.startsWith("//", at)) {
			const end = text.indexOf("\n", at)
			return ["", end === -1 ? text.length : end]
		}
		if (text.startsWith("/*", at)) {
			const end = text.indexOf("*/", at + 2)
			return [" ", end === -1 ? text.length : end + 2]
		}
		return [text[at] as string, at + 1]
	})
	const closer = /\s*[}\]]/y
	return scan(uncommented, (at) => {
		closer.lastIndex = at + 1
		return [uncommented[at] === "," && closer.test(uncommented) ? "" : (uncommented[at] as string), at + 1]
	})
}

type Assets = { readonly binding: string | undefined; readonly directory: string }

/** The assets directory and binding a named document at `at` resolves against; none is an error naming the fix. */
function assetsOf(config: ResolvedHoneyConfig, root: string, at: string): Assets {
	if (config.codegen.assetsDir !== undefined) return { binding: undefined, directory: config.codegen.assetsDir }
	for (const name of ["wrangler.json", "wrangler.jsonc"]) {
		const path = resolve(root, name)
		if (!existsSync(path)) continue
		const { assets } = JSON.parse(jsoncToJson(readFileSync(path, "utf8"))) as {
			assets?: { binding?: string; directory?: string }
		}
		if (assets?.directory !== undefined)
			return { binding: assets.binding === "ASSETS" ? undefined : assets.binding, directory: assets.directory }
	}
	const fix = existsSync(resolve(root, "wrangler.toml"))
		? "wrangler.toml is not read: set codegen.assetsDir, or keep the Worker's config in wrangler.json or wrangler.jsonc"
		: "set codegen.assetsDir, or assets.directory in wrangler.jsonc"
	throw new Error(`${at} is named, so its files are listed as assets: ${fix}`)
}

/** The module's text for `config`'s named documents; `null` when no document is named. */
export function openApiSourcesOf(config: ResolvedHoneyConfig, root: string): string | null {
	const named = config.codegen.openApi.filter((entry) => entry.name !== undefined)
	if (named.length === 0) return null
	let assets: Assets | undefined
	const lines = named.map((entry) => {
		const at = `codegen.openApi ${JSON.stringify(entry.name)}`
		assets ??= assetsOf(config, root, at)
		const directory = resolve(root, assets.directory)
		const binding = assets.binding === undefined ? {} : { binding: assets.binding }
		const paths = openApiOutputPaths(entry.path, entry.formats)
		const source: Record<string, { asset: string; binding?: string }> = {}
		for (const format of ["json", "yaml"] as const) {
			const path = paths[format]
			if (path === null) continue
			const inside = relative(directory, resolve(root, path))
			if (inside.startsWith(`..${sep}`))
				throw new Error(
					`${at}: ${path} is outside the assets directory ${relative(root, directory)}, so no asset serves it`,
				)
			source[format] = { asset: `/${inside.split(sep).join("/")}`, ...binding }
		}
		return `\t${JSON.stringify(entry.name)}: ${JSON.stringify(source)},`
	})
	return [
		"/** Where each named OpenAPI document is, as serveStaticOpenApi sources. Generated by honey generate. */",
		"export const openApiSources = {",
		...lines,
		"} as const",
		"",
	].join("\n")
}
