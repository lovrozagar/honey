/**
 * The package manifest (Fb2, Fb3): `pyproject.toml` with the generated marker, hatchling over the src
 * layout, `requires-python` and the one httpx2 dependency, and no spec text, so no TOML escaping. The package
 * name and version are validated before anything is emitted.
 */

/** The `requires-python` every emitted package declares. */
export const PYTHON_REQUIRES = ">=3.11"

/** The lowest httpx2 every emitted package accepts. */
export const HTTPX2_FLOOR = "2.12.0"

/** The dependency string every emitted package declares (`httpx2[ws]` when it needs WebSockets). */
export const HTTPX2 = `httpx2>=${HTTPX2_FLOOR},<3`

/* the hard keywords and the soft ones, none an import name */
const KEYWORDS =
	" False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield match case type _ "

/** `name` when it is an import name a package may take: lower snake case, no keyword, not the runtime's. */
export function validatePackageName(name: string): string {
	if (!/^[a-z][a-z0-9_]*$/.test(name) || KEYWORDS.includes(` ${name} `) || name === "_honey") {
		throw new Error(`Invalid package name: "${name}"`)
	}
	return name
}

/** `version` when it is in PEP 440's release, pre, post and dev subset. */
export function validateVersion(version: string): string {
	if (!/^\d+(\.\d+)*((a|b|rc)\d+)?(\.post\d+)?(\.dev\d+)?$/.test(version)) {
		throw new Error(`Invalid version: "${version}"`)
	}
	return version
}

/** The manifest of package `pkg` (its import name; the distribution name has `-` for `_`). */
export function pyproject(pkg: { readonly name: string; readonly version: string }, ws: boolean): string {
	const dependency = ws ? HTTPX2.replace("httpx2", "httpx2[ws]") : HTTPX2
	return [
		"# @generated by honey. DO NOT EDIT.",
		"[build-system]",
		'requires = ["hatchling>=1.27"]',
		'build-backend = "hatchling.build"',
		"",
		"[project]",
		`name = "${pkg.name.replaceAll("_", "-")}"`,
		`version = "${pkg.version}"`,
		`requires-python = "${PYTHON_REQUIRES}"`,
		`dependencies = ["${dependency}"]`,
		"",
		"[tool.hatch.build.targets.wheel]",
		`packages = ["src/${pkg.name}"]`,
		"",
	].join("\n")
}
