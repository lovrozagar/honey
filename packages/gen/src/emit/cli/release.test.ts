/**
 * The release (bit 17 phase g): .goreleaser.yaml and .github/workflows/release.yml pinned byte for byte (the six
 * targets, CGO off, the version-less archives and checksums.txt; a v* trigger, contents read except the release job,
 * checkout without credentials, every action by commit); `goreleaser check` passes on the config, with a repository
 * and without one (the git remote's); every value a YAML string whatever its spelling; and a repository that is not
 * GitHub's owner/name refused at generate (F2), since it reaches the config and the install scripts.
 */
import { spawnSync } from "node:child_process"
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { describe, expect, it } from "vitest"
import { goCacheDir } from "../go/__fixtures__/go-env.ts"
