/**
 * The MCP server's vendored runtime (bit 18), as the emitter ships it: `runtime/mcp` modules joined into one, each
 * after the ones it imports, their imports of each other dropped. A module of its own, so the gen mutation harness can
 * swap the runtime a guard is switched off in, and every emitter call sees it. Bit 21 e: the portable modules (web
 * APIs alone) are what an app mounts, on Workers too; the standalone package adds the node ones after them.
 */
import { readFileSync } from "node:fs"

/** The portable runtime modules, each after the ones it imports: no node API, none of the node modules. */
export const MCP_PORTABLE: readonly string[] = [
	"jsonrpc",
	"protocol",
	"files",
	"http",
	"guard",
	"result",
	"stream",
	"call",
	"mount",
]

/** The node modules the standalone package adds: stdio, its file reader, the HTTP listener. */
export const MCP_NODE: readonly string[] = ["stdio", "reader", "listen"]

/** Every runtime module under `runtime/mcp`, each after the ones it imports. */
export const MCP_RUNTIME: readonly string[] = [...MCP_PORTABLE, ...MCP_NODE]

/** The standalone package's: every module but the mount, which only an app's handler serves. */
export const MCP_STANDALONE: readonly string[] = [
	"jsonrpc",
	"protocol",
	"files",
	"http",
	"guard",
	"result",
	"stream",
	"call",
	"stdio",
	"reader",
	"listen",
]

/* an import of a sibling runtime module, on one line or several */
const SIBLING_IMPORT = /^import\s+(?:type\s+)?\{[^}]*\}\s+from\s+"\.\/[\w-]+\.ts"\n/gm

const MARKER = "// Code generated by honey. DO NOT EDIT."

/** The vendored runtime as one module: `names` (the standalone package's by default) in order, sibling imports dropped. */
export function mcpRuntimeSource(names: readonly string[] = MCP_STANDALONE): string {
	const modules = names.map((name) =>
		readFileSync(new URL(`../../runtime/mcp/${name}.ts`, import.meta.url), "utf8")
			.replace(SIBLING_IMPORT, "")
			.trim(),
	)
	return `${MARKER}\n\n${modules.join("\n\n")}\n`
}
