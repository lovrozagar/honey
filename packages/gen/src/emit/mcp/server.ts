/**
 * The generated MCP server as files (bit 18): a package an agent's MCP client starts as a command. Its TypeScript under
 * `src/` (the entry, the tools, the vendored runtime joined into one module, the API's own TS SDK under `src/sdk/`), and
 * the same code with its types erased under `dist/`, CommonJS, which the package's bin runs: node refuses to strip
 * types under an installed package's folder, so an installed server must ship JavaScript. The erasure is jiti's
 * transform, gen's own dependency, deterministic whichever runtime generates. No dependency, no build step.
 */
import { readFileSync } from "node:fs"
import { createJiti } from "jiti"
import { type OpenApiDocument, toIR } from "../../ir/build.ts"
import { binaryNameOf } from "../cli/module.ts"
import { tsString } from "../shared/escape.ts"
import { generateSdk } from "../ts/sdk.ts"

export type McpServerOptions = {
	/** the server's name: lowercase words joined by `-`, at most 60 characters; by default the document title's */
	readonly name?: string
	/** the prefix of its environment variables; by default the name's words, uppercased, joined by `_` */
	readonly envPrefix?: string
}

export type GeneratedMcpServer = { readonly files: Readonly<Record<string, string>> }

/** The runtime modules under `runtime/mcp`, each after the ones it imports. */
export const MCP_RUNTIME: readonly string[] = ["jsonrpc", "server", "stdio"]

/* a name leaves room for the bin's `-mcp`; a prefix is uppercase words joined by `_` */
const NAME = /^(?=.{1,60}$)[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/
const ENV_PREFIX = /^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*$/
/* an import of a sibling runtime module, on one line or several */
const SIBLING_IMPORT = /^import\s+(?:type\s+)?\{[^}]*\}\s+from\s+"\.\/[\w-]+\.ts"\n/gm
/* a version npm accepts in a package.json */
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/

const MARKER = "// Code generated by honey. DO NOT EDIT."

/** The options with their defaults filled, each refused unless it matches its grammar (F2). */
function resolved(options: McpServerOptions, title: string | undefined) {
	const name = options.name ?? binaryNameOf(title)
	if (!NAME.test(name)) throw new Error(`Invalid name: ${JSON.stringify(name)}`)
	const envPrefix = options.envPrefix ?? name.toUpperCase().replaceAll("-", "_")
	if (!ENV_PREFIX.test(envPrefix)) throw new Error(`Invalid envPrefix: ${JSON.stringify(envPrefix)}`)
	return { envPrefix, name }
}

/** The vendored runtime as one module: each runtime/mcp module in order, their imports of each other dropped. */
export function mcpRuntimeSource(): string {
	const modules = MCP_RUNTIME.map((name) =>
		readFileSync(new URL(`../../runtime/mcp/${name}.ts`, import.meta.url), "utf8")
			.replace(SIBLING_IMPORT, "")
			.trim(),
	)
	return `${MARKER}\n\n${modules.join("\n\n")}\n`
}

/** The entry: the tools served over stdio under the server's name and version. */
const entrySource = (name: string, version: string) =>
	`${MARKER}

// The ${name} MCP server: its tools over stdio, for the MCP client that starts it.
import { createSession, serveStdio } from "./mcp.runtime"
import { tools } from "./tools.gen"

void serveStdio(createSession({ name: ${tsString(name)}, version: ${tsString(version)} }, tools))
`

/** The package: its bin the compiled entry, no dependency. */
const packageJson = (name: string, version: string) =>
	`${JSON.stringify(
		{
			bin: { [`${name}-mcp`]: "dist/server.js" },
			description: `The ${name} API as MCP tools`,
			engines: { node: ">=22" },
			files: ["dist", "src"],
			name: `${name}-mcp`,
			type: "module",
			version: SEMVER.test(version) ? version : "0.0.0",
		},
		null,
		"\t",
	)}\n`

/** `source` with its types erased, as CommonJS; the entry gets the shebang a bin needs. */
function erased(path: string, source: string): string {
	const jiti = createJiti(import.meta.url, { fsCache: false, moduleCache: false })
	const code = jiti.transform({ filename: path, source, ts: true })
	return `${path === "src/server.ts" ? "#!/usr/bin/env node\n" : ""}${code.trimEnd()}\n`
}

/** The MCP server for `document`, as its package's files. */
export function generateMcpServer(
	document: Record<string, unknown>,
	options: McpServerOptions = {},
): GeneratedMcpServer {
	const ir = toIR(document as OpenApiDocument, { deriveOperationIds: true })
	const { name } = resolved(options, ir.info.title)
	const version = ir.info.version ?? "0.0.0"
	const sdk = generateSdk(document, { name: "Api", stem: "api" })
	const source: Record<string, string> = {
		"src/mcp.runtime.ts": mcpRuntimeSource(),
		"src/server.ts": entrySource(name, version),
		"src/tools.gen.ts": `${MARKER}\n\nimport type { Tool } from "./mcp.runtime"\n\nexport const tools: readonly Tool[] = []\n`,
		...Object.fromEntries(Object.entries(sdk.files).map(([file, text]) => [`src/sdk/${file}`, text])),
	}
	const compiled = Object.fromEntries(
		Object.entries(source).map(([path, text]) => [
			path.replace(/^src\//, "dist/").replace(/\.ts$/, ".js"),
			erased(path, text),
		]),
	)
	return {
		files: {
			"package.json": packageJson(name, version),
			...source,
			"dist/package.json": `${JSON.stringify({ type: "commonjs" }, null, "\t")}\n`,
			...compiled,
		},
	}
}
