/**
 * The MCP handler an app mounts (bit 21 e, H24.3): the honey plugin's `codegen.mcp` output, from the app's own
 * document. Its entry holds the tool table and the handler (`mcpHandler`) over the portable runtime and the API's own
 * TS SDK, each in the companion directory beside it; @lovrozagar/honey/mcp's `mcp(app, path, mcpHandler)` mounts it.
 * Each call runs in-process through the app. The handler is `secured` when any tool's operation requires a credential
 * (its `security`, else the document's, with no empty requirement), and carries the headers the schemes those tools
 * name read (an http, OAuth or OpenID scheme's Authorization, an API key's own header or Cookie; mutual TLS and a query
 * key none), and the SDK's own.
 */
import { type OpenApiDocument, toIR } from "../../ir/build.ts"
import type { IR, IROperation } from "../../ir/model.ts"
import { tsString } from "../shared/escape.ts"
import { generateSdk } from "../ts/sdk.ts"
import { MOUNTED_FILE_SCHEMA } from "./files.ts"
import { literal } from "./literal.ts"
import { MCP_PORTABLE, mcpRuntimeSource } from "./runtime.ts"
import { resolved } from "./server.ts"
import { isTool, toolsOf, untoolable } from "./tools.ts"

export type McpHandlerOptions = {
	/** the server's name: lowercase words joined by `-`; by default the document title's */
	readonly name?: string
	/** the companion directory's name, beside the entry; `mcp` by default */
	readonly dir?: string
}

export type GeneratedMcpHandler = {
	/** the entry module, exporting `mcpHandler` */
	readonly entry: string
	/** the companion directory's files, by name */
	readonly files: Readonly<Record<string, string>>
	/** each operation marked x-mcp that no tool serves: its id and what it is */
	readonly skipped: readonly string[]
}

const MARKER = "// Code generated by honey. DO NOT EDIT."
/* a directory name a relative import names */
const DIR = /^[A-Za-z0-9_][A-Za-z0-9_.-]*$/

type Requirement = Readonly<Record<string, unknown>>
type Scheme = { readonly type?: unknown; readonly in?: unknown; readonly name?: unknown }

/** `op`'s security requirements: its own, else the document's. */
function requirementsOf(spec: Record<string, unknown>, op: IROperation): readonly Requirement[] {
	/* a tool's operation is the document's own, at its path and method */
	const paths = spec.paths as Record<string, Record<string, { security?: Requirement[] }>>
	const own = (paths[op.path] as Record<string, { security?: Requirement[] }>)[op.method.toLowerCase()] as {
		security?: Requirement[]
	}
	return own.security ?? (spec.security as Requirement[] | undefined) ?? []
}

/** The request header a scheme reads its credential from, lower case; none for a query key. */
function headerOf(scheme: Scheme | undefined): string | undefined {
	if (["http", "oauth2", "openIdConnect"].includes(String(scheme?.type))) return "authorization"
	if (scheme?.type !== "apiKey") return undefined
	return scheme.in === "header" ? String(scheme.name).toLowerCase() : scheme.in === "cookie" ? "cookie" : undefined
}

/** Whether any tool needs a credential, and every header the tools' schemes and the SDK's own read, sorted. */
function securityOf(spec: Record<string, unknown>, ir: IR) {
	const schemes = ((spec.components as { securitySchemes?: unknown } | undefined)?.securitySchemes ?? {}) as Record<
		string,
		Scheme
	>
	const requirements = ir.operations.filter(isTool).map((op) => requirementsOf(spec, op))
	const named = requirements.flat().flatMap((requirement) => Object.keys(requirement))
	const headers = [ir.auth.headerName.toLowerCase(), ...named.map((name) => headerOf(schemes[name]))]
	return {
		credentials: [...new Set(headers.filter((header) => header !== undefined))].sort(),
		secured: requirements.some((list) => list.length > 0 && list.every((each) => Object.keys(each).length > 0)),
	}
}

/** The path of the API's first server, where the app's routes sit: empty for none or the root. */
const serverPath = (server: string | undefined) =>
	server === undefined ? "" : new URL(server, "http://localhost").pathname.replace(/\/$/, "")

/** The MCP handler for `document`'s tools, as its entry and the companion directory's files. */
export function generateMcpHandler(
	spec: Record<string, unknown>,
	options: McpHandlerOptions = {},
): GeneratedMcpHandler {
	const dir = options.dir ?? "mcp"
	if (!DIR.test(dir)) throw new Error(`Invalid dir: ${JSON.stringify(dir)}`)
	const ir = toIR(spec as OpenApiDocument, { deriveOperationIds: true })
	const { name } = resolved({ name: options.name }, ir.info.title)
	const specs = toolsOf(ir, MOUNTED_FILE_SCHEMA)
	if (specs.length === 0) throw new Error("No operation marked x-mcp is one a tool can call: nothing to mount")
	const { credentials, secured } = securityOf(spec, ir)
	const sdk = generateSdk(spec, { name: "Api", stem: "api" })
	const entry = `${MARKER}

// The ${name} API's tools, mounted in the app: mcp(app, path, mcpHandler) from @lovrozagar/honey/mcp serves them over
// Streamable HTTP, each call dispatched in-process through the app. ${secured ? "Its tools require a credential, so the mount needs authenticate." : "No tool requires a credential."}
import type { ToolSpec } from "./${dir}/runtime.gen"
import { mountedMcp } from "./${dir}/runtime.gen"
import { Api } from "./${dir}/api.index.gen"

const toolSpecs: readonly ToolSpec[] = ${literal(specs)}

export const mcpHandler = mountedMcp({
	challenge: ${tsString(ir.auth.prefix.trim() || "ApiKey")},
	client: (config) => new Api(config),
	credentials: ${JSON.stringify(credentials)},
	info: { name: ${tsString(name)}, version: ${tsString(ir.info.version ?? "0.0.0")} },
	secured: ${secured},
	server: ${tsString(serverPath(ir.servers[0]))},
	specs: toolSpecs,
})
`
	return {
		entry,
		files: { "runtime.gen.ts": mcpRuntimeSource(MCP_PORTABLE), ...sdk.files },
		skipped: ir.operations.flatMap((op) => {
			const what = op.extensions.mcp === true ? untoolable(op) : undefined
			return what === undefined ? [] : [`${op.id} (${what})`]
		}),
	}
}
