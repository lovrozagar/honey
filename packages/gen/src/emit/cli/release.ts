/**
 * The CLI's release (bit 17 phase g): `.goreleaser.yaml` builds six static binaries (linux, darwin, windows × amd64,
 * arm64; CGO off, trimmed paths, stripped, the tag linked in as the version) into archives named without the
 * version, `<bin>_<os>_<arch>` (.tar.gz, .zip for windows), so a release's `latest/download` resolves them, beside
 * `checksums.txt`, which cosign signs keyless (`checksums.txt.sigstore.json`, one bundle vouching for every
 * archive's digest). With a repository, each release also carries `version.txt` (its tag, which the install scripts
 * read through `latest/download`) and, when the scripts are served from the release itself, `install.sh` and
 * `install.ps1`. The channels the options name are added to it: a Homebrew cask, a Scoop manifest, a winget pull
 * request from a fork, an AUR `-bin` package, and deb/rpm/apk packages, each from its own validated options.
 * `.github/workflows/release.yml` runs it on a `v*` tag alone: contents read by default; the release job alone gets
 * contents write and the OIDC token cosign and the build provenance attestation over every archive sign with;
 * checkout keeps no credentials; every action is pinned by commit; each channel's secret reaches goreleaser's step
 * env by name. Every value is a validated option (the binary, the module path, the repository, the channels), never
 * spec text.
 */

import { channelBlock, type Release, SECRETS } from "./channels.ts"

export { REPO, type Release, type ReleaseOptions, resolvedRelease } from "./channels.ts"

/* the marker generated YAML carries on its first line */
const MARKER = "# Code generated by honey. DO NOT EDIT."

/** The tools release.yml runs, each pinned by commit (its release in the comment beside it). */
export const RELEASE_ACTIONS = {
	attest: "actions/attest@1e69f48acb82d1966a394da916b4c1698aa569d6 # v4.2.2",
	checkout: "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1",
	cosign: "sigstore/cosign-installer@6f9f17788090df1f26f669e9d70d6ae9567deba6 # v4.1.2",
	goreleaser: "goreleaser/goreleaser-action@f06c13b6b1a9625abc9e6e439d9c05a8f2190e94 # v7.2.3",
	setupGo: "actions/setup-go@b7ad1dad31e06c5925ef5d2fc7ad053ef454303e # v7.0.0",
}

/** A value as a YAML double-quoted scalar (a JSON string is one): a name like `true` or `1e3` stays a string. */
export const q = (value: string) => JSON.stringify(value)

/** The goreleaser release the action installs: the one the tests check the config with. */
export const GORELEASER_VERSION = "v2.18.3"

/** .goreleaser.yaml for the CLI `bin` in module `modulePath`, released per `release` when it names a repository. */
export function goreleaserFile(bin: string, modulePath: string, release: Release | undefined): string {
	/* without a repository, goreleaser releases to the git remote's, and there is no version file to serve */
	const before =
		release === undefined
			? ""
			: `# the release's tag, which the install scripts read through releases/latest/download
before:
  hooks:
    - sh -c 'printf "%s\\n" "{{ .Tag }}" > version.txt'
`
	const extra =
		release === undefined ? [] : ["version.txt", ...(release.scriptsInRelease ? ["install.sh", "install.ps1"] : [])]
	const github =
		release === undefined
			? ""
			: `release:
  github:
    owner: ${q(release.owner)}
    name: ${q(release.name)}
  extra_files:
${extra.map((file) => `    - glob: ./${file}\n`).join("")}`
	return `${MARKER}
# ${bin}'s release: six static binaries, each archive named ${bin}_<os>_<arch>, and checksums.txt signed by cosign
# (release.yml).
version: 2
project_name: ${q(bin)}
${before}builds:
  - id: ${q(bin)}
    main: .
    binary: ${q(bin)}
    env:
      - CGO_ENABLED=0
    flags:
      - -trimpath
    ldflags:
      - ${q(`-s -w -X ${modulePath}/internal/cli.Version={{ .Tag }}`)}
    goos: [linux, darwin, windows]
    goarch: [amd64, arm64]
archives:
  - id: ${q(bin)}
    name_template: "{{ .ProjectName }}_{{ .Os }}_{{ .Arch }}"
    formats: [tar.gz]
    format_overrides:
      - goos: windows
        formats: [zip]
checksum:
  name_template: checksums.txt
  algorithm: sha256
# checksums.txt signed keyless by cosign as the release workflow, one bundle vouching for every archive's digest
signs:
  - cmd: cosign
    signature: "\${artifact}.sigstore.json"
    args: [sign-blob, "--bundle=\${signature}", "\${artifact}", --yes]
    artifacts: checksum
changelog:
  disable: true
${github}${(release?.channels ?? []).map((channel) => channelBlock(bin, channel)).join("")}`
}

/** .github/workflows/release.yml: goreleaser on a `v*` tag, publishing the signed release, then attesting it. */
export function releaseWorkflow(bin: string, release: Release | undefined): string {
	const secrets = (release?.channels ?? []).flatMap((channel) => {
		const secret = SECRETS[channel.kind]
		return secret === undefined ? [] : [`          ${secret}: \${{ secrets.${secret} }}\n`]
	})
	return `${MARKER}
# Releases ${bin} on a v* tag: goreleaser builds the six binaries and publishes them beside checksums.txt, which cosign
# signs keyless as this workflow; every archive gets a build provenance attestation.
name: release
on:
  push:
    tags:
      - "v*"
permissions:
  contents: read
jobs:
  release:
    runs-on: ubuntu-latest
    permissions:
      contents: write
      id-token: write
      attestations: write
    steps:
      - uses: ${RELEASE_ACTIONS.checkout}
        with:
          fetch-depth: 0
          persist-credentials: false
      - uses: ${RELEASE_ACTIONS.setupGo}
        with:
          go-version-file: go.mod
          cache: false
      - uses: ${RELEASE_ACTIONS.cosign}
      - uses: ${RELEASE_ACTIONS.goreleaser}
        with:
          distribution: goreleaser
          version: ${GORELEASER_VERSION}
          args: release --clean
        env:
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
${secrets.join("")}      - uses: ${RELEASE_ACTIONS.attest}
        with:
          subject-checksums: dist/checksums.txt
`
}
