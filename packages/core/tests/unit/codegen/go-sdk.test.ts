/* ── Tier 2: JSON Schema → Go type ── */

describe("Tier 2: JSON Schema → Go type", () => {
	it("9. primitive type mappings", () => {
		expect(renderUse({ type: "string" }, mkCtx())).toBe("string")
		expect(renderUse({ type: "integer" }, mkCtx())).toBe("int64")
		expect(renderUse({ type: "number" }, mkCtx())).toBe("float64")
		expect(renderUse({ type: "boolean" }, mkCtx())).toBe("bool")
		expect(renderUse({ type: "null" }, mkCtx())).toBe("json.RawMessage")
	})

	it("10. array of primitive → []T", () => {
		expect(renderUse({ items: { type: "string" }, type: "array" }, mkCtx())).toBe("[]string")
		expect(renderUse({ items: { type: "integer" }, type: "array" }, mkCtx())).toBe("[]int64")
	})

	it("11. tuple (items array) → [N]interface{}", () => {
		const result = renderUse(
			{ items: [{ type: "string" }, { type: "number" }], type: "array" },
			mkCtx(),
		)
		expect(result).toContain("[2]interface{}")
	})

	it("12. string enum → hoisted named type + const block in decls", () => {
		const decls = new Map<string, string>()
		const ref = renderUse(
			{ enum: ["a", "b"], type: "string" },
			{ decls, fieldName: "status", parentName: "User" },
		)
		expect(ref).toBe("UserStatus")
		const decl = decls.get("UserStatus")
		expect(decl).toBeDefined()
		expect(decl).toContain("type UserStatus string")
		expect(decl).toContain("const (")
		expect(decl).toMatch(/UserStatusA\s+UserStatus\s+=\s+"a"/)
		expect(decl).toMatch(/UserStatusB\s+UserStatus\s+=\s+"b"/)
	})

	it("13. top-level const literal → type alias + const value via renderTopLevel", () => {
		const decls = new Map<string, string>()
		const result = renderTopLevel("Role", { const: "admin" }, decls)
		expect(result).toContain("type Role string")
		expect(result).toContain(`= "admin"`)
	})

	it("14. nullable shorthand → *T pointer", () => {
		expect(renderUse({ nullable: true, type: "string" }, mkCtx())).toBe("*string")
	})

	it("15. type array with null → *T pointer", () => {
		expect(renderUse({ type: ["string", "null"] }, mkCtx())).toBe("*string")
	})

	it("16. type array multi non-null → json.RawMessage fallback", () => {
		expect(renderUse({ type: ["string", "number"] }, mkCtx())).toBe("json.RawMessage")
	})

	it("17. oneOf/anyOf without discriminator → json.RawMessage; top-level with discriminator → tagged struct", () => {
		expect(renderUse({ oneOf: [{ type: "string" }, { type: "integer" }] }, mkCtx()))
			.toBe("json.RawMessage")

		const withDisc = renderTopLevel(
			"Animal",
			{
				discriminator: { propertyName: "kind" },
				oneOf: [{ $ref: "#/components/schemas/Dog" }, { $ref: "#/components/schemas/Cat" }],
			},
			new Map(),
		)
		expect(withDisc).toContain("Type string")
		expect(withDisc).toContain("json.RawMessage")
	})

	it("18. top-level allOf → struct with embedded fields", () => {
		const result = renderTopLevel(
			"Extended",
			{
				allOf: [
					{ $ref: "#/components/schemas/Base" },
					{ properties: { extra: { type: "string" } }, type: "object" },
				],
			},
			new Map(),
		)
		expect(result).toContain("Base")
		expect(result).toContain("struct")
		expect(result).toContain("Extra")
	})

	it("19. top-level object required+optional → bare vs pointer fields, sorted alphabetically", () => {
		const result = renderTopLevel(
			"User",
			{
				properties: {
					email: { type: "string" },
					name: { type: "string" },
				},
				required: ["email"],
				type: "object",
			},
			new Map(),
		)
		expect(result).toMatch(/Email\s+string\s+`json:"email"/)
		expect(result).toMatch(/Name\s+\*string\s+`json:"name,omitempty"/)
		expect(result.indexOf("Email")).toBeLessThan(result.indexOf("Name"))
	})

	it("20. additionalProperties → map[string]T; with props → struct + Extra map + marshal pair", () => {
		const mapOnly = renderTopLevel(
			"Attrs",
			{ additionalProperties: { type: "string" }, type: "object" },
			new Map(),
		)
		expect(mapOnly).toContain("map[string]string")

		const withProps = renderTopLevel(
			"Mixed",
			{
				additionalProperties: { type: "string" },
				properties: { id: { type: "string" } },
				required: ["id"],
				type: "object",
			},
			new Map(),
		)
		expect(withProps).toContain("Extra")
		expect(withProps).toContain("map[string]string")
		expect(withProps).toContain("UnmarshalJSON")
		expect(withProps).toContain("MarshalJSON")
	})

	it("21. $ref → bare Go type name; circular ref → pointer", () => {
		expect(renderUse({ $ref: "#/components/schemas/User" }, mkCtx())).toBe("User")

		const circular = renderTopLevel(
			"Comment",
			{
				properties: {
					parent: { $ref: "#/components/schemas/Comment" },
				},
				type: "object",
			},
			new Map(),
		)
		expect(circular).toContain("*Comment")
	})

	it("22. depth guard → json.RawMessage beyond 12", () => {
		const result = renderUse(
			{ properties: { x: { type: "string" } }, type: "object" },
			{ ...mkCtx(), depth: 13 },
		)
		expect(result).toBe("json.RawMessage")
	})

	it("23. non-identifier property key → PascalCase field + json tag preserves original", () => {
		const result = renderTopLevel(
			"Obj",
			{
				properties: { "bad-key": { type: "string" } },
				required: ["bad-key"],
				type: "object",
			},
			new Map(),
		)
		expect(result).toContain("BadKey")
		expect(result).toContain('`json:"bad-key"')
	})

	it("24. Go reserved keyword property → PascalCase export is safe", () => {
		const result = renderTopLevel(
			"Reserved",
			{
				properties: {
					chan: { type: "string" },
					func: { type: "string" },
					type: { type: "string" },
				},
				required: ["type", "chan", "func"],
				type: "object",
			},
			new Map(),
		)
		expect(result).toContain("Type ")
		expect(result).toContain("Chan ")
		expect(result).toContain("Func ")
		expect(result).toContain('`json:"type"')
		expect(result).toContain('`json:"chan"')
		expect(result).toContain('`json:"func"')
	})

	it("25. bracket balance on all renderTopLevel outputs", () => {
		const schemas: [string, Record<string, unknown>][] = [
			["T1", { properties: { id: { type: "string" }, val: { type: "number" } }, required: ["id"], type: "object" }],
			["T2", { properties: { arr: { items: { properties: { x: { type: "boolean" } }, type: "object" }, type: "array" } }, type: "object" }],
			["T3", { properties: { u: { oneOf: [{ type: "string" }, { type: "integer" }] } }, type: "object" }],
			["T4", { allOf: [{ $ref: "#/components/schemas/Base" }, { properties: { y: { type: "string" } }, type: "object" }] }],
			["T5", { additionalProperties: { type: "integer" }, type: "object" }],
		]
		for (const [name, schema] of schemas) {
			const decls = new Map<string, string>()
			const out = renderTopLevel(name, schema, decls)
			assertBalancedGoBrackets(out)
			for (const d of decls.values()) assertBalancedGoBrackets(d)
		}
	})
})

