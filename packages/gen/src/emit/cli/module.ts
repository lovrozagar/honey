/**
 * The generated CLI (bit 17, E1): a pure-Go module building one static binary (`CGO_ENABLED=0`; the end user
 * needs no Go and no Node). It holds `main.go`, the commands under `cmd/`, the vendored CLI runtime
 * (`runtime/cli/*.go`, verbatim under `internal/cli/`), and the API's own Go SDK embedded under `internal/sdk/`, which
 * every command calls through: the CLI projects the SDK, never re-implementing its HTTP. Its dependencies are cobra
 * and pflag (the Go CLI standard, H9) and go-toml (its config file), each pinned with its checksum-database hashes in
 * `go.sum`. The binary name,
 * module path and environment prefix reach Go, goreleaser, the install scripts and variable names, so each is
 * refused at generate unless it matches its own grammar; the document's words reach Go only as escaped literals.
 */
