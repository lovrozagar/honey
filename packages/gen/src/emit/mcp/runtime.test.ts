/**
 * The MCP server's vendored runtime as the emitter ships it (bit 18): every runtime/mcp module joined into one, each
 * after the ones it imports (read from its own source), their imports of each other dropped, every module once. Bit 21
 * e: the portable part an app mounts reaches no node API and none of the node modules; the standalone package's joins
 * every module but the mount.
 */
import { readdirSync, readFileSync } from "node:fs"
import { describe, expect, it } from "vitest"
import { MCP_NODE, MCP_PORTABLE, MCP_RUNTIME, MCP_STANDALONE, mcpRuntimeSource } from "./runtime.ts"

const MARKER = "// Code generated by honey. DO NOT EDIT."

/** A runtime/mcp module's source. */
const runtimeModule = (name: string) => readFileSync(new URL(`../../runtime/mcp/${name}.ts`, import.meta.url), "utf8")

describe("the vendored runtime (phase a)", () => {
	// v0: 9b4a7eba93
	it("joins the vendored runtime into one module, each runtime/mcp file after the ones it imports, their imports of each other dropped", () => {
		const text = mcpRuntimeSource(MCP_RUNTIME)
		/* each module's own imports of its siblings, by name, read from its source */
		const misplaced = MCP_RUNTIME.flatMap((name, at) =>
			[...runtimeModule(name).matchAll(/from "\.\/([\w-]+)\.ts"/g)]
				.map((match) => match[1] as string)
				.filter((sibling) => !MCP_RUNTIME.slice(0, at).includes(sibling))
				.map((sibling) => `${name} before ${sibling}`),
		)
		const firsts = MCP_RUNTIME.map(
			(name) =>
				runtimeModule(name)
					.split("\n")
					.find((line) => line.startsWith("export ")) as string,
		)
		expect([
			text.startsWith(`${MARKER}\n\n`),
			misplaced,
			firsts
				.map((line) => text.indexOf(line))
				.every((at, i, all) => at > 0 && (i === 0 || at > (all[i - 1] as number))),
			/from "\.\/[\w-]+\.ts"/.test(text),
		]).toEqual([true, [], true, false])
	})
})

describe("the runtime's modules (phase c)", () => {
	it("joins every runtime/mcp module once, and nothing else", () => {
		const modules = readdirSync(new URL("../../runtime/mcp/", import.meta.url))
			.filter((file) => file.endsWith(".ts") && !file.endsWith(".test.ts"))
			.map((file) => file.slice(0, -3))
		expect([...MCP_RUNTIME].sort()).toEqual(modules.sort())
	})
})

describe("the portable runtime (bit 21 e)", () => {
	it("imports no node module and none of the node runtime modules, and touches neither process nor Buffer", () => {
		const leaks = MCP_PORTABLE.flatMap((name) => {
			const source = runtimeModule(name)
			const imports = [...source.matchAll(/from "([^"]+)"/g)].map((match) => match[1] as string)
			return [
				...imports.filter((spec) => !spec.startsWith("./")).map((spec) => `${name} imports ${spec}`),
				...imports
					.filter((spec) => MCP_NODE.includes(spec.slice(2, -3)))
					.map((spec) => `${name} imports the node module ${spec}`),
				/* the code, its comments dropped */
				...[...source.replace(/\/\*[\s\S]*?\*\/|^\s*\/\/.*$/gm, "").matchAll(/\b(process|Buffer|NodeJS)\b/g)].map(
					(match) => `${name} uses ${match[1]}`,
				),
			]
		})
		const joined = mcpRuntimeSource(MCP_PORTABLE)
		expect([leaks, /from "node:|\bprocess\.|\bBuffer\./.test(joined)]).toEqual([[], false])
	})

	it("splits every module into the portable part or the node part, never both; the standalone package all but the mount", () => {
		expect([
			MCP_PORTABLE.filter((name) => MCP_NODE.includes(name)),
			[...MCP_PORTABLE, ...MCP_NODE].sort(),
			MCP_STANDALONE,
			mcpRuntimeSource() === mcpRuntimeSource(MCP_STANDALONE),
		]).toEqual([[], [...MCP_RUNTIME].sort(), MCP_RUNTIME.filter((name) => name !== "mount"), true])
	})
})
