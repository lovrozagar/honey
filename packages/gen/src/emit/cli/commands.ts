/**
 * One command per operation (bit 17 phase b), by its dotted id: `items.get` is `items get`, `a.b.c` is `a b c`, a flat
 * id (`getRoot`) a top-level `get-root`. The verb is the id's last segment as authored, never renamed. In a group a
 * subgroup claims its name before a command, and at the root every built-in (completion, commands, config, help,
 * schema, skill, version) is taken first, so a clash is suffixed as the IR suffixes ids (`version2`). Each command calls
 * the embedded SDK's own method by the emitter's call plan, its result printed by the runtime. Phase b emits every
 * operation that answers once with a JSON, text, form or binary body, or none; streams join at d, multipart at c.
 */
import type { IR } from "../../ir/model.ts"
import type { SdkOp } from "../../ir/sdk-model.ts"
import type { GoCallPlan } from "../go/sdk-client.ts"
import { NOT_CODE } from "../go/sdk.ts"
import { goString, lineComment } from "../shared/escape.ts"
import { compareCodeUnits, NameScope, pascalWords, snakeWords } from "../shared/lang.ts"
import { commandFlags, helpText, kebab } from "./flags.ts"

/* the marker gopls and linters read, apart from the package doc by a blank line */
const MARKER = "// Code generated by honey. DO NOT EDIT."

/** The root's own commands, each taken before an operation's. */
export const BUILT_INS = ["commands", "completion", "config", "help", "schema", "skill", "version"]

/** A command node: a group of others, or one operation's command. */
export type CommandNode = {
	readonly name: string
	readonly fn: string
	readonly children: readonly CommandNode[]
	readonly op?: { readonly op: SdkOp; readonly plan: GoCallPlan }
}

/** Whether phase b gives `op` a command: it answers once, its body none of multipart's. */
export const commanded = (op: SdkOp): boolean => op.stream === null && op.body?.kind !== "multipart"

/** The raw tree: each segment's subtree, and the operation a path ends at. */
type Raw = { readonly groups: Map<string, Raw>; readonly leaves: Map<string, { op: SdkOp; plan: GoCallPlan }> }

function rawTree(ops: readonly SdkOp[], plans: Readonly<Record<string, GoCallPlan>>): Raw {
	const root: Raw = { groups: new Map(), leaves: new Map() }
	for (const op of [...ops].filter(commanded).sort((a, b) => compareCodeUnits(a.id, b.id))) {
		let at = root
		for (const segment of op.segments.slice(0, -1)) {
			if (!at.groups.has(segment)) at.groups.set(segment, { groups: new Map(), leaves: new Map() })
			at = at.groups.get(segment) as Raw
		}
		at.leaves.set(op.segments.at(-1) as string, { op, plan: plans[op.id] as GoCallPlan })
	}
	return root
}

/** `raw` named: its groups first, then its commands, each claimed in its parent's scope; funcs claimed in `funcs`. */
function named(raw: Raw, path: readonly string[], scope: NameScope, funcs: NameScope): CommandNode[] {
	const groups = [...raw.groups].sort(([a], [b]) => compareCodeUnits(a, b))
	const leaves = [...raw.leaves].sort(([a], [b]) => compareCodeUnits(a, b))
	return [
		...groups.map(([segment, child]): CommandNode => {
			const name = scope.claim(kebab(segment))
			const at = [...path, name]
			return {
				children: named(child, at, new NameScope(), funcs),
				fn: funcs.claim(`new${pascalWords(at.join(" "))}Cmd`),
				name,
			}
		}),
		...leaves.map(([segment, leaf]): CommandNode => {
			const name = scope.claim(kebab(segment))
			return { children: [], fn: funcs.claim(`new${pascalWords([...path, name].join(" "))}Cmd`), name, op: leaf }
		}),
	]
}

/** The command tree under the root, by the ids of every operation `ops` holds a command for. */
export function commandTree(ops: readonly SdkOp[], plans: Readonly<Record<string, GoCallPlan>>): CommandNode[] {
	return named(rawTree(ops, plans), [], new NameScope(BUILT_INS), new NameScope(["Root", "newClient", "failed"]))
}

/** A named type of the SDK's, as package cmd spells it: `sdk.` before each exported name. */
const qualified = (type: string) => type.replace(/(?<![\w.])([A-Z]\w*)/g, "sdk.$1")

/** The statements reading the body, and the argument passing it. */
function bodyLines(op: SdkOp, plan: GoCallPlan, fields: readonly (readonly [string, string])[]): [string[], string] {
	const body = op.body
	if (body === undefined) return [[], ""]
	const required = String(body.required)
	const map = `map[string]string{${fields.map(([flag, key]) => `${goString(flag)}: ${goString(key)}`).join(", ")}}`
	const fail = ["\tif err != nil {", "\t\treturn err", "\t}"]
	switch (body.kind) {
		case "json": {
			/* a pointer type decodes as well: json.Unmarshal allocates it, and an absent optional body stays nil */
			const read = `\tif err := p.JSON(&body, ${required}, ${map}); err != nil {`
			return [[`\tvar body ${qualified(plan.bodyType as string)}`, read, "\t\treturn err", "\t}"], ", body"]
		}
		case "form":
			return [[`\tbody, err := p.Form(${required}, ${map})`, ...fail], ", body"]
		case "text":
			return [[`\tbody, err := p.Text(${required})`, ...fail], ", body"]
		default:
			return [[`\tbody, err := p.Reader(${required})`, ...fail], ", body"]
	}
}

/** The call and what follows it, by what the method returns. */
function callLines(call: string, returns: string): string[] {
	if (returns === "error") return [`\tif err := ${call}; err != nil {`, "\t\treturn failed(err)", "\t}", "\treturn nil"]
	return [
		`\tanswer, err := ${call}`,
		"\tif err != nil {",
		"\t\treturn failed(err)",
		"\t}",
		"\treturn cli.Print(c, answer)",
	]
}

/** An operation's command function: its flags, then the RunE that checks them, calls the SDK and prints. */
function opFunc(node: CommandNode, path: readonly string[], ir: IR): string[] {
	const { op, plan } = node.op as { op: SdkOp; plan: GoCallPlan }
	const flags = commandFlags(op, plan, ir.schemas)
	const use = [node.name, ...plan.pathParams.map((name) => `<${kebab(name)}>`)].join(" ")
	const [read, bodyArg] = bodyLines(op, plan, flags.fields)
	const args = plan.pathParams.map((_, i) => `, path[${i}]`).join("")
	const method = ["client", ...plan.members, plan.method].join(".")
	const cobra = [`Use: ${goString(use)}`, `Short: ${goString(helpText(op.summary))}`]
	if (op.description !== "") cobra.push(`Long: ${goString(helpText(op.description))}`)
	const run = [
		"\tif err := p.Check(); err != nil {",
		"\t\treturn err",
		"\t}",
		...(plan.pathParams.length > 0 ? ["\tpath := p.PathValues(args)"] : []),
		`\topts := &sdk.${plan.opts}{}`,
		...flags.opts,
		...read,
		"\tclient, err := newClient(c)",
		"\tif err != nil {",
		"\t\treturn err",
		"\t}",
		...callLines(`${method}(c.Context()${args}${bodyArg}, opts)`, plan.returns),
	]
	return [
		...lineComment(`${node.fn} is \`${[...path, node.name].join(" ")}\`: ${op.method} ${op.path}.`, "//"),
		`func ${node.fn}() *cobra.Command {`,
		`\tcmd := &cobra.Command{${cobra.join(", ")}}`,
		"\tp := cli.NewParams(cmd)",
		...flags.declare,
		`\tcmd.RunE = func(c *cobra.Command, ${plan.pathParams.length > 0 ? "args" : "_"} []string) error {`,
		...run.map((line) => `\t${line}`),
		"\t}",
		"\treturn cmd",
		"}",
	]
}

/** A group's command function, then each of its children's. */
function groupFuncs(node: CommandNode, path: readonly string[], ir: IR): string[][] {
	if (node.op !== undefined) return [opFunc(node, path, ir)]
	const at = [...path, node.name]
	const children = node.children.map((child) => `${child.fn}()`).join(", ")
	const own = [
		...lineComment(`${node.fn} is \`${at.join(" ")}\`, a group of commands.`, "//"),
		`func ${node.fn}() *cobra.Command {`,
		`\tcmd := cli.Group(&cobra.Command{Use: ${goString(node.name)}})`,
		`\tcmd.AddCommand(${children})`,
		"\treturn cmd",
		"}",
	]
	return [own, ...node.children.flatMap((child) => groupFuncs(child, at, ir))]
}

/** What a cmd file imports, by the packages its code names: cobra and the runtime always. */
const importsOf = (text: string) => {
	const code = text.replace(NOT_CODE, "")
	return ["cobra", "cli", ...["errors", "json", "sdk"].filter((name) => new RegExp(`\\b${name}\\.`).test(code))]
}

/** Each package a cmd file may import, by name, in its import group: the standard library, cobra, the module's own. */
const PACKAGES: Readonly<Record<string, readonly [group: number, path: (module: string) => string]>> = {
	cli: [2, (module) => `${module}/internal/cli`],
	cobra: [1, () => "github.com/spf13/cobra"],
	errors: [0, () => "errors"],
	json: [0, () => "encoding/json"],
	sdk: [2, (module) => `${module}/internal/sdk`],
}

/** A cmd file: the marker, its package and doc, its imports in gofmt's groups, then `body`. */
function cmdFile(module: string, body: string, doc = ""): string {
	const groups: string[][] = [[], [], []]
	for (const name of importsOf(body)) {
		const [group, path] = PACKAGES[name] as readonly [number, (module: string) => string]
		groups[group]?.push(`\t"${path(module)}"`)
	}
	const block = groups
		.filter((lines) => lines.length > 0)
		.map((lines) => lines.sort(compareCodeUnits).join("\n"))
		.join("\n\n")
	return `${MARKER}\n\n${doc}package cmd\n\nimport (\n${block}\n)\n\n${body}\n`
}

/** The CLI's name, description and environment prefix, and its module. */
export type CliApp = {
	readonly binaryName: string
	readonly short: string
	readonly envPrefix: string
	readonly modulePath: string
}

/** cmd/root.go: the root command, named by the binary, its top-level commands added. */
function rootBody(app: CliApp, nodes: readonly CommandNode[]): string {
	const declared = `cli.App{Name: ${goString(app.binaryName)}, Short: ${goString(helpText(app.short))}, EnvPrefix: ${goString(app.envPrefix)}}`
	const add = nodes.length === 0 ? [] : [`\troot.AddCommand(${nodes.map((node) => `${node.fn}()`).join(", ")})`]
	return [
		`// Root is the ${app.binaryName} command; every other command hangs under it.`,
		"func Root() *cobra.Command {",
		`\troot := cli.Root(${declared})`,
		...add,
		"\treturn root",
		"}",
	].join("\n")
}

/**
 * cmd/client.go: the SDK client the run's settings configure, its requests and responses logged under --verbose, and
 * an answer outside 2xx as the runtime's APIError. An API that declares no server needs a base URL set.
 */
function clientBody(app: CliApp, ir: IR): string {
	const env = `$${app.envPrefix}_BASE_URL`
	const noServer =
		ir.servers.length > 0
			? []
			: [
					'\tif s.BaseURL == "" {',
					`\t\treturn nil, cli.Usage(${goString(`no base URL: set --base-url, ${env} or base_url in the config file`)})`,
					"\t}",
				]
	return [
		"// newClient is the API client the run's settings configure.",
		"func newClient(c *cobra.Command) (*sdk.Client, error) {",
		"\ts, err := cli.Settings(c)",
		"\tif err != nil {",
		"\t\treturn nil, err",
		"\t}",
		...noServer,
		"\treturn sdk.NewClient(sdk.Config{",
		"\t\tBaseURL: s.BaseURL, BearerToken: s.APIKey, Headers: s.Headers, Timeout: s.Timeout,",
		"\t\tOnRequest: []func(*sdk.RequestContext) error{func(rc *sdk.RequestContext) error {",
		"\t\t\ts.LogRequest(rc.Method, rc.URL, rc.Headers)",
		"\t\t\treturn nil",
		"\t\t}},",
		"\t\tOnResponse: []func(*sdk.ResponseContext) error{func(rc *sdk.ResponseContext) error {",
		"\t\t\ts.LogResponse(rc.Status, rc.Headers)",
		"\t\t\treturn nil",
		"\t\t}},",
		"\t}), nil",
		"}",
		"",
		"// failed is err as the CLI reports it: an answer outside 2xx with its status, error key and message.",
		"func failed(err error) error {",
		"\tvar answer *sdk.ClientError",
		"\tif errors.As(err, &answer) {",
		"\t\treturn &cli.APIError{Status: answer.StatusCode, Key: string(answer.Key), Message: answer.Message, Err: err}",
		"\t}",
		"\treturn err",
		"}",
	].join("\n")
}

/** Every file under cmd/: root.go, client.go, and `<name>_cmds.go` for each top-level command (a group and all below). */
export function cmdFiles(app: CliApp, ir: IR, nodes: readonly CommandNode[]): Record<string, string> {
	const stems = new NameScope(["client", "root"])
	const files: Record<string, string> = {
		"cmd/client.go": cmdFile(app.modulePath, clientBody(app, ir)),
		"cmd/root.go": cmdFile(
			app.modulePath,
			rootBody(app, nodes),
			`// Package cmd holds the ${app.binaryName} commands.\n`,
		),
	}
	for (const node of nodes) {
		const body = groupFuncs(node, [], ir)
			.map((lines) => lines.join("\n"))
			.join("\n\n")
		files[`cmd/${stems.claim(snakeWords(node.name))}_cmds.go`] = cmdFile(app.modulePath, body)
	}
	return files
}
