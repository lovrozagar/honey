import { readFileSync } from "node:fs"
import { describe, expect, it } from "vitest"
import { generateGoCLI } from "../../../../src/codegen-go-cli.ts"

/* ── fixture loader ── */

function loadFixture(name: string): Record<string, unknown> {
	const url = new URL(`../fixtures/go-cli/${name}.json`, import.meta.url)
	return JSON.parse(readFileSync(url, "utf8")) as Record<string, unknown>
}

/* ── Go bracket-balance helper (duplicated from go-sdk.test.ts:37-93) ── */

function assertBalancedGoBrackets(src: string): void {
	let braces = 0
	let parens = 0
	let brackets = 0
	let i = 0
	while (i < src.length) {
		if (src[i] === "/" && src[i + 1] === "*") {
			i += 2
			while (i < src.length && !(src[i] === "*" && src[i + 1] === "/")) i++
			i += 2
			continue
		}
		if (src[i] === "/" && src[i + 1] === "/") {
			while (i < src.length && src[i] !== "\n") i++
			continue
		}
		if (src[i] === "`") {
			i++
			while (i < src.length && src[i] !== "`") i++
			i++
			continue
		}
		if (src[i] === '"') {
			i++
			while (i < src.length && src[i] !== '"') {
				if (src[i] === "\\") i++
				i++
			}
			i++
			continue
		}
		if (src[i] === "'") {
			i++
			while (i < src.length && src[i] !== "'") {
				if (src[i] === "\\") i++
				i++
			}
			i++
			continue
		}
		if (src[i] === "{") braces++
		else if (src[i] === "}") braces--
		else if (src[i] === "(") parens++
		else if (src[i] === ")") parens--
		else if (src[i] === "[") brackets++
		else if (src[i] === "]") brackets--
		i++
	}
	expect(braces, "unbalanced {}").toBe(0)
	expect(parens, "unbalanced ()").toBe(0)
	expect(brackets, "unbalanced []").toBe(0)
}

/* ── Tier 1: scaffold + command tree ── */

describe("go-cli codegen — Tier 1: scaffold", () => {
	const crudSpec = loadFixture("crud")

	it("[#1] generateGoCLI returns { files, serviceMap, skippedOperations }", () => {
		const result = generateGoCLI(crudSpec, { binaryName: "acme" })
		expect(result).toHaveProperty("files")
		expect(result).toHaveProperty("serviceMap")
		expect(result).toHaveProperty("skippedOperations")
		expect(Array.isArray(result.skippedOperations)).toBe(true)
	})

	it("[#2] files object contains main.go, cmd/root.go, cmd/users.go, go.mod, README.md", () => {
		const result = generateGoCLI(crudSpec, { binaryName: "acme" })
		expect(result.files).toHaveProperty("main.go")
		expect(result.files).toHaveProperty("cmd/root.go")
		expect(result.files).toHaveProperty("cmd/users.go")
		expect(result.files).toHaveProperty("go.mod")
		expect(result.files).toHaveProperty("README.md")
	})

	it("[#3] main.go has `package main` and calls cmd.Execute()", () => {
		const result = generateGoCLI(crudSpec, { binaryName: "acme" })
		const main = result.files["main.go"]
		expect(main).toContain("package main")
		expect(main).toContain("cmd.Execute()")
	})

	it("[#4] cmd/root.go opens with generated header, package cmd, cobra import, and registers 6 global flags", () => {
		const result = generateGoCLI(crudSpec, { binaryName: "acme" })
		const root = result.files["cmd/root.go"]
		expect(root).toMatch(/^\/\/ Code generated by honey\. DO NOT EDIT\./)
		expect(root).toContain("package cmd")
		expect(root).toContain("github.com/spf13/cobra")
		expect(root).toContain(`"api-key"`)
		expect(root).toContain(`"base-url"`)
		expect(root).toContain(`"output"`)
		expect(root).toContain(`"verbose"`)
		expect(root).toContain(`"config"`)
		expect(root).toContain(`"timeout"`)
	})

	it("[#5] cmd/root.go registers every resource subcommand via rootCmd.AddCommand(usersCmd)", () => {
		const result = generateGoCLI(crudSpec, { binaryName: "acme" })
		const root = result.files["cmd/root.go"]
		expect(root).toContain("rootCmd.AddCommand(usersCmd)")
	})

	it('[#6] cmd/users.go declares usersCmd cobra Command with Use: "users" and a Short description', () => {
		const result = generateGoCLI(crudSpec, { binaryName: "acme" })
		const users = result.files["cmd/users.go"]
		expect(users).toContain("var usersCmd = &cobra.Command{")
		expect(users).toMatch(/Use:\s*"users"/)
		expect(users).toMatch(/Short:\s*"[^"]+"/)
	})

	it("[#7] usersCmd has child subcommands added for each action (list, create, get, update, delete)", () => {
		const result = generateGoCLI(crudSpec, { binaryName: "acme" })
		const users = result.files["cmd/users.go"]
		expect(users).toContain("usersCmd.AddCommand(usersListCmd)")
		expect(users).toContain("usersCmd.AddCommand(usersCreateCmd)")
		expect(users).toContain("usersCmd.AddCommand(usersGetCmd)")
		expect(users).toContain("usersCmd.AddCommand(usersUpdateCmd)")
		expect(users).toContain("usersCmd.AddCommand(usersDeleteCmd)")
	})

	it("[#8] bracket balance holds for cmd/root.go and every cmd/*.go file", () => {
		const result = generateGoCLI(crudSpec, { binaryName: "acme" })
		assertBalancedGoBrackets(result.files["cmd/root.go"])
		for (const [name, content] of Object.entries(result.files)) {
			if (name.startsWith("cmd/") && name.endsWith(".go")) {
				assertBalancedGoBrackets(content)
			}
		}
	})
})
