/**
 * The Java SDK as files (bit 16, R5): `generateJavaSdk` writes the Gradle build, the client and the vendored runtime
 * for a document. Phase a's client has no operation yet: `<Client>.builder().baseUrl(…).build()` holds one transport,
 * whose `HttpClient` follows no redirect on its own (R2 owns the follow loop) and is never closed (`--release 17` has
 * no `HttpClient.close`). The emitted Java is google-java-format's canonical form by construction (format.test.ts).
 */
import { readFileSync } from "node:fs"
import { compareCodeUnits } from "../shared/lang.ts"
import {
	buildGradle,
	type JavaPackage,
	settingsGradle,
	validateArtifactId,
	validateClientName,
	validateGroupId,
	validatePackageName,
	validateVersion,
} from "./gradle.ts"

/** The package's options, each defaulted and validated. */
export type JavaSdkOptions = {
	/** the Maven group id; `ai.anyrow` by default */
	readonly groupId?: string
	/** the Maven artifact id and the root project's name; `anyrow` by default */
	readonly artifactId?: string
	/** the package of every type; the group id by default */
	readonly packageName?: string
	/** the client class; `<Last package segment>Client` by default */
	readonly clientName?: string
	/** the package version; `0.1.0` by default */
	readonly version?: string
}

/** The SDK's files by path. */
export type GeneratedJavaSdk = { readonly files: Readonly<Record<string, string>> }

/** The marker on line 1 of every emitted file. */
const MARKER = "// @generated by honey. DO NOT EDIT."

/* the package line of every vendored runtime file */
const RUNTIME_PACKAGE = /^package honey\.runtime;$/m

/** The validated package for `options`. */
function packageOf(options: JavaSdkOptions): JavaPackage {
	const groupId = validateGroupId(options.groupId ?? "ai.anyrow")
	const packageName = validatePackageName(options.packageName ?? groupId)
	const last = packageName.split(".").at(-1) as string
	return {
		artifactId: validateArtifactId(options.artifactId ?? "anyrow"),
		clientName: validateClientName(options.clientName ?? `${last.charAt(0).toUpperCase()}${last.slice(1)}Client`),
		groupId,
		packageName,
		version: validateVersion(options.version ?? "0.1.0"),
	}
}

/** The client class: its builder takes the base URL and builds the one transport. */
const clientJava = (pkg: JavaPackage): string => `package ${pkg.packageName};

import java.net.URI;

/** The client for the API. Build one with {@link #builder()}. */
public final class ${pkg.clientName} {
  private final Transport transport;

  private ${pkg.clientName}(Transport transport) {
    this.transport = transport;
  }

  /** A builder for a client; the base URL is required. */
  public static Builder builder() {
    return new Builder();
  }

  /** Builds an {@link ${pkg.clientName}}. */
  public static final class Builder {
    private URI baseUrl;

    private Builder() {}

    /** Sets the base URL that every request resolves against. */
    public Builder baseUrl(String baseUrl) {
      this.baseUrl = URI.create(baseUrl);
      return this;
    }

    /** Builds the client; throws {@link IllegalStateException} when no base URL was set. */
    public ${pkg.clientName} build() {
      if (baseUrl == null) {
        throw new IllegalStateException("baseUrl is required");
      }
      return new ${pkg.clientName}(new Transport(baseUrl));
    }
  }
}
`

/** The vendored runtime's files by class name, read from disk on every call, in `packageName`. */
export function runtimeFiles(packageName: string): Record<string, string> {
	return Object.fromEntries(
		["Transport"].map((name) => [
			name,
			readFileSync(new URL(`../../runtime/java/${name}.java`, import.meta.url), "utf8").replace(
				RUNTIME_PACKAGE,
				() => `package ${packageName};`,
			),
		]),
	)
}

/** The package's files for `document`, by path, in code-unit order. */
export function generateJavaSdk(_document: Record<string, unknown>, options: JavaSdkOptions = {}): GeneratedJavaSdk {
	const pkg = packageOf(options)
	const dir = `src/main/java/${pkg.packageName.replaceAll(".", "/")}`
	const runtime = Object.entries(runtimeFiles(pkg.packageName)).map(([name, text]) => [`${dir}/${name}.java`, text])
	const files: Record<string, string> = {
		"build.gradle": `${MARKER}\n${buildGradle(pkg)}`,
		"settings.gradle": `${MARKER}\n${settingsGradle(pkg)}`,
		[`${dir}/${pkg.clientName}.java`]: `${MARKER}\n${clientJava(pkg)}`,
		...Object.fromEntries(runtime),
	}
	return { files: Object.fromEntries(Object.entries(files).sort(([a], [b]) => compareCodeUnits(a, b))) }
}
