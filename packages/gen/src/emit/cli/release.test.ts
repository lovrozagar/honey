/** The module `generated` holds, written to a fresh git repo; `remote` its origin when given. */
function written(generated: Readonly<Record<string, string>>, remote?: string): string {
	const dir = mkdtempSync(join(goCacheDir("tmp"), "release-"))
	for (const [name, text] of Object.entries(generated)) {
		mkdirSync(dirname(join(dir, name)), { recursive: true })
		writeFileSync(join(dir, name), text)
	}
	spawnSync("git", ["init", "-q"], { cwd: dir })
	if (remote !== undefined) spawnSync("git", ["remote", "add", "origin", remote], { cwd: dir })
	return dir
}

describe("the release files (phase g)", () => {
	it("writes .goreleaser.yaml and the release workflow byte for byte", () => {
		const generated = files()
		expect([generated[".goreleaser.yaml"], generated[".github/workflows/release.yml"]]).toEqual([GORELEASER, WORKFLOW])
	})

	it("releases to the git remote's repository when none is named, and keeps every value a YAML string", () => {
		const bare = files({ binaryName: "true" })[".goreleaser.yaml"] ?? ""
		const parsed = yamlValue(bare) as { project_name: unknown; release?: unknown }
		expect([parsed.project_name, parsed.release, bare.includes("owner: OWNER, name: homebrew-tap")]).toEqual([
			"true",
			undefined,
			true,
		])
	})

	it.each([
		"acme",
		"acme/",
		"/shop",
		"-acme/shop",
		"acme-/shop",
		"ac--me/shop",
		`${"a".repeat(40)}/shop`,
		"acme/.",
		"acme/..",
		"acme/shop.git",
		`acme/${"s".repeat(101)}`,
		"acme/sh op",
		"acme/shop'$(id)",
		"acme/shop\nx",
		"ac.me/shop",
	])("refuses repo %j at generate", (repo) => {
		expect(() => files({ repo })).toThrow(`Invalid repo: ${JSON.stringify(repo)}`)
	})

	it("accepts a repository GitHub accepts", () => {
		expect(files({ repo: "Acme-Co9/shop.cli_x-1" })[".goreleaser.yaml"]).toContain('name: "shop.cli_x-1"')
	})
})

describe.skipIf(!TOOLS)("goreleaser check (phase g)", () => {
	it("passes the config with a repository, and without one beside a GitHub remote", () => {
		const runs = [written(files()), written(files({}), "https://github.com/acme/shop.git")].map((dir) =>
			spawnSync(toolBin("goreleaser"), ["check"], { cwd: dir, encoding: "utf8" }),
		)
		expect(runs.map((ran) => [ran.status, /1 configuration file\(s\) validated/.test(ran.stderr)])).toEqual([
			[0, true],
			[0, true],
		])
	})
})
