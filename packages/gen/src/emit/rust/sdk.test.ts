/**
 * `text` in the TOML subset Cargo writes: `[table]`, `[[array of tables]]`, comment lines, and `key = value`
 * whose value is a string, number, boolean, inline table or array (an array may span lines). Anything else
 * throws, so a shape the reader does not know fails loudly instead of reading as absent.
 */
function toml(text: string): Json {
	const root: Json = {}
	let table = root
	const joined = text.replace(/= \[\n([^\]]*)\]/g, (_, items: string) => `= [${items.replace(/\n/g, " ")}]`)
	for (const raw of joined.split("\n")) {
		const line = raw.trim()
		if (line === "" || line.startsWith("#")) continue
		const array = /^\[\[([\w-]+)\]\]$/.exec(line)?.[1]
		const header = /^\[([\w-]+)\]$/.exec(line)?.[1]
		const pair = /^([\w-]+)\s*=\s*(.+)$/.exec(line)
		if (array !== undefined) {
			const list = (root[array] ??= []) as Json[]
			table = {}
			list.push(table)
		} else if (header !== undefined) table = root[header] = {}
		else if (pair) {
			const json = (pair[2] as string).replace(/([{,]\s*)([\w-]+)\s*=\s*/g, '$1"$2": ').replace(/,\s*([\]}])/g, "$1")
			table[pair[1] as string] = JSON.parse(json)
		} else throw new Error(`not TOML this reader knows: ${line}`)
	}
	return root
}

const manifest = (files: Files) => toml(files["Cargo.toml"] ?? "")
const dependencies = (files: Files) => (manifest(files).dependencies ?? {}) as Record<string, Requirement>
const lockOf = (files: Files) => (toml(files["Cargo.lock"] ?? "").package ?? []) as LockPackage[]
const roots = (lock: readonly LockPackage[]) => lock.filter((entry) => entry.source === undefined)
const named = (entry: LockPackage) => `${entry.name} ${entry.version}`
/** `name` of a lock `dependencies` entry, which carries a version only when two are locked. */
const depName = (entry: string) => entry.split(" ")[0] as string

/** The locked version of the root's dependency `name`: the one its entry names, else the only one locked. */
function locked(lock: readonly LockPackage[], name: string): string {
	const entry = roots(lock)[0]?.dependencies?.find((dep) => depName(dep) === name)
	return (
		entry?.split(" ")[1] ??
		lock
			.filter((p) => p.name === name)
			.map((p) => p.version)
			.join(", ")
	)
}

/** The document with its paths, and the methods inside each, in reverse order. */
const reordered = (document: Json): Json => ({
	...document,
	paths: Object.fromEntries(
		Object.entries(document.paths as Record<string, Json>)
			.toReversed()
			.map(([key, item]) => [key, Object.fromEntries(Object.entries(item).toReversed())]),
	),
})

/** The files map's keys, in the order the emitter wrote them. */
const fileSet = (document: Json) => Object.keys(generateRustSdk(document).files)

/** Cargo.toml's first line, and the `.rs` files whose first line is not the marker. */
function marks(document: Json) {
	const { files } = generateRustSdk(document)
	const rs = Object.entries(files).filter(([name]) => name.endsWith(".rs"))
	return {
		cargo: files["Cargo.toml"]?.split("\n")[0],
		rs: rs.length > 0,
		unmarked: rs.filter(([, text]) => text.split("\n")[0] !== MARK_RS).map(([name]) => name),
	}
}

/** The package's name and version, the lock's roots, whether the lock is in name order, and any `honey-sdk` left. */
function identity(options: RustSdkOptions) {
	const { files } = generateRustSdk(minimal, options)
	const lock = lockOf(files)
	const names = lock.map((entry) => entry.name)
	const { name, version } = manifest(files).package as Json
	return {
		honey: ["Cargo.lock", "Cargo.toml"].filter((key) => files[key]?.includes("honey-sdk")),
		inOrder: names.join("\n") === sorted(names).join("\n"),
		package: { name, version },
		roots: roots(lock).map(named),
	}
}

/**
 * The declared dependencies, those whose requirement is not a bare `x.y.z` equal to the locked version, the
 * lock root's dependencies, and the tungstenite packages locked.
 */
function declared(document: Json) {
	const { files } = generateRustSdk(document)
	const lock = lockOf(files)
	const requirements = Object.entries(dependencies(files))
	return {
		names: sorted(requirements.map(([name]) => name)),
		offFloor: requirements
			.filter(([name, requirement]) => {
				const version = typeof requirement === "string" ? requirement : requirement.version
				return !/^\d+\.\d+\.\d+$/.test(version) || version !== locked(lock, name)
			})
			.map(([name]) => name),
		root: sorted((roots(lock)[0]?.dependencies ?? []).map(depName)),
		tungstenite: sorted(lock.filter((p) => /^(tokio-)?tungstenite$/.test(p.name)).map((p) => p.name)),
	}
}

/** reqwest's default features, the TLS features it lacks or has from native TLS, and any OpenSSL package locked. */
function tls(document: Json) {
	const { files } = generateRustSdk(document)
	const reqwest = dependencies(files).reqwest
	const features = typeof reqwest === "object" ? (reqwest.features ?? []) : []
	return {
		defaultFeatures: typeof reqwest === "object" ? reqwest["default-features"] : true,
		missing: ["json", "rustls", "stream"].filter((feature) => !features.includes(feature)),
		native: features.filter((feature) => /native-tls|default-tls/.test(feature)),
		openssl: lockOf(files)
			.filter((p) => ["native-tls", "openssl", "openssl-sys"].includes(p.name))
			.map(named),
	}
}

