/**
 * The CLI module (bit 17 phase a): the zero-op module's files byte for byte, its file set (the runtime under
 * `internal/cli`, the API's own Go SDK under `internal/sdk`), the options' defaults and refusals, and the module built
 * and vetted at the pin and at the go 1.24 floor, gofmt-clean, tidy as written, and linked into a static binary whose
 * version, help and usage errors answer as a script expects.
 */
import { describe, expect, it } from "vitest"
import { generateGoSdk } from "../go/sdk.ts"
import { GO_FLOOR, gofmtPath, runGo, withGo } from "../go/__fixtures__/go-env.ts"
import { goString } from "../shared/escape.ts"
import { ws } from "../shared/__fixtures__/documents-streams.ts"
import { builtCli, STAMPED } from "./__fixtures__/built.ts"
import { binaryNameOf, CLI_RUNTIME, generateGoCli } from "./module.ts"
import { spawnSync } from "node:child_process"

type Json = Record<string, unknown>

/** Whether Go is pinned here: a missing toolchain fails where it is required and skips these legs elsewhere. */
const GO = withGo()
/** A cold module cache fetches cobra first. */
const SLOW = { timeout: 600_000 }

/** The zero-op document: no path, so no operation. */
const ZERO: Json = { info: { title: "Anyrow", version: "1" }, openapi: "3.1.0", paths: {} }

const MAIN_GO = `// Code generated by honey. DO NOT EDIT.

package main

import (
\t"os"

\t"example.com/anyrow/cmd"
\t"example.com/anyrow/internal/cli"
)

func main() {
\tos.Exit(cli.Run(cmd.Root(), os.Args[1:], os.Stdout, os.Stderr))
}
`

const ROOT_GO = `// Code generated by honey. DO NOT EDIT.

// Package cmd holds the anyrow commands.
package cmd

import (
\t"github.com/spf13/cobra"

\t"example.com/anyrow/internal/cli"
)

// Root is the anyrow command; every other command hangs under it.
func Root() *cobra.Command {
\troot := cli.Root(cli.App{Name: "anyrow", Short: "Anyrow", EnvPrefix: "ANYROW"})
\treturn root
}
`

const CLIENT_GO = `// Code generated by honey. DO NOT EDIT.

package cmd

import (
\t"errors"

\t"github.com/spf13/cobra"

\t"example.com/anyrow/internal/cli"
\t"example.com/anyrow/internal/sdk"
)

// newClient is the API client the run's settings configure.
func newClient(c *cobra.Command) (*sdk.Client, error) {
\ts, err := cli.Settings(c)
\tif err != nil {
\t\treturn nil, err
\t}
\tif s.BaseURL == "" {
\t\treturn nil, cli.Usage("no base URL: set --base-url, $ANYROW_BASE_URL or base_url in the config file")
\t}
\treturn sdk.NewClient(sdk.Config{
\t\tBaseURL: s.BaseURL, BearerToken: s.APIKey, Headers: s.Headers, Timeout: s.Timeout,
\t\tOnRequest: []func(*sdk.RequestContext) error{func(rc *sdk.RequestContext) error {
\t\t\ts.LogRequest(rc.Method, rc.URL, rc.Headers)
\t\t\treturn nil
\t\t}},
\t\tOnResponse: []func(*sdk.ResponseContext) error{func(rc *sdk.ResponseContext) error {
\t\t\ts.LogResponse(rc.Status, rc.Headers)
\t\t\treturn nil
\t\t}},
\t}), nil
}

// failed is err as the CLI reports it: an answer outside 2xx with its status, error key and message.
func failed(err error) error {
\tvar answer *sdk.ClientError
\tif errors.As(err, &answer) {
\t\treturn &cli.APIError{Status: answer.StatusCode, Key: string(answer.Key), Message: answer.Message, Err: err}
\t}
\treturn err
}
`

const GO_MOD = `module example.com/anyrow

go 1.24

require (
\tgithub.com/pelletier/go-toml/v2 v2.4.3
\tgithub.com/spf13/cobra v1.10.2
\tgithub.com/spf13/pflag v1.0.10
)

require github.com/inconshreveable/mousetrap v1.1.0 // indirect
`

const zero = (options = {}) => generateGoCli(ZERO, options).files

describe("generateGoCli: the zero-op module's files", () => {
	it("writes main.go, cmd/root.go, cmd/client.go and go.mod byte for byte", () => {
		const files = zero()
		expect([files["main.go"], files["cmd/root.go"], files["cmd/client.go"], files["go.mod"]]).toEqual([
			MAIN_GO,
			ROOT_GO,
			CLIENT_GO,
			GO_MOD,
		])
	})

	it("ships the CLI runtime under internal/cli and the API's Go SDK under internal/sdk, its module files the CLI's", () => {
		const sdk = Object.keys(generateGoSdk(ZERO).files).filter((name) => name !== "go.mod" && name !== "go.sum")
		expect(Object.keys(zero()).sort()).toEqual(
			[
				"cmd/client.go",
				"cmd/root.go",
				"go.mod",
				"go.sum",
				...CLI_RUNTIME.map((name) => `internal/cli/${name}`),
				"main.go",
				...sdk.map((name) => `internal/sdk/${name}`),
			].sort(),
		)
	})

	it("marks line 1 of every .go file generated", () => {
		const unmarked = Object.entries(zero()).filter(
			([name, text]) => name.endsWith(".go") && text.split("\n")[0] !== "// Code generated by honey. DO NOT EDIT.",
		)
		expect(unmarked.map(([name]) => name)).toEqual([])
	})

	it("requires the WebSocket library, with its go.sum lines, when the embedded SDK needs it", () => {
		const files = generateGoCli(ws()).files
		expect({
			mod: files["go.mod"]?.includes("\tgithub.com/coder/websocket v1.8.15\n"),
			sum: files["go.sum"]?.includes("github.com/coder/websocket v1.8.15 h1:"),
		}).toEqual({ mod: true, sum: true })
		expect(zero()["go.sum"]).not.toContain("coder/websocket")
	})
})

describe("generateGoCli: its options (F2)", () => {
	it("names the binary by the title's words, `api` without one, and the module and prefix by the binary", () => {
		const untitled = generateGoCli({ info: { version: "1" }, openapi: "3.1.0", paths: {} }).files
		expect({
			hostile: binaryNameOf('9 Anyrow\'s "API"\n$(x)'),
			module: /^module (\S+)/.exec(untitled["go.mod"] ?? "")?.[1],
			untitled: binaryNameOf(undefined),
		}).toEqual({ hostile: "anyrow-s-api-x", module: "example.com/api", untitled: "api" })
	})

	it("writes the document's title into Go only as an escaped literal", () => {
		const title = 'Anyrow\'s "API" `x` */ \n $(rm -rf ~) %s \\'
		const root = generateGoCli({ ...ZERO, info: { title, version: "1" } }, { binaryName: "anyrow" }).files[
			"cmd/root.go"
		]
		expect(root).toContain(`cli.Root(cli.App{Name: "anyrow", Short: ${goString(title)}, EnvPrefix: "ANYROW"})`)
	})

	it.each([
		["binaryName", "Anyrow"],
		["binaryName", "any row"],
		["binaryName", "-anyrow"],
		["binaryName", "anyrow-"],
		["binaryName", "$(rm)"],
		["binaryName", "a/b"],
		["modulePath", "anyrow"],
		["modulePath", "example.com/a b"],
		["modulePath", "example.com/../x"],
		["modulePath", "Example.com/x"],
		["modulePath", "example.com/x/"],
		["modulePath", "example.com/x\nreplace y => ../z"],
		["envPrefix", "anyrow"],
		["envPrefix", "ANY-ROW"],
		["envPrefix", "_ANYROW"],
		["envPrefix", "ANYROW_"],
	])("refuses %s %j at generate", (option, value) => {
		expect(() => zero({ [option]: value })).toThrow(`Invalid ${option}: ${JSON.stringify(value)}`)
	})

	it("accepts a module path's versioned and dotted elements", () => {
		expect(zero({ modulePath: "github.com/acme-co/any.row/v2" })["go.mod"]).toMatch(
			/^module github.com\/acme-co\/any.row\/v2\n/,
		)
	})
})

describe.skipIf(!GO)("the zero-op module, built (phase a)", SLOW, () => {
	it.each([
		["the pin", undefined],
		["the go 1.24 floor", GO_FLOOR],
	])("builds and vets at %s, links a static binary, and is gofmt-clean and tidy as written", (_, toolchain) => {
		const built = builtCli(zero(), { toolchain })
		const tidy = runGo(["mod", "tidy", "-diff"], { cwd: built.dir, env: { GOFLAGS: "-modcacherw" }, toolchain })
		/* the embedded SDK's files take the gofmt post-pass go/format.test.ts proves; the CLI's own are gofmt-clean as written */
		const fmt = spawnSync(gofmtPath(toolchain), ["-l", "."], { cwd: built.dir, encoding: "utf8" })
		const unformatted = fmt.stdout.split("\n").filter((name) => name !== "" && !name.startsWith("internal/sdk/"))
		const settings = runGo(["version", "-m", built.binary], { toolchain }).stdout
		/* a cold module cache's `go: downloading` lines are build output, not errors: the build's status answers */
		expect(
			{
				built: built.built,
				gofmt: unformatted,
				link: built.linkErrors,
				static: /^\tbuild\tCGO_ENABLED=0$/m.test(settings),
				tidy: [tidy.status, tidy.stdout],
				vet: built.vet,
			},
			built.stderr,
		).toEqual({ built: true, gofmt: [], link: "", static: true, tidy: [0, ""], vet: [] })
	})

	it("is tidy as written with the WebSocket library required", () => {
		const built = builtCli(generateGoCli(ws()).files)
		const tidy = runGo(["mod", "tidy", "-diff"], { cwd: built.dir, env: { GOFLAGS: "-modcacherw" } })
		expect({ built: built.built, link: built.linkErrors, tidy: [tidy.status, tidy.stdout] }, built.stderr).toEqual({
			built: true,
			link: "",
			tidy: [0, ""],
		})
	})

	it("prints the stamped version alone, and its help with no command", async () => {
		const { cli } = builtCli(zero())
		const [version, bare] = [await cli(["--version"]), await cli([])]
		expect({
			bare: [bare.status, bare.stdout.split("\n")[0], bare.stderr],
			version: [version.status, version.stdout, version.stderr],
		}).toEqual({ bare: [0, "Anyrow", ""], version: [0, `${STAMPED}\n`, ""] })
	})

	it("exits 4 on an unknown command or flag, naming it on stderr after the CLI's name", async () => {
		const { cli } = builtCli(zero())
		const [command, flag] = [await cli(["frobnicate"]), await cli(["--nope"])]
		expect({
			command: [command.status, command.stdout, command.stderr],
			flag: [flag.status, flag.stdout, flag.stderr],
		}).toEqual({
			command: [4, "", 'anyrow: unknown command "frobnicate" for "anyrow"\n'],
			flag: [4, "", "anyrow: unknown flag: --nope\n"],
		})
	})
})
