/** client.py's lines, and the docstring of each `def <name>(` in it (sync and async), from its opening line. */
function docstrings(document: Json, name: string, options?: PythonSdkOptions): string[][] {
	const lines = (generatePythonSdk(document, options).files["src/honey_sdk/client.py"] ?? "").split("\n")
	return lines.flatMap((line, at) => {
		if (!new RegExp(`^ {4}(?:async )?def ${name}\\(`).test(line)) return []
		const open = lines.findIndex((text, i) => i > at && text.trimStart().startsWith('"""'))
		const close = lines.findIndex((text, i) => i > open && text.trimEnd().endsWith('"""'))
		return [open < 0 || close < 0 ? [] : lines.slice(open, close + 1)]
	})
}

/** Each `Raises:` block in client.py: the heading and the three status lines after it. */
const raisesBlocks = (throwOnError: boolean) => {
	const lines = (generatePythonSdk(RAISES, { throwOnError }).files["src/honey_sdk/client.py"] ?? "").split("\n")
	return lines.flatMap((line, at) => (line.trim() === "Raises:" ? [lines.slice(at, at + 4)] : []))
}

/** The `.py` files and pyproject.toml of `document`'s package whose first line is not the marker. */
const unmarked = (document: Json) =>
	Object.entries(generatePythonSdk(document).files)
		.filter(([name]) => name.endsWith(".py") || name === "pyproject.toml")
		.filter(([, text]) => text.split("\n")[0] !== MARK)
		.map(([name]) => name)

/** The registry document `key`'s operations whose plan leaves them off SDK, sorted. */
const asyncOnly = (key: "fixtures" | "surface") => {
	const entry = FIXTURES[key]
	return Object.values(pythonCallPlans(entry.document(), "options" in entry ? entry.options : undefined))
		.filter((plan) => !plan.sync)
		.map((plan) => plan.operation)
		.sort()
}

/** pyproject.toml of `document` under `options`, parsed by the pinned interpreter's own tomllib. */
function pyproject(document: Json, options?: PythonSdkOptions): Json {
	const input = generatePythonSdk(document, options).files["pyproject.toml"] ?? ""
	const parse = "import json, sys, tomllib; print(json.dumps(tomllib.loads(sys.stdin.read())))"
	const run = runPython(venv({ python: pinnedPython(), requirements: [] }), ["-c", parse], { input })
	if (run.status !== 0) throw new Error(`tomllib refused pyproject.toml:\n${run.stderr}\n${input}`)
	return JSON.parse(run.stdout) as Json
}

/** The dependency strings `document`'s pyproject.toml declares. */
const dependencies = (document: Json) => (pyproject(document).project as Json).dependencies

describe("generatePythonSdk: the package's files", () => {
	// v0: d57a6c7805
	it("emits pyproject.toml, the package's __init__, client, types and py.typed, and the runtime under _honey/, ws.py only for a WebSocket API and the realtime modules only for a realtime API", () => {
		/* V0BUG: v0 shipped no manifest or dependency declaration, and all 7 runtime files always (contract 28 §9.1) */
		expect({
			http: keysOf(minimal),
			realtime: keysOf(realtimeApi),
			runtime: runtimeOnDisk(),
			ws: keysOf(wsApi),
		}).toEqual({
			http: packageKeys(CORE),
			realtime: packageKeys([...CORE, ...WS, ...REALTIME]),
			runtime: [...CORE, ...WS, ...REALTIME].map((name) => `${name}.py`).sort(),
			ws: packageKeys([...CORE, ...WS]),
		})
	})

	it("marks every .py file and pyproject.toml @generated on line 1", () => {
		expect([unmarked(minimal), unmarked(realtimeApi)]).toEqual([[], []])
	})

	// v0: 27fb54d8c4
	it("ships py.typed empty (PEP 561)", () => {
		expect(generatePythonSdk(minimal).files["src/honey_sdk/py.typed"]).toBe("")
	})
})

describe.skipIf(!PY)("generatePythonSdk: pyproject.toml, read by tomllib", () => {
	it("declares honey-sdk 0.1.0 for Python >=3.11 on httpx2, built by hatchling from src/honey_sdk", () => {
		const toml = pyproject(minimal)
		expect(toml).toEqual({
			"build-system": { "build-backend": "hatchling.build", requires: ["hatchling>=1.27"] },
			project: {
				dependencies: ["httpx2>=2.12.0,<3"],
				name: "honey-sdk",
				"requires-python": ">=3.11",
				version: "0.1.0",
			},
			tool: { hatch: { build: { targets: { wheel: { packages: ["src/honey_sdk"] } } } } },
		})
	})

	it("depends on httpx2[ws] for a WebSocket or realtime API", () => {
		expect([dependencies(wsApi), dependencies(realtimeApi)]).toEqual([
			["httpx2[ws]>=2.12.0,<3"],
			["httpx2[ws]>=2.12.0,<3"],
		])
	})

	it("takes packageName and version into the distribution name, the version and the src/<package> path", () => {
		const options = { packageName: "acme_sdk", version: "1.0.0" }
		const toml = pyproject(minimal, options)
		expect({
			elsewhere: keysOf(minimal, options).filter((key) => key !== "pyproject.toml" && !key.startsWith("src/acme_sdk/")),
			packages: (toml.tool as { hatch: { build: { targets: { wheel: Json } } } }).hatch.build.targets.wheel.packages,
			project: { name: (toml.project as Json).name, version: (toml.project as Json).version },
		}).toEqual({ elsewhere: [], packages: ["src/acme_sdk"], project: { name: "acme-sdk", version: "1.0.0" } })
	})
})

describe("generatePythonSdk: the options it refuses", () => {
	it.each(["Bad Name!", "123x", "class", "_honey"])("refuses the package name %j", (packageName) => {
		expect(() => generatePythonSdk(minimal, { packageName })).toThrow(`Invalid package name: "${packageName}"`)
	})

	it("refuses a version outside PEP 440's subset", () => {
		expect(() => generatePythonSdk(minimal, { version: "1.0.0-beta" })).toThrow('Invalid version: "1.0.0-beta"')
	})
})

describe("generatePythonSdk: determinism and conflicts", () => {
	// v0: 67ae8ff84b
	// v0: ccf0031834
	it.each(DOCUMENTS)("emits identical files for %s twice and for its paths reordered", (_name, document, options) => {
		const { files } = generatePythonSdk(document, options)
		expect([generatePythonSdk(document, options).files, generatePythonSdk(reordered(document), options).files]).toEqual(
			[files, files],
		)
	})

	// v0: 87ccdf5091
	it("refuses an id that is both callable and a namespace, naming both ids", () => {
		expect(() => generatePythonSdk(COLLISION)).toThrow(/operationId conflict.*users\.create.*users\.create\.draft/)
	})
})

