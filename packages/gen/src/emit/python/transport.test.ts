/**
 * The vendored Python runtime's reader (contract 29 §5.11): the file set each feature mix ships, in code-unit order;
 * the files returned byte for byte from `runtime/python/`, each marked on line 1; determinism; and the root exports the
 * package's `__init__` star-lists, phase c's `FilePart`, `ErrorEnvelope` and `FieldError` among them.
 */
import { readFileSync } from "node:fs"
import { describe, expect, it } from "vitest"
import { needsWebSocket, publicNames, runtimeExports, runtimeFileNames, runtimeFiles } from "./transport.ts"

const MARK = "# @generated by honey. DO NOT EDIT."

/** Every SDK's runtime modules (phase-b §5.2; phase c adds no file, contract 29 §3.2), in code-unit order. */
const CORE = [
	"__init__.py",
	"auth.py",
	"body.py",
	"config.py",
	"errors.py",
	"events.py",
	"exchange.py",
	"hooks.py",
	"invalidation.py",
	"log.py",
	"operation.py",
	"path.py",
	"query.py",
	"redirect.py",
	"result.py",
	"send_async.py",
	"send_sync.py",
	"sse.py",
	"stale.py",
]

/** The full set: `ws.py` and the realtime transports on top of CORE, in code-unit order (`.` sorts before `_`). */
const FULL = [
	...CORE.slice(0, 13),
	"realtime.py",
	...CORE.slice(13),
	"transport.py",
	"transport_longpoll.py",
	"transport_sse.py",
	"transport_ws.py",
	"ws.py",
]

const MIXES = [
	{ realtime: false, ws: false },
	{ realtime: false, ws: true },
	{ realtime: true, ws: false },
	{ realtime: true, ws: true },
] as const

const onDisk = (name: string) => readFileSync(new URL(`../../runtime/python/${name}`, import.meta.url), "utf8")

describe("runtimeFileNames: which runtime modules a feature mix ships", () => {
	it("ships the 19 core modules for plain HTTP, ws.py on top for a WebSocket API, and the realtime transports on top of both for a realtime API", () => {
		expect(Object.fromEntries(MIXES.map((mix) => [JSON.stringify(mix), runtimeFileNames(mix)]))).toEqual({
			'{"realtime":false,"ws":false}': CORE,
			'{"realtime":false,"ws":true}': [...CORE, "ws.py"],
			'{"realtime":true,"ws":false}': FULL,
			'{"realtime":true,"ws":true}': FULL,
		})
		expect(CORE).toHaveLength(19)
	})

	it("depends on httpx2[ws] exactly when it ships ws.py", () => {
		expect(MIXES.map((mix) => needsWebSocket(mix))).toEqual(MIXES.map((mix) => runtimeFileNames(mix).includes("ws.py")))
		expect(MIXES.map((mix) => needsWebSocket(mix))).toEqual([false, true, true, true])
	})
})

describe("runtimeFiles: the runtime as shipped, read from runtime/python/", () => {
	it.each(MIXES)("returns each shipped module byte for byte as it is on disk, keyed in code-unit order (%o)", (mix) => {
		const files = runtimeFiles(mix)
		expect(Object.keys(files)).toEqual(runtimeFileNames(mix))
		expect(files).toEqual(Object.fromEntries(runtimeFileNames(mix).map((name) => [name, onDisk(name)])))
	})

	it("marks every module @generated on line 1", () => {
		const files = runtimeFiles({ realtime: true, ws: true })
		expect(Object.entries(files).filter(([, text]) => text.split("\n")[0] !== MARK)).toEqual([])
	})

	it("returns the same bytes on every call, in a fresh map the caller may change", () => {
		const first = runtimeFiles({ realtime: true, ws: true })
		const second = runtimeFiles({ realtime: true, ws: true })
		expect(second).toEqual(first)
		expect(second).not.toBe(first)
		delete first["errors.py"]
		expect(Object.keys(runtimeFiles({ realtime: true, ws: true }))).toEqual(FULL)
	})
})

describe("runtimeExports: what each runtime module adds to the package root", () => {
	const files = runtimeFiles({ realtime: true, ws: true })
	const exports = (name: string) => runtimeExports(files[name] ?? "")

	it("exports FilePart from body.py, the multipart file part (Fc6)", () => {
		expect(exports("body.py")).toEqual(["FilePart"])
	})

	it("exports ErrorEnvelope and FieldError from errors.py beside the error classes (Fc4)", () => {
		const names = new Set(exports("errors.py"))
		expect({
			envelope: ["ErrorEnvelope", "FieldError"].filter((name) => !names.has(name)),
			kept: ["APIStatusError", "HoneyError"].filter((name) => !names.has(name)),
		}).toEqual({ envelope: [], kept: [] })
	})

	it("exports only names its module defines at the top level", () => {
		expect(
			Object.entries(files).flatMap(([name, text]) =>
				runtimeExports(text)
					.filter((exported) => !publicNames(text).includes(exported))
					.map((exported) => `${name}: ${exported}`),
			),
		).toEqual([])
	})

	it("exports each name from one module only, since the root imports them all side by side", () => {
		const names = Object.values(files).flatMap(runtimeExports)
		expect(names.filter((name, at) => names.indexOf(name) !== at)).toEqual([])
	})

	it("reads __all__ on one line or across lines, and nothing from a module without one", () => {
		expect([
			runtimeExports('__all__ = ["A", "B"]\n'),
			runtimeExports('x = 1\n__all__ = [\n    "A",\n    "B",\n]\n'),
			runtimeExports("def f() -> None: ...\n"),
		]).toEqual([["A", "B"], ["A", "B"], []])
	})
})

describe("publicNames: a module's top-level public names", () => {
	it("takes class, def, async def and bound names at column 0, in source order, and skips private and nested ones", () => {
		const source = [
			"class A:",
			"    def inner(self) -> None: ...",
			"def b() -> None: ...",
			"async def c() -> None: ...",
			"D = 1",
			"E: int = 2",
			"_F = 3",
			"def _g() -> None: ...",
			"class _H: ...",
		].join("\n")
		expect(publicNames(source)).toEqual(["A", "b", "c", "D", "E"])
	})
})
